struct RootRec {
    /// The root allomorph's own registry id — keyed by `crate::precision`'s ENVIRONMENT-family owner-side gate.
    id: AllomorphId,
    morpheme: MorphemeId,
    category: FsId,
    /// Every accepted spelling (`surface_variants`), each emitted as its own lexc entry line sharing this morpheme's tag symbol. Empty when `pattern_regex_body` is `Some` (the regex entry represents the whole language instead).
    variants: Vec<String>,
    /// Every accepted spelling with the first segment removed (`stripped_variants`); used only by a roots lexicon's `Stripped` sibling, empty when there is no phonology or nothing to strip.
    stripped: Vec<String>,
    /// True iff the owning entry has exactly one allomorph and it is `is_bound` — compile-time-provable dead weight for a bare-root candidate. Callers must omit such a `RootRec` from the `"#"`-continuation bare-root write only; every other continuation still offers it.
    never_valid_bare: bool,
    /// `Some(pattern_shape_regex_body(...))` for a root whose shape `pattern_variants` reports `VariantLimit::Unbounded` for -- written as one `< regex >` lexc entry (`write_pattern_root_entry`) instead of an enumerated `variants` list.
    pattern_regex_body: Option<String>,
}

fn uncovered_role_code(role: Role) -> GrammarHealthCode {
    match role {
        // A plain prefix/suffix reaches this gap only when its rule's assigned zone cannot route it.
        Role::Prefix | Role::Suffix | Role::CircumfixPrefix | Role::CircumfixSuffix => {
            GrammarHealthCode::FstCircumfixNoRoute
        }
        Role::Reduplication => GrammarHealthCode::FstReduplicationNoRoute,
        Role::None | Role::Infix | Role::Process => GrammarHealthCode::FstProcessNotEmittable,
    }
}

fn rule_gap(rule: MRuleId, code: GrammarHealthCode) -> EmissionHealth {
    EmissionHealth::Grammar(EmissionGrammarFinding {
        code,
        subject: EmissionSubject::MorphRule(rule),
    })
}

fn affix_spelling_gap(rule: MRuleId, limit: VariantLimit) -> EmissionHealth {
    match limit {
        VariantLimit::Unbounded => rule_gap(rule, GrammarHealthCode::FstProcessNotEmittable),
        VariantLimit::BytesExhausted { bytes } => EmissionHealth::Budget {
            value: bytes,
            limit: REP_VARIANT_BYTE_BUDGET,
        },
        VariantLimit::Complete { .. } => {
            unreachable!("only incomplete enumeration reaches this branch")
        }
    }
}

#[allow(clippy::too_many_arguments)]
fn collect_roots(
    g: &Grammar,
    uncovered: &mut Vec<UncoveredItem>,
    counts: &mut EmitCounts,
    phon: Option<&PhonologyProbe>,
    cache: &RuleCache,
    morpher: Option<&Morpher>,
    allowed_entries: Option<&HashSet<LexEntryId>>,
) -> Vec<RootRec> {
    let mut roots = Vec::new();
    // Stratum order then entry order, mirroring trie.rs's own roots collection — deterministic Vec walks only.
    for sd in &g.strata {
        // Resolved fresh per stratum from `sd.table`, never a caller-supplied constant table: a multi-table grammar's earlier-stratum char-def ids can be out of bounds against a later, shorter table, which panics rather than refuses.
        let stratum_table = &g.char_tables[sd.table.0 as usize];
        for &entry_id in &sd.entries {
            // `allowed_entries`: every existing caller passes `None` (unfiltered); a skipped entry belongs to a different group's lexicon, not a coverage gap.
            if let Some(allowed) = allowed_entries {
                if !allowed.contains(&entry_id) {
                    continue;
                }
            }
            let entry = &g.entries[entry_id.0 as usize];
            let morpheme_name = g
                .morphemes
                .get(entry.morpheme.0 as usize)
                .map(|m| m.xml_key.as_str())
                .unwrap_or("?");
            for (allo_idx, allo) in entry.allomorphs.iter().enumerate() {
                let label = format!(
                    "entry{}(morpheme={morpheme_name})#allo{allo_idx}",
                    entry_id.0
                );
                // Routes every root uniformly through the Shape-based `pattern_variants` path rather than re-segmenting literal text: a mandatory (non-optional) `[ClassName]` node doesn't set `is_pattern`, but its literal text (e.g. `"b[Vowel]t"`) still can't re-segment, so text-based re-segmentation alone would miss it.
                let (variants, limit) = pattern_variants(stratum_table, &allo.shape.shape);
                // Unbounded shapes route to a regex entry instead of an enumerated list, scoped to allomorphs with no `<RequiredEnvironments>` (`crate::precision`'s owner-require flags need a literal surface, which an unbounded pattern has none of).
                let pattern_regex_body = (limit == VariantLimit::Unbounded
                    && allo.environments.is_empty())
                .then(|| pattern_shape_regex_body(stratum_table, &allo.shape.shape));
                // Only an incomplete, UNREPRESENTED set is an uncovered item; breadth alone is its own advisory kind below.
                if limit.drops_spellings() && pattern_regex_body.is_none() {
                    uncovered.push(UncoveredItem {
                        grammar_health: match limit {
                            VariantLimit::Unbounded => {
                                EmissionHealth::Grammar(EmissionGrammarFinding {
                                    code: GrammarHealthCode::FstPatternRootShape,
                                    subject: EmissionSubject::LexicalEntry(entry_id),
                                })
                            }
                            VariantLimit::BytesExhausted { bytes } => EmissionHealth::Budget {
                                value: bytes,
                                limit: REP_VARIANT_BYTE_BUDGET,
                            },
                            VariantLimit::Complete { .. } => {
                                unreachable!("only incomplete enumeration reaches this branch")
                            }
                        },
                        kind: "rep-variant-overflow".to_string(),
                        id: label.clone(),
                        reason: format!("root shape {:?}: {}", allo.shape.text, limit.describe()),
                    });
                } else if limit == (VariantLimit::Complete { warn: true }) {
                    uncovered.push(UncoveredItem {
                        grammar_health: EmissionHealth::Advisory,
                        kind: "rep-variant-breadth".to_string(),
                        id: label.clone(),
                        reason: format!(
                            "root shape {:?}: {} -- advisory only, every spelling is emitted",
                            allo.shape.text,
                            limit.describe()
                        ),
                    });
                }
                if pattern_regex_body.is_none() && variants.is_empty() {
                    uncovered.push(UncoveredItem {
                        grammar_health: EmissionHealth::Grammar(EmissionGrammarFinding {
                            code: if allo.is_pattern {
                                GrammarHealthCode::FstPatternRootShape
                            } else {
                                GrammarHealthCode::FstShapeNotInSurfaceTable
                            },
                            subject: EmissionSubject::LexicalEntry(entry_id),
                        }),
                        kind: if allo.is_pattern {
                            "pattern-allomorph".to_string()
                        } else {
                            "unsegmentable-root".to_string()
                        },
                        id: label,
                        reason: format!(
                            "root shape {:?} produced no concrete spelling at all",
                            allo.shape.text
                        ),
                    });
                    counts.allomorphs_skipped += 1;
                    continue;
                }
                // Stripped spellings are only consumed when `phon` is `Some`; pattern allomorphs never get one — no reference grammar needs a stripped pattern root.
                let stripped = if allo.is_pattern {
                    Vec::new()
                } else {
                    phon.and_then(|_| stripped_variants(stratum_table, &allo.shape.text))
                        .map(|(v, _)| v)
                        .unwrap_or_default()
                };
                let mut variants = variants;
                let feat_shape = (!allo.is_pattern && pattern_regex_body.is_none())
                    .then(|| {
                        pg_rules::shape_feat::segment_with_features(
                            g,
                            stratum_table,
                            &allo.shape.text,
                        )
                        .ok()
                    })
                    .flatten();
                // Bare-root phonology: unions in the root's real post-cascade surface, tried via `generate_words` first since `probe_surface` is POS-blind and gets a same-stratum, POS-scoped rule wrong on a bare root.
                // See docs/research/pg-foma-emit-design-notes.md for the empirical counter-example.
                if phon.is_some() {
                    if let Some(feat_shape) = &feat_shape {
                        // `.find(!empty)`, not `.next()`: an empty `generate_words` answer must still fall through to `probe_surface`.
                        let extra = morpher
                            .and_then(|m| {
                                m.generate_words(entry_id, &[], FeatureStruct::EMPTY)
                                    .into_iter()
                                    .find(|s| !s.is_empty())
                            })
                            .or_else(|| probe_surface(g, surface_table(g), feat_shape, cache));
                        if let Some(s) = extra {
                            if !s.is_empty() && !variants.contains(&s) {
                                variants.push(s);
                            }
                        }
                    }
                }
                // Cross-table respelling, rule or no rule; the characterizer calls the same function, so the observed construct and the emitted spelling cannot drift.
                if feat_shape.is_some() {
                    if let Some(s) =
                        cross_table_root_surface(g, stratum_table, &allo.shape.text, cache)
                    {
                        if !variants.contains(&s) {
                            variants.push(s);
                        }
                    }
                }
                // A regex-routed root's whole language is already represented in `pattern_regex_body`; the literal (truncated) `variants` list would only add redundant, harmless-but-noisy entries, so it is dropped here.
                if pattern_regex_body.is_some() {
                    variants = Vec::new();
                }
                roots.push(RootRec {
                    id: allo.id,
                    morpheme: entry.morpheme,
                    category: entry.syn_fs,
                    variants,
                    stripped,
                    never_valid_bare: entry.allomorphs.len() == 1 && allo.is_bound,
                    pattern_regex_body,
                });
                counts.allomorphs_emitted += 1;
            }
        }
    }
    roots
}

/// Filters `all_roots` down to the subset safe to offer on the bare (`"#"`-continuation) `Root` lexicon; every other call site keeps using the full, unfiltered set, since a word with any other morph attached is untouched by the bound-root gate this targets. Defensive floor: if every root would be pruned, backs off to the unfiltered set rather than leave no continuation at all — only ever a superset, never narrower than proven safe.
fn bare_admissible_roots<'a>(
    all_roots: &[&'a RootRec],
    counts: &mut EmitCounts,
) -> Vec<&'a RootRec> {
    if !all_roots.is_empty() && all_roots.iter().all(|r| r.never_valid_bare) {
        return all_roots.to_vec();
    }
    let mut out = Vec::with_capacity(all_roots.len());
    for &r in all_roots {
        if r.never_valid_bare {
            counts.bare_root_arcs_pruned += r.variants.len();
            continue;
        }
        out.push(r);
    }
    out
}

// --- Compounding license gate ---------------------------------------------------------------------

/// The two license-gated lexical-entry subsets the `Gate` partitions a reified `Plan`'s
/// `Union(Gate(head-trie) x Gate(non_head-trie))`
/// node would author for `compounding.non-recursive`. Computed directly against `Grammar` here
/// (rather than authored as real `crate::plan::PlanNodeKind::Gate` nodes) because
/// this crate's lexc emitters consult `Grammar` directly rather than a reified
/// `Plan` — this is the concrete stand-in the emitter itself consults instead of a real `Gate`
/// node.
pub(crate) struct CompoundLicense {
    /// Entries licensed to serve as a compound's HEAD stem by at least one `CompoundingRuleDef` in
    /// the grammar.
    pub(crate) head_eligible: HashSet<LexEntryId>,
    /// Entries licensed to serve as a compound's NON-HEAD ("extra root") stem by at least one
    /// `CompoundingRuleDef` in the grammar.
    pub(crate) non_head_eligible: HashSet<LexEntryId>,
}

/// Computes `CompoundLicense` for `g`, or `None` if `g` declares no `CompoundingRuleDef` at all
/// (the overwhelmingly common case — this function, and every call site consuming its result, is a
/// pure no-op for a grammar that never uses compounding).
///
/// **The (un)group-awareness contract (load-bearing — never reverse these):**
/// - The three RULE-level restriction fields (`head_prod_restrictions_mpr`,
///   `non_head_prod_restrictions_mpr`; `output_prod_restrictions_mpr` is confirm-only, see below)
///   are tested with `pg_grammar::model::MprSet::compound_match` — group-UNAWARE, mirroring C#'s
///   `CompoundMprFeaturesMatch`, the ONLY semantics `pg_rules::morph::synth_compound`/
///   `resolve_non_head_roots` ever apply to these two fields (`morph.rs:2834,2938,3329,3357`).
/// - Each SUBRULE's `required_mpr`/`excluded_mpr` is tested with `Grammar::mpr_group_ok` —
///   group-AWARE (`morph.rs:2842,2955`). Using `compound_match` here instead would apply a LOOSER
///   test than confirm does (harmless for propose's over-approximation, but not what confirm
///   verifies against); using the group-aware helper on the RULE-level fields instead (the
///   opposite mistake) would apply a STRICTER test than C# and confirm actually use there, a
///   genuine under-propose/recall-loss bug. This function follows
///   the contract exactly, in the direction that matches `pg_rules::morph` line for line.
///
/// **Head-subrule union, not per-subrule partitions (a documented simplification, not a precision
/// loss):** `synth_compound`'s own gate order tests EVERY subrule's `required_mpr`/`excluded_mpr`
/// against the SAME `word.mpr` (the head's own mpr) before trying that subrule's pattern match — so
/// an entry is head-eligible under rule `r` if it clears `r`'s rule-level gate AND clears AT LEAST
/// ONE subrule's gate. Keeping N separate per-subrule head partitions and unioning their CROSS
/// PRODUCTS with the (subrule-independent) non-head set afterward would be provably equivalent as an
/// upper bound (`∪_sr (H_sr x N) == (∪_sr H_sr) x N` for a fixed `N`) — this function computes the
/// flattened right-hand side directly, a safe simplification (still a superset), not a narrower one.
///
/// **The subrule gate is NEVER applied to the non-head side**: confirm's own
/// `resolve_non_head_roots` tests only `rule.non_head_prod_restrictions_mpr.compound_match`, never
/// any subrule's `required_mpr`/`excluded_mpr`, against a non-head candidate — applying it here would
/// silently narrow past what confirm accepts (an under-propose bug), so this function does not.
///
/// **Grammar-scoped, not per-rule** (mirrors the pre-existing `has_compounding_rules: bool` grain
/// this module's "bounded compound loop" already uses — module doc, "Bounded compound loop"): an
/// entry is admitted if ANY `CompoundingRuleDef` in the grammar licenses it. Union across rules is
/// still a safe superset of any one rule's own exact requirement, and matches the granularity the
/// existing lexc sections (`TLCmp`/`G{gi}Cmp`, shared across every compounding rule) already use.
///
/// **Left to confirm, deliberately** (only language-preserving/widening operations belong in
/// propose): `head_required_syn_fs`/`non_head_required_syn_fs` (syntactic-FS
/// unification), `output_prod_restrictions_mpr`, `out_syn_fs`, `obligatory_features`, and the exact
/// `head_lhs`/`non_head_lhs` pattern match itself. None of those narrow this function's result.
pub(crate) fn compound_license(g: &Grammar) -> Option<CompoundLicense> {
    let mut head_eligible: HashSet<LexEntryId> = HashSet::new();
    let mut non_head_eligible: HashSet<LexEntryId> = HashSet::new();
    let mut any_rule = false;
    for mrule in &g.mrules {
        let MorphRuleDef::Compounding(rule) = mrule else {
            continue;
        };
        any_rule = true;
        for (i, entry) in g.entries.iter().enumerate() {
            let id = LexEntryId(i as u32);
            if rule.head_prod_restrictions_mpr.compound_match(entry.mpr)
                && (rule.subrules.is_empty()
                    || rule
                        .subrules
                        .iter()
                        .any(|sr| g.mpr_group_ok(sr.required_mpr, sr.excluded_mpr, entry.mpr)))
            {
                head_eligible.insert(id);
            }
            if rule
                .non_head_prod_restrictions_mpr
                .compound_match(entry.mpr)
            {
                non_head_eligible.insert(id);
            }
        }
    }
    if !any_rule {
        return None;
    }
    Some(CompoundLicense {
        head_eligible,
        non_head_eligible,
    })
}

/// Resolves a `RootRec`'s owning `LexEntryId` via `g.allomorph_owners`; `None` only if the registry doesn't classify this id as a root — defensive, not expected to fire in practice.
fn root_lex_entry(g: &Grammar, id: AllomorphId) -> Option<LexEntryId> {
    match g.allomorph_owners.get(id.0 as usize)? {
        AllomorphOwner::Root(le, _) => Some(*le),
        AllomorphOwner::Affix(_, _) => None,
    }
}

/// Filters `roots` down to the entries `eligible` licenses; narrows the compound head/non-head continuation sections from `all_roots` to `compound_license`'s subsets.
fn filter_roots_by_license<'a>(
    g: &Grammar,
    roots: &[&'a RootRec],
    eligible: &HashSet<LexEntryId>,
) -> Vec<&'a RootRec> {
    roots
        .iter()
        .copied()
        .filter(|r| root_lex_entry(g, r.id).is_some_and(|le| eligible.contains(&le)))
        .collect()
}

// --- Bounded compound loop: the shared depth-budgeted chain -------------------------------------

/// The depth-budgeted extension of the "bounded compound loop" (module doc) -- a chain of `levels`
/// license-gated non-head-root LEVELS under `base` (e.g. `"TLCmp"`/`"G3Cmp"`), each with its own
/// optional prefix-derivation hop (a prefix on the compound's non-head span, e.g.
/// `lexbedom`/`silamanuk` -- see module doc's "Bounded compound loop" section), realizing every compound
/// depth from 2 stems (head + 1 extra root) up to `1 + levels` stems (head + `levels` extra roots)
/// as accepted paths through ONE compiled network, not `levels` separately-sized copies --
/// `compound_license`'s own license-gated non-head set is reused, UNCHANGED, at every level (this
/// adds depth, never new precision, matching every other over-approximating simplification the
/// module doc's "Deliberate supersets" section already accepts).
///
/// **Byte-identical to the pre-existing single-level construction when `levels == 1`**: level 1 reuses the EXACT
/// pre-existing names (`{base}`, `{base}Pfx`, `{base}RootsStripped`) and, since `levels == 1`
/// makes it also the LAST level, its root entries continue DIRECTLY to `exit` -- no dispatcher
/// lexicon is ever written for the single-level case. Level `k >= 2` (only emitted when
/// `levels >= 2`, a genuinely recursive/self-feeding `CompoundingRuleDef`) uses
/// `{base}{k}`/`{base}{k}Pfx`/`{base}{k}Roots`; a level's root entries continue to `exit` directly
/// when it is the LAST level, or to a small `{base}{k}Next` dispatcher (bare-redirecting to BOTH
/// `exit` and level `k+1`'s own entry) otherwise -- so every intermediate depth from 2 up to
/// `1 + levels` stems is a real accepted path, not just the maximum.
///
/// Growth is LINEAR in `levels` (one more `{Pfx,Roots,Next}` triple per level, each sized by the
/// license-gated non-head root count), never exponential in emitted TEXT size --
/// `crate::construction::DEFAULT_COMPOUND_DEPTH` is the containment for the one input that can
/// still make `levels` itself unreasonably large.
///
/// Generic over the root record type `R` and the emitter-state type `C`, with the prefix hop and
/// the root-entry writers supplied by the caller as closures, so the caller's own `width` and
/// tag-writing convention stay out of this function. `write_stripped_root_entries` is only
/// invoked when `emit_stripped` (the caller's `phon.is_some()`) is true.
///
/// `write_prefix_hop(out, pfx_base, roots_name, counts, ctx)` must define the lexicon
/// **`{pfx_base}0`** -- the name this function has already bare-redirected the level's entry lexicon
/// to before calling it -- and every path through it must exit to `roots_name`.
/// `build_deriv_chain` satisfies this by construction (it always defines `{prefix}0` and returns
/// that name).
///
/// Shared shape of `build_compound_chain`'s `write_root_entries`/`write_stripped_root_entries`
/// callback parameters (own doc above): each emitter's own local closure for writing one root
/// group's lexc entries, capturing that emitter's `width`/tag-writing convention.
pub(crate) type RootEntryWriter<'a, R, C> =
    &'a dyn Fn(&mut String, &[&R], &str, &mut EmitCounts, &mut C);

/// Shared shape of `build_compound_chain`'s per-level prefix-derivation hop (own doc above):
/// `FnMut` rather than `Fn` because this module's own callers capture `&mut uncovered` in it.
pub(crate) type CompoundPrefixHop<'a, C> =
    &'a mut dyn FnMut(&mut String, &str, &str, &mut EmitCounts, &mut C);

#[allow(clippy::too_many_arguments)]
pub(crate) fn build_compound_chain<R, C>(
    out: &mut String,
    base: &str,
    levels: usize,
    non_head_roots: &[&R],
    all_roots: &[&R],
    exit: &str,
    counts: &mut EmitCounts,
    ctx: &mut C,
    emit_stripped: bool,
    write_prefix_hop: CompoundPrefixHop<'_, C>,
    write_root_entries: RootEntryWriter<'_, R, C>,
    write_stripped_root_entries: RootEntryWriter<'_, R, C>,
) {
    let levels = levels.max(1);
    for k in 1..=levels {
        let entry_name = if k == 1 {
            base.to_string()
        } else {
            format!("{base}{k}")
        };
        let pfx_base = if k == 1 {
            format!("{base}Pfx")
        } else {
            format!("{base}{k}Pfx")
        };
        let roots_name = if k == 1 {
            format!("{base}Roots")
        } else {
            format!("{base}{k}Roots")
        };
        let continuation = if k == levels {
            exit.to_string()
        } else {
            format!("{base}{k}Next")
        };

        write_lexicon_header(out, &entry_name);
        write_bare(out, &format!("{pfx_base}0"), counts);
        write_prefix_hop(out, &pfx_base, &roots_name, counts, ctx);
        write_lexicon_header(out, &roots_name);
        write_root_entries(out, non_head_roots, &continuation, counts, ctx);
        if emit_stripped {
            write_lexicon_header(out, &format!("{roots_name}Stripped"));
            write_stripped_root_entries(out, all_roots, &continuation, counts, ctx);
        }

        if k < levels {
            write_lexicon_header(out, &continuation);
            write_bare(out, exit, counts);
            write_bare(out, &format!("{base}{}", k + 1), counts);
        }
    }
}

/// Checks `compound_extra_levels` against `crate::construction::DEFAULT_COMPOUND_DEPTH` before any chain lexc text is written, shared by both emitters so the discipline never drifts; `result_large_err` is deliberate, since the `Err` IS the full `EmitResult` refusal the caller returns verbatim.
#[allow(clippy::result_large_err)]
fn compound_chain_depth_and_budget_check(
    g: &Grammar,
    uncovered: &[UncoveredItem],
    counts: &EmitCounts,
    chain_depth_cap: Option<usize>,
) -> Result<usize, EmitResult> {
    let compound_depth_bound = compound_depth_bound(g);
    let (depth, limit) = match compound_extra_levels_checked_with_cap(g, chain_depth_cap) {
        Ok(levels) => return Ok(levels),
        Err(ComposeError::ChainDepthExceeded { depth, limit, .. }) => (depth, limit),
        Err(ComposeError::CannotRepresent { reason }) => {
            unreachable!("chain depth check: {reason}")
        }
    };
    {
        let reason = format!(
            "compound chain depth ({depth} extra non-head compound-root level(s), from a computed \
             max_depth of {compound_depth_bound} total stems across this grammar's CompoundingRule(s)) \
             exceeds this path's compound chain-depth budget (limit {limit}). This grammar's \
             self-feeding compounding recursion is deeper than this construction will unroll -- raise \
             --fst-compound-depth (or HC_COMPOUND_CHAIN_DEPTH_BUDGET when the request leaves that \
             bound unset) only if you understand why this grammar's compounding \
             recursion is this deep, or fall back to another engine for this grammar. Never silently \
             truncated: an honest refusal, not a partial/unsound network."
        );
        Err(EmitResult {
            lexc_source: String::new(),
            report: EmitReport {
                uncovered: uncovered.to_vec(),
                counts: counts.clone(),
                tier: FomaTier::Unsupported { reason },
                enum_budget_exceeded: Some(EnumBudgetExceeded {
                    measure: "compound chain depth (extra non-head root levels)",
                    value: depth,
                    limit,
                }),
                closure_refusal: None,
                closure_evidence: None,
            },
        })
    }
}

/// The grammar-wide total-stem bound `crate::capability::characterize` already computed for every `CompoundingRuleDef`, defaulting to 2 (head + one non-head) for a grammar whose rules declare nothing deeper.
fn compound_depth_bound(g: &Grammar) -> usize {
    crate::capability::characterize(g)
        .compounding_details()
        .map(|d| d.max_depth)
        .max()
        .unwrap_or(2)
}

fn compound_extra_levels_checked_with_cap(
    g: &Grammar,
    chain_depth_cap: Option<usize>,
) -> Result<usize, ComposeError> {
    let compound_extra_levels = compound_depth_bound(g).saturating_sub(1).max(1);
    let budget = match chain_depth_cap {
        Some(cap) => ComposeBudget {
            chain_depth_cap: Some(crate::compose_budget::clamp_chain_depth_cap(cap)),
        },
        None => ComposeBudget::unbounded().with_chain_depth_cap(compound_chain_depth_budget()),
    };
    budget.check_chain_depth(
        compound_extra_levels,
        "compound loop (extra non-head root levels)",
    )?;
    Ok(compound_extra_levels)
}

// --- Affix entry emission (shared by slot chains and derivation layers) ---------------------------

/// What `emit_rule_allomorphs` does with one allomorph once it knows `zone_role`, shared with `eager_route_refuses_mixed_circumfix_zone` so the two cannot drift.
enum AllomorphZoneOutcome {
    Routed,
    Circumfix(Vec<(String, String)>),
    /// Owned by another assigned zone or the reduplication peeler, so absence here is not a gap.
    OwnZoneElsewhere,
    Uncovered,
}

/// The zone-fit decision `emit_rule_allomorphs` makes for one allomorph; called by both that function and `eager_route_refuses_mixed_circumfix_zone`. `mid` lets a plain Prefix/Suffix allomorph be told apart from one truly unrepresentable in any zone.
fn allomorph_zone_outcome(
    g: &Grammar,
    mid: MRuleId,
    allo: &AffixAllomorphDef,
    zone_role: Role,
) -> AllomorphZoneOutcome {
    let role = classify_affix(&allo.rhs);
    if role == zone_role || role == Role::None {
        return AllomorphZoneOutcome::Routed;
    }
    if role == Role::Reduplication && reduplication_rule_is_peelable(g, mid) {
        return AllomorphZoneOutcome::OwnZoneElsewhere;
    }
    if role == Role::CircumfixPrefix && matches!(zone_role, Role::Prefix | Role::Suffix) {
        if let Some(texts) = circumfix_surface_texts(g, allo) {
            return AllomorphZoneOutcome::Circumfix(texts);
        }
    }
    // A circumfix sibling widens the whole rule into both zones, so a plain Prefix/Suffix allomorph's own zone is guaranteed present too.
    if matches!(role, Role::Prefix | Role::Suffix) && any_allomorph_is_circumfix_prefix(g, mid) {
        return AllomorphZoneOutcome::OwnZoneElsewhere;
    }
    AllomorphZoneOutcome::Uncovered
}

/// Emits every emittable allomorph of `mid` as one tagged entry into `next`, requiring role `zone_role` (or `None`, a zero morph legal in either zone). A consuming ordinary Realizational prefix/suffix may target `repeat_target` so the FST represents its intentionally unbounded application count as a regular loop. Empty and structural spellings never loop. When `phon` is `Some`, also unions in `PhonologyProbe::variants`' spellings, and `junction_target` (if given) reroutes deletion-junction hits to a separate lexicon at the root-adjacent final derivation level.
#[allow(clippy::too_many_arguments)]
fn emit_rule_allomorphs(
    out: &mut String,
    g: &Grammar,
    table: &CharDefTable,
    mid: MRuleId,
    zone_role: Role,
    width: usize,
    next: &str,
    repeat_target: Option<&str>,
    uncovered: &mut Vec<UncoveredItem>,
    counts: &mut EmitCounts,
    phon: Option<&PhonologyProbe>,
    junction_target: Option<&str>,
    pk: &mut PrecisionEmit,
) {
    let morpheme = owning_morpheme(g, mid);
    let tag_lexc = tags::morph_tag_lexc(morpheme, width);
    for (allo_idx, allo) in allomorphs_of(g, mid).iter().enumerate() {
        let label = format!("mrule{}#allo{allo_idx}", mid.0);
        if has_unemittable_action(&allo.rhs) {
            uncovered.push(UncoveredItem {
                grammar_health: rule_gap(mid, GrammarHealthCode::FstProcessNotEmittable),
                kind: "process-morph".to_string(),
                id: label,
                reason: "Modify/InsertContext action has no literal text to emit (v1)".to_string(),
            });
            counts.allomorphs_skipped += 1;
            continue;
        }
        let role = classify_affix(&allo.rhs);
        // Only the Prefix-zone occurrence carries the tag (the oracle always orders a circumfix's morpheme before the root); the Suffix-zone occurrence is untagged literal text, or the morpheme would be double-counted.
        match allomorph_zone_outcome(g, mid, allo, zone_role) {
            AllomorphZoneOutcome::Routed => {}
            AllomorphZoneOutcome::Circumfix(texts) => {
                let emitted = texts.len();
                match zone_role {
                    Role::Prefix => {
                        for (prefix, _) in texts {
                            write_tag_entry(out, &tag_lexc, &prefix, next, counts, pk, Some(allo.id));
                        }
                    }
                    Role::Suffix => {
                        for (_, suffix) in texts {
                            write_untagged_entry(out, &suffix, next, counts);
                        }
                    }
                    _ => unreachable!(
                        "allomorph_zone_outcome only returns Circumfix for Role::Prefix/Role::Suffix zones"
                    ),
                }
                counts.allomorphs_emitted += emitted;
                continue;
            }
            AllomorphZoneOutcome::OwnZoneElsewhere => continue,
            AllomorphZoneOutcome::Uncovered => {
                uncovered.push(UncoveredItem {
                    grammar_health: rule_gap(mid, uncovered_role_code(role)),
                    kind: role.label().to_string(),
                    id: label,
                    reason: format!(
                        "allomorph classifies as {role:?} but its rule is referenced in a {zone_role:?} position"
                    ),
                });
                counts.allomorphs_skipped += 1;
                continue;
            }
        }
        let owner = Some(allo.id);
        let can_repeat = repeat_target.is_some()
            && matches!(g.mrules[mid.0 as usize], MorphRuleDef::Realizational(_))
            && matches!(role, Role::Prefix | Role::Suffix)
            && role == zone_role
            && !rhs_drops_lhs_material(allo);
        let target_for = |spelling: &str| {
            // A boundary-kept spelling (surface_variants_boundary_optional) can be non-empty text that still cleans up to nothing; treat it like the empty spelling this self-loop gate already guards against.
            let cleans_to_nothing = spelling.is_empty()
                || surface_variants(table, spelling)
                    .is_some_and(|(variants, _)| variants.iter().all(String::is_empty));
            if can_repeat && !cleans_to_nothing {
                repeat_target.unwrap_or(next)
            } else {
                next
            }
        };
        match insert_action_texts(&allo.rhs) {
            InsertText::None => {
                write_tag_entry(out, &tag_lexc, "", next, counts, pk, owner);
                counts.allomorphs_emitted += 1;
            }
            InsertText::Text { texts } => {
                let mut emitted_any = false;
                match surface_variants_concat_boundary_optional(table, &texts) {
                    Some((variants, limit)) => {
                        if limit.drops_spellings() {
                            uncovered.push(UncoveredItem {
                                grammar_health: affix_spelling_gap(mid, limit),
                                kind: "rep-variant-overflow".to_string(),
                                id: label.clone(),
                                reason: format!(
                                    "affix insert text {texts:?}: {}",
                                    limit.describe()
                                ),
                            });
                        }
                        for surface in &variants {
                            write_tag_entry(
                                out,
                                &tag_lexc,
                                surface,
                                target_for(surface),
                                counts,
                                pk,
                                owner,
                            );
                        }
                        emitted_any = true;
                    }
                    None => {
                        uncovered.push(UncoveredItem {
                            grammar_health: rule_gap(mid, GrammarHealthCode::FstShapeNotInSurfaceTable),
                            kind: "unsegmentable-affix".to_string(),
                            id: label.clone(),
                            reason: format!(
                                "affix insert text {texts:?} does not re-segment against the surface char-def table"
                            ),
                        });
                    }
                }
                // Unions in every probe-derived surface spelling, and where the caller says this level is root-adjacent, routes deletion-junction spellings to the stripped-roots continuation instead; pieces are joined in document order first since the probe takes one literal string.
                if let Some(probe) = phon {
                    let joined: String = texts.concat();
                    let deletion_junctions = junction_target
                        .map(|_| probe.deletion_junctions(&joined))
                        .unwrap_or_default();
                    for surface in probe.variants(&joined) {
                        let target = if deletion_junctions.contains(&surface) {
                            next
                        } else {
                            target_for(&surface)
                        };
                        write_tag_entry(out, &tag_lexc, &surface, target, counts, pk, owner);
                        emitted_any = true;
                    }
                    if let Some(target) = junction_target {
                        for surface in deletion_junctions {
                            write_tag_entry(out, &tag_lexc, &surface, target, counts, pk, owner);
                            emitted_any = true;
                        }
                    }
                }
                if emitted_any {
                    counts.allomorphs_emitted += 1;
                } else {
                    counts.allomorphs_skipped += 1;
                }
            }
        }
    }
}

// --- Derivation layer chain (trie.rs::build_derivation_layer) -------------------------------------

/// Chain depth: the sum of `max_apps` over non-realizational rules (a realizational rule counts one), never below `DERIV_DEPTH_MIN`.
pub fn deriv_chain_depth(g: &Grammar, rules: &[MRuleId]) -> usize {
    let sum: usize = rules
        .iter()
        .map(|&mid| match &g.mrules[mid.0 as usize] {
            MorphRuleDef::Realizational(_) => 1,
            rule => usize::from(rule.max_apps().max(1)),
        })
        .sum();
    sum.max(DERIV_DEPTH_MIN)
}

/// Emits a chain of optional derivation layers ending at `exit`, always defining `{prefix}0`.
#[allow(clippy::too_many_arguments)]
fn build_deriv_chain(
    out: &mut String,
    g: &Grammar,
    table: &CharDefTable,
    prefix: &str,
    zone_role: Role,
    rules: &[MRuleId],
    width: usize,
    exit: &str,
    uncovered: &mut Vec<UncoveredItem>,
    counts: &mut EmitCounts,
    phon: Option<&PhonologyProbe>,
    exit_is_roots: bool,
    pk: &mut PrecisionEmit,
) -> String {
    let entry_name = format!("{prefix}0");
    if rules.is_empty() {
        write_lexicon_header(out, &entry_name);
        write_bare(out, exit, counts);
        return entry_name;
    }
    let junction_target = if zone_role == Role::Prefix && exit_is_roots && phon.is_some() {
        Some(format!("{exit}Stripped"))
    } else {
        None
    };

    let depth = deriv_chain_depth(g, rules);

    for level in 0..depth {
        let name = format!("{prefix}{level}");
        write_lexicon_header(out, &name);
        let is_final = level + 1 == depth;
        let next = if is_final {
            exit.to_string()
        } else {
            format!("{prefix}{}", level + 1)
        };
        // The whole level is optional (mirrors trie's epsilon skip before the per-rule arcs) — identical for both strategies.
        write_bare(out, &next, counts);
        let junction_here = if is_final {
            junction_target.as_deref()
        } else {
            None
        };
        // Every level offers every rule.
        for &mid in rules {
            emit_rule_allomorphs(
                out,
                g,
                table,
                mid,
                zone_role,
                width,
                &next,
                Some(&name),
                uncovered,
                counts,
                phon,
                junction_here,
                pk,
            );
        }
    }
    entry_name
}

// --- Slot chains (trie.rs::classify_template + append_slots) --------------------------------------

/// `trie.rs::slot_op`: a slot's zone is that of its first Prefix/Suffix-classified rule; a slot with only zero-morph rules counts as Suffix, and a slot with only circumfix-shaped rules counts as Prefix (the zone `emit_rule_allomorphs` tags).
fn slot_role(g: &Grammar, slot: &SlotDef) -> Role {
    let mut has_zero = false;
    for &mid in &slot.rules {
        let role = rule_role(g, mid);
        if role == Role::Prefix || role == Role::Suffix {
            return role;
        }
        if any_allomorph_is_circumfix_prefix(g, mid) {
            return Role::Prefix;
        }
        if role == Role::None {
            has_zero = true;
        }
    }
    if has_zero {
        Role::Suffix
    } else {
        Role::None
    }
}

/// `trie.rs::classify_template`: splits a template's slots into prefix (reversed to surface order) and suffix lists, routing any exotic-op slot rule to `uncovered`.
fn classify_template<'g>(
    g: &'g Grammar,
    template: &'g pg_grammar::model::AffixTemplateDef,
    uncovered: &mut Vec<UncoveredItem>,
) -> (Vec<&'g SlotDef>, Vec<&'g SlotDef>) {
    let mut prefix = Vec::new();
    let mut suffix = Vec::new();
    for slot in &template.slots {
        match slot_role(g, slot) {
            Role::Prefix => prefix.push(slot),
            Role::Suffix => suffix.push(slot),
            _ => {
                for &mid in &slot.rules {
                    let role = rule_role(g, mid);
                    if role != Role::Prefix && role != Role::Suffix && role != Role::None {
                        uncovered.push(UncoveredItem {
                            grammar_health: rule_gap(mid, uncovered_role_code(role)),
                            kind: role.label().to_string(),
                            id: format!("mrule{}", mid.0),
                            reason: format!(
                                "template slot rule's primary allomorph classifies as {role:?}; slot dropped (v1, mirrors trie.rs classify_template)"
                            ),
                        });
                    }
                }
            }
        }
    }
    prefix.reverse();
    (prefix, suffix)
}

/// `trie.rs::append_slots`: emits one lexicon per slot in order, each offering every zone-fitting rule allomorph once with an epsilon skip if optional; `phon` unions into every spelling, but there is no junction routing since a slot chain's exit always lands on further derivation, never a roots lexicon directly.
#[allow(clippy::too_many_arguments)]
fn build_slot_chain(
    out: &mut String,
    g: &Grammar,
    table: &CharDefTable,
    prefix: &str,
    slots: &[&SlotDef],
    zone_role: Role,
    template_category: FsId,
    width: usize,
    exit: &str,
    uncovered: &mut Vec<UncoveredItem>,
    counts: &mut EmitCounts,
    phon: Option<&PhonologyProbe>,
    pk: &mut PrecisionEmit,
) -> String {
    let entry_name = format!("{prefix}0");
    if slots.is_empty() {
        write_lexicon_header(out, &entry_name);
        write_bare(out, exit, counts);
        return entry_name;
    }
    for (si, slot) in slots.iter().enumerate() {
        let name = format!("{prefix}{si}");
        write_lexicon_header(out, &name);
        let next = if si + 1 == slots.len() {
            exit.to_string()
        } else {
            format!("{prefix}{}", si + 1)
        };
        if slot.optional {
            write_bare(out, &next, counts);
        }
        for &mid in &slot.rules {
            // Mirrors trie.rs's append_slots category gate: skip a slot rule whose requirement can't unify with the template's category.
            let req = required_category(g, mid);
            let req_fs = g.fs_interner.get(req);
            if !req_fs.is_empty() {
                let tmpl_fs = g.fs_interner.get(template_category);
                if !is_unifiable(tmpl_fs, req_fs) {
                    continue;
                }
            }
            emit_rule_allomorphs(
                out, g, table, mid, zone_role, width, &next, None, uncovered, counts, phon, None,
                pk,
            );
        }
    }
    entry_name
}

// Structural composites replay `pg_rules::morph::synthesize` for rules `crate::preexpand` cannot represent (truncation, and probe-refused rules), reusing its `Composites`/`CompositeExit` wiring.

/// A live successor at this resource boundary refuses the artifact instead of truncating it.
const DEFAULT_STRUCTURAL_CLOSURE_DEPTH_BUDGET: usize =
    crate::preexpand::DEFAULT_CLOSURE_DEPTH_BUDGET;

pub use crate::construction::StructuralClosureLimits;

#[derive(Default, Clone, Debug)]
struct StructuralBudgetState {
    work: usize,
    retained_bytes: usize,
    nodes: usize,
    commutations: usize,
    /// Reverse-order proofs attempted (gates passed); each ends in exactly one outcome below.
    proof_attempts: usize,
    /// Failed: the reverse order is not morphotactically reachable or synthesizes nothing.
    proof_fail_no_reverse: usize,
    /// Failed: a reverse path exists but reaches a different continuation state.
    proof_fail_state: usize,
    /// Failed: a reverse path reaches the same state but a different annotated word.
    proof_fail_word: usize,
    /// Output records rejected because their (tag, surface, boundary) key was already retained.
    seen_duplicate_hits: usize,
    dedup_bytes: usize,
    refusal: Option<EnumBudgetExceeded>,
}

pub(crate) struct StructuralTrace {
    limits: StructuralClosureLimits,
    state: Mutex<StructuralBudgetState>,
    #[cfg(test)]
    canonical_order: bool,
}

impl StructuralTrace {
    fn new(limits: StructuralClosureLimits) -> Self {
        Self {
            limits,
            state: Mutex::new(StructuralBudgetState::default()),
            #[cfg(test)]
            canonical_order: true,
        }
    }

    fn charge(&self, bytes: Option<usize>) -> bool {
        let mut state = self.state.lock().expect("structural trace poisoned");
        if state.refusal.is_some() {
            return false;
        }
        let (measure, value, limit) = match bytes {
            None => (
                "HC_STRUCTURAL_CLOSURE_WORK_LIMIT",
                state.work.saturating_add(1),
                self.limits.work_limit,
            ),
            Some(bytes) => (
                "HC_STRUCTURAL_CLOSURE_BYTES_LIMIT",
                state.retained_bytes.saturating_add(bytes),
                self.limits.retained_bytes_limit,
            ),
        };
        let exceeds = match bytes {
            None => state.work >= limit,
            Some(bytes) => bytes > limit.saturating_sub(state.retained_bytes),
        };
        if exceeds {
            state.refusal = Some(EnumBudgetExceeded {
                measure,
                value,
                limit,
            });
            return false;
        }
        if bytes.is_some() {
            state.retained_bytes = value;
        } else {
            state.work = value;
        }
        true
    }

    fn bump(&self, f: impl FnOnce(&mut StructuralBudgetState)) {
        f(&mut self.state.lock().expect("structural trace poisoned"));
    }

    fn stopped(&self) -> bool {
        self.state
            .lock()
            .expect("structural trace poisoned")
            .refusal
            .is_some()
    }
}

/// True if any allomorph of `mid` classifies `Role::CircumfixPrefix`, unlike `rule_role` (allomorph 0 only).
fn any_allomorph_is_circumfix_prefix(g: &Grammar, mid: MRuleId) -> bool {
    allomorphs_of(g, mid)
        .iter()
        .any(|a| classify_affix(&a.rhs) == Role::CircumfixPrefix)
}

/// True for a rule `crate::preexpand`'s ordinary composite mechanism cannot represent: any
/// allomorph -- not just the first -- that drops real LHS material (`rhs_drops_lhs_material`)
/// while ITSELF classifying `None`/`Prefix`/`Suffix`/`Infix`, any `CircumfixPrefix` allomorph, or
/// any `Process` allomorph, or a `Reduplication` allomorph outside the peeler's statically proven
/// prefix-copy, suffix-copy, and one-separator layouts. Proven shapes stay
/// `crate::peel::ReduplicationPeeler`'s job; every other shape is synthesized structurally.
/// Per census C5, the separate dropping-material exclusion is checked per allomorph, not per rule:
/// a rule with a dropping
/// `Reduplication`-classified allomorph and a separate, non-dropping allomorph of some OTHER role
/// stays excluded on the strength of the `Reduplication` one alone (the copy-count semantics
/// genuinely differ, so that shape never earns admission by itself), while a dropping
/// `None`/`Prefix`/`Suffix`/`Infix` allomorph is admitted regardless of what any other allomorph of
/// the same rule classifies as (pinned by
/// `redup_first_allomorph_then_dropping_prefix_allomorph_structural_recall_parity`). A non-dropping
/// `Infix` allomorph stays `crate::preexpand`'s job, per the census
/// (`docs/research/circumfix-composite-precedence-census.md`, C4-C5).
///
/// `pub(crate)`: `crate::capability`'s `CircumfixStructuralCompositePredicate` calls this directly
/// so its check reads the same fact the compile path branches on, rather than re-deriving it.
pub(crate) fn is_structural_rule(g: &Grammar, mid: MRuleId) -> bool {
    if let MorphRuleDef::AffixProcess(def) = &g.mrules[mid.0 as usize] {
        if !g.fs_interner.get(def.out_syn_fs).is_empty()
            && allomorphs_of(g, mid)
                .iter()
                .all(|a| classify_affix(&a.rhs) == Role::None)
        {
            return true;
        }
    }
    // Checked unconditionally, ahead of the checks below, since it only adds cases rule_role's allomorph-0-only view would miss.
    if any_allomorph_is_circumfix_prefix(g, mid)
        || allomorphs_of(g, mid)
            .iter()
            .any(|a| has_unemittable_action(&a.rhs))
        || allomorphs_of(g, mid)
            .iter()
            .any(|a| reduplication_requires_structural(g, a))
    {
        return true;
    }
    // Admit only representable dropping allomorphs; another allomorph's role must not gate this path.
    allomorphs_of(g, mid).iter().any(|a| {
        rhs_drops_lhs_material(a)
            && matches!(
                classify_affix(&a.rhs),
                Role::None | Role::Prefix | Role::Suffix | Role::Infix
            )
    })
}

/// Whether ordinary edge emission is a recall-preserving superset for every allomorph here.
fn structural_rule_is_edge_decomposable(g: &Grammar, mid: MRuleId) -> bool {
    if g.mrules[mid.0 as usize].max_apps() != 1 {
        return false;
    }
    let allomorphs = allomorphs_of(g, mid);
    if allomorphs.is_empty() {
        return false;
    }
    let primary = rule_role(g, mid);
    let has_circumfix = any_allomorph_is_circumfix_prefix(g, mid);
    let prefix_zone =
        has_circumfix || matches!(primary, Role::Prefix | Role::None | Role::CircumfixPrefix);
    let suffix_zone = has_circumfix || matches!(primary, Role::Suffix | Role::None);
    let alphabet = SegAlphabet::new(surface_table(g));

    allomorphs.iter().all(|allomorph| {
        if has_unemittable_action(&allomorph.rhs) || rhs_drops_lhs_material(allomorph) {
            return false;
        }
        match classify_affix(&allomorph.rhs) {
            Role::Prefix => prefix_zone,
            Role::Suffix => suffix_zone,
            Role::None => prefix_zone || suffix_zone,
            Role::CircumfixPrefix => {
                circumfix_surface_texts(g, allomorph).is_some()
                    && crate::structural_allomorph::circumfix_texts(g, &alphabet, allomorph)
                        .is_some()
            }
            Role::Infix | Role::Reduplication | Role::CircumfixSuffix | Role::Process => false,
        }
    })
}

const STRUCTURAL_FS_REACHABILITY_STATE_CAP: usize = 4096;

/// Overapproximates synthesis by applying only its syntactic-feature transition.
fn abstract_syn_transition(
    g: &Grammar,
    rule: &MorphRuleDef,
    input: &FeatureStruct,
) -> Option<FeatureStruct> {
    let (required, output) = match rule {
        MorphRuleDef::AffixProcess(def) => (def.required_syn_fs, def.out_syn_fs),
        MorphRuleDef::Realizational(def) => (def.required_syn_fs, def.real_fs),
        MorphRuleDef::Compounding(def) => (def.head_required_syn_fs, def.out_syn_fs),
    };
    let unified = unify(g.fs_interner.get(required), input)?;
    Some(priority_union(&unified, g.fs_interner.get(output)))
}

fn root_can_reach_nondecomposable_structural_anchor(g: &Grammar, root_fs: &FeatureStruct) -> bool {
    let anchors: Vec<MRuleId> = (0..g.mrules.len() as u32)
        .map(MRuleId)
        .filter(|&mid| is_structural_rule(g, mid) && !structural_rule_is_edge_decomposable(g, mid))
        .collect();
    if anchors.is_empty() {
        return false;
    }

    let mut seen = HashSet::new();
    let mut pending = VecDeque::new();
    seen.insert(root_fs.clone());
    pending.push_back(root_fs.clone());

    while let Some(state) = pending.pop_front() {
        if anchors.iter().any(|mid| {
            let required = match &g.mrules[mid.0 as usize] {
                MorphRuleDef::AffixProcess(def) => def.required_syn_fs,
                MorphRuleDef::Realizational(def) => def.required_syn_fs,
                MorphRuleDef::Compounding(def) => def.head_required_syn_fs,
            };
            is_unifiable(g.fs_interner.get(required), &state)
        }) {
            return true;
        }

        for rule in &g.mrules {
            let Some(next) = abstract_syn_transition(g, rule, &state) else {
                continue;
            };
            if seen.contains(&next) {
                continue;
            }
            if seen.len() >= STRUCTURAL_FS_REACHABILITY_STATE_CAP {
                return true;
            }
            seen.insert(next.clone());
            pending.push_back(next);
        }
    }
    false
}

fn structural_candidate_rules_for_root(
    g: &Grammar,
    grammar_rules: &[MRuleId],
    root_fs: &FeatureStruct,
) -> (Vec<MRuleId>, usize) {
    if probe_would_refuse(g) {
        return (grammar_rules.to_vec(), 0);
    }
    if root_can_reach_nondecomposable_structural_anchor(g, root_fs) {
        return (grammar_rules.to_vec(), 0);
    }
    let rules: Vec<MRuleId> = grammar_rules
        .iter()
        .copied()
        .filter(|&mid| {
            is_structural_rule(g, mid) || !matches!(rule_role(g, mid), Role::Prefix | Role::Suffix)
        })
        .collect();
    let pruned = grammar_rules.len().saturating_sub(rules.len());
    (rules, pruned)
}

/// Whether `pg_rules::surface_probe::probe_synthesize` would REFUSE for ANY word synthesized in
/// this grammar — module doc, item 2. A purely STATIC, per-grammar fact (not per-word), checking
/// every rule in `g.prules` (not just ones reachable from a given stratum) regardless of whether
/// that specific rule actually fires for the shape being probed — a safe, conservative
/// over-approximation of "could this ever refuse", cheap enough to run unconditionally.
/// `probe_would_refuse_detects_epenthesis` (below) pins this against the real cascade on a
/// grammar whose epenthesis rule actually triggers it.
///
/// `pub(crate)` (widened from private, no body change): `crate::enumerate::enumerate_default`
/// mirrors this seam's decision structurally, and that module's own tests compare the enumerated
/// `Plan` against calling this REAL function directly — the correctness argument depends on both
/// sides calling the identical predicate, not a re-derivation of it.
pub(crate) fn probe_would_refuse(g: &Grammar) -> bool {
    g.prules.iter().any(|pr| match pr {
        PhonRuleDef::Metathesis(_) => true,
        PhonRuleDef::Rewrite(r) => r.lhs.nodes.is_empty(),
    })
}

/// Candidate rules for `build_structural_composites`: always `is_structural_rule`'s set. When a
/// structural anchor exists, every bounded non-Compounding morphology rule is included so an
/// anchor reached through a `Role::None` or peel-owned reduplication predecessor cannot be missed.
/// With no structural anchor, probing refusal still widens only to ordinary affix roles.
///
/// `pub(crate)`: `crate::enumerate::enumerate_default` calls this directly to decide the
/// structural-composite route's presence, the other half of the seam `probe_would_refuse`
/// documents; `plan_topology_decisions` then makes `emit_with_budget_profiled`'s own gate match it
/// by construction rather than by two independently-written call sites happening to agree.
/// The rules `build_structural_composites` claims, by grammar ordinal.
///
/// Published because an uncovered item naming one of these is an emitter OVER-REPORT rather than a
/// capability gap: the standalone-derivational loop reports a role it cannot route, while structural
/// synthesis covers that same rule through `pg_rules::morph::synthesize`. Telling the two apart is
/// what decides whether a refusal belongs in the envelope or the emitter.
#[cfg(feature = "test-support")]
pub fn structurally_routed_rule_ordinals(g: &Grammar) -> Vec<u32> {
    structural_candidate_rules(g)
        .into_iter()
        .map(|mid| mid.0)
        .collect()
}

pub(crate) fn structural_candidate_rules(g: &Grammar) -> Vec<MRuleId> {
    let probe_refuses = probe_would_refuse(g);
    let has_structural =
        (0..g.mrules.len() as u32).any(|index| is_structural_rule(g, MRuleId(index)));
    let every_structural_anchor_is_edge_decomposable = has_structural
        && (0..g.mrules.len() as u32)
            .map(MRuleId)
            .filter(|&mid| is_structural_rule(g, mid))
            .all(|mid| structural_rule_is_edge_decomposable(g, mid));
    (0..g.mrules.len() as u32)
        .map(MRuleId)
        .filter(|&mid| {
            if matches!(g.mrules[mid.0 as usize], MorphRuleDef::Compounding(_)) {
                return false;
            }
            if is_structural_rule(g, mid) {
                true
            } else if probe_refuses {
                matches!(rule_role(g, mid), Role::Prefix | Role::Suffix | Role::Infix)
            } else if has_structural {
                !(every_structural_anchor_is_edge_decomposable
                    && matches!(rule_role(g, mid), Role::Prefix | Role::Suffix))
            } else {
                false
            }
        })
        .collect()
}

/// True if `plan` contains a `PlanNodeKind::Leaf` whose `FragmentSpec` equals `fragment`.
fn plan_has_leaf(plan: &Plan, fragment: &FragmentSpec) -> bool {
    plan.iter()
        .any(|(_, kind)| matches!(kind, PlanNodeKind::Leaf { fragment: f, .. } if f == fragment))
}

/// Whether the surface route leaves root spellings OUT without emitting -- byte budget always;
/// an unbounded (`*`) shape only when `collect_roots`' regex route does not apply to it (a
/// `<RequiredEnvironments>` constraint on the allomorph, `pattern_regex_body`'s own scope limit),
/// since every OTHER unbounded shape is now represented as a regex entry, not dropped. Mirrors
/// `collect_roots`' own `pattern_regex_body` gate exactly so the two can never drift.
pub fn eager_route_drops_root_spellings(g: &Grammar) -> bool {
    !eager_route_root_spelling_refusals(g).is_empty()
}

/// The root-spelling decision with its semantic or budget cause, shared with the selector.
pub fn eager_route_root_spelling_refusals(
    g: &Grammar,
) -> Vec<crate::capability::CapabilityRefusal> {
    use crate::capability::CapabilityRefusal;
    let mut refusals = Vec::new();
    for sd in &g.strata {
        let table = &g.char_tables[sd.table.0 as usize];
        for &entry in &sd.entries {
            for allo in &g.entries[entry.0 as usize].allomorphs {
                match pattern_variants(table, &allo.shape.shape).1 {
                    VariantLimit::BytesExhausted { bytes } => {
                        refusals.push(CapabilityRefusal::RootSpellingBudget {
                            entry: entry.0,
                            bytes,
                            limit: REP_VARIANT_BYTE_BUDGET,
                        })
                    }
                    VariantLimit::Unbounded if !allo.environments.is_empty() => {
                        refusals.push(CapabilityRefusal::PatternRootShape { entry: entry.0 })
                    }
                    VariantLimit::Unbounded | VariantLimit::Complete { .. } => {}
                }
            }
        }
    }
    refusals
}

/// The standalone-derivational loop's own per-rule classification: `None` once a zone or the reduplication peel claims it, else `Some(role)`.
fn standalone_rule_unclaimed_role(g: &Grammar, mid: MRuleId) -> Option<Role> {
    match rule_role(g, mid) {
        Role::Prefix | Role::Suffix | Role::None | Role::CircumfixPrefix => None,
        Role::Process if is_structural_rule(g, mid) => None,
        _ if reduplication_rule_is_peelable(g, mid) => None,
        other => Some(other),
    }
}

/// The `(in_prefix, in_suffix)` derivational-zone membership the standalone loop assigns one rule, shared with `eager_route_refuses_mixed_circumfix_zone` so the two never drift.
fn standalone_rule_zones(g: &Grammar, mid: MRuleId) -> (bool, bool) {
    let (mut in_prefix, mut in_suffix) = match rule_role(g, mid) {
        Role::Prefix => (true, false),
        Role::Suffix => (false, true),
        Role::None => (true, true),
        _ => (false, false),
    };
    if any_allomorph_is_circumfix_prefix(g, mid) {
        in_prefix = true;
        in_suffix = true;
    }
    (in_prefix, in_suffix)
}

/// Whether `emit_rule_allomorphs` would report at least one `Role::Prefix`/`Role::Suffix`
/// allomorph genuinely `AllomorphZoneOutcome::Uncovered` for a rule zone membership
/// `standalone_rule_zones` assigns it into. Calls the SAME two decisions the surface route's own
/// standalone loop and `emit_rule_allomorphs` make (`standalone_rule_zones`,
/// `allomorph_zone_outcome`), rather than reconstructing an equivalent condition from lower-level
/// primitives — `allomorph_zone_outcome` itself now reports `OwnZoneElsewhere`, not `Uncovered`,
/// for a plain allomorph whose own zone a circumfix sibling already widened this rule into (the
/// shape `machine:edge-cases/circumfix-non-first-allomorph-selection` pins), so this predicate no
/// longer fires on that case; it still fires when no sibling widening covers the mismatched zone.
///
/// Deliberately excludes an `Infix`/`Reduplication`/`CircumfixPrefix` "other allomorph": those kinds
/// can still be dropped from `uncovered` by the later composite-coverage retain
/// (`emit_with_budget_profiled_with_strategy_and_trace`'s `uncovered.retain` on
/// `kind == "infix" | "circumfix-prefix" | "reduplication"`, keyed on
/// `composite_report.covered_infix_rules`/`struct_covered_rules`) -- measured to over-claim a
/// refusal on `languages/suffixing-vowel-harmony`'s infix rule, which compiles. `Prefix`/`Suffix`
/// are never touched by that retain, so restricting to them keeps this fact one-way-safe without
/// needing the retain's own `struct_covered_rules` set.
pub fn eager_route_refuses_mixed_circumfix_zone(g: &Grammar) -> bool {
    g.strata.iter().flat_map(|sd| sd.mrules.iter()).any(|&mid| {
        let (in_prefix, in_suffix) = standalone_rule_zones(g, mid);
        let allomorphs = allomorphs_of(g, mid);
        let zone_mismatches = |zone_role: Role| {
            allomorphs.iter().any(|allo| {
                matches!(classify_affix(&allo.rhs), Role::Prefix | Role::Suffix)
                    && matches!(
                        allomorph_zone_outcome(g, mid, allo, zone_role),
                        AllomorphZoneOutcome::Uncovered
                    )
            })
        };
        (in_prefix && zone_mismatches(Role::Prefix)) || (in_suffix && zone_mismatches(Role::Suffix))
    })
}

/// Builds `g`'s reified `Plan` (`crate::enumerate::enumerate_default`) and returns
/// `emit_with_budget_profiled`'s two topology decisions **derived from it** --
/// `(plan wants the composite-emission subtree, plan wants the structural-composite subtree)` --
/// rather than that function calling `crate::preexpand::should_run`/
/// `structural_candidate_rules(...).is_empty()` a second, independently-derived time.
/// `crate::enumerate::enumerate_default` is the ONE place these two seams are
/// consulted to decide topology; this function only ever READS the plan it built. (The third seam,
/// `gate::partition_entries`, belongs to `gate.rs`'s separate compile entry point, which this
/// mainline lexc-emission path never calls at all -- see `emit_with_budget_profiled`'s own doc.)
///
/// `prules_in_order`/`alphabet` mirror `crate::backend_selection::best_case_across_backends`'s own
/// construction of these same `enumerate_default` inputs (that function's own doc: this crate's
/// mainline lexc-emission path doesn't build a `Replace` cascade at all, so `prules_in_order` isn't
/// already a local anywhere in `emit.rs` -- built the same way every other real construction site in
/// this crate does: `g`'s strata, in order, flattened over each stratum's own `phonologicalRules` id
/// list, as literal borrows of `g.prules`).
///
/// Cheap and side-effect-free: `crate::enumerate::enumerate_default` builds plan DATA only
/// (`crate::plan`'s own module doc: "no live `Fsm` is built here at all") -- calling it here does
/// not build or compose any real FST, just the same handful of `Vec`/`HashMap` grammar-data scans
/// `should_run`/`structural_candidate_rules`/`find_gated_subrules`/`partition_entries` already
/// perform on their own.
pub(crate) fn plan_topology_decisions(g: &Grammar, phon: Option<&PhonologyProbe>) -> (bool, bool) {
    let prules_in_order: Vec<&PhonRuleDef> = g
        .strata
        .iter()
        .flat_map(|s| &s.prules)
        .map(|&id| &g.prules[id.0 as usize])
        .collect();
    let plan = enumerate_default(g, &prules_in_order, phon);
    let wants_composite_emission = plan_has_leaf(&plan, &FragmentSpec::CompositeEmissionMarker);
    let wants_structural_composite = plan_has_leaf(&plan, &FragmentSpec::StructuralCompositeMarker);
    (wants_composite_emission, wants_structural_composite)
}

/// Uses extra stack headroom for recursive feature and rewrite probes.
#[cfg(not(target_arch = "wasm32"))]
/// `shape`'s real surface via the build-time probe, run on a large stack since a stack overflow in the uncontrolled pg_rules recursion would abort the process; None when the probe declines or renders empty.
fn probe_surface_on_current_stack(
    g: &Grammar,
    table: &CharDefTable,
    shape: &Shape,
    cache: &RuleCache,
) -> Option<String> {
    let segs = pg_rules::surface_probe::probe_synthesize(g, shape, cache)?;
    pg_rules::surface_probe::render_nodes(table, &segs).filter(|s| !s.is_empty())
}

fn probe_surface(
    g: &Grammar,
    table: &CharDefTable,
    shape: &Shape,
    cache: &RuleCache,
) -> Option<String> {
    // wasm32 has no thread support, so run inline instead of on the dedicated stack below.
    #[cfg(target_arch = "wasm32")]
    {
        return probe_surface_on_current_stack(g, table, shape, cache);
    }
    #[cfg(not(target_arch = "wasm32"))]
    std::thread::scope(|scope| {
        std::thread::Builder::new()
            .stack_size(PROBE_STACK_BYTES)
            .spawn_scoped(scope, || {
                probe_surface_on_current_stack(g, table, shape, cache)
            })
            .expect("spawning the probe thread")
            .join()
            .unwrap_or(None)
    })
}

/// Every `BoundaryDefinition` representation (NFD) in `table`; empty when the grammar defines none.
fn boundary_reps(table: &CharDefTable) -> Vec<String> {
    let mut out = Vec::new();
    for (_, cd) in table.iter() {
        if cd.kind() == CharDefKind::Boundary {
            for r in cd.representations_nfd() {
                if !r.is_empty() && !out.contains(r) {
                    out.push(r.clone());
                }
            }
        }
    }
    out
}

/// `surface` plus every single-boundary-insertion variant at each interior gap: `generate_words` always strips boundaries, so a metathesis-introduced boundary's true position is unrecoverable, and enumerating lets `crate::confirm` prune the spurious ones. A no-op when `bnd_reps` is empty.
fn with_boundary_insertions(surface: &str, bnd_reps: &[String]) -> Vec<String> {
    let mut out = vec![surface.to_string()];
    if bnd_reps.is_empty() {
        return out;
    }
    let chars: Vec<char> = surface.chars().collect();
    for pos in 1..chars.len() {
        let head: String = chars[..pos].iter().collect();
        let tail: String = chars[pos..].iter().collect();
        for rep in bnd_reps {
            out.push(format!("{head}{rep}{tail}"));
        }
    }
    out
}

/// Shares the suffix after a speculative boundary, allowing at most one insertion per surface.
fn write_boundary_surface_lexicons(
    out: &mut String,
    surface: &str,
    reps: &[String],
    prefix: &str,
    exit: &str,
    counts: &mut EmitCounts,
) {
    // Combining runs are single foma symbols. Preserve their literal tokenization on each path.
    if surface.chars().any(char_is_combining) {
        write_lexicon_header(out, &format!("{prefix}N0"));
        for variant in with_boundary_insertions(surface, reps) {
            write_untagged_entry(out, &variant, exit, counts);
        }
        return;
    }
    let chars: Vec<char> = surface.chars().collect();
    if chars.is_empty() {
        write_lexicon_header(out, &format!("{prefix}N0"));
        write_bare(out, exit, counts);
        return;
    }
    for (i, c) in chars.iter().enumerate() {
        let last = i + 1 == chars.len();
        write_lexicon_header(out, &format!("{prefix}N{i}"));
        let next = if last {
            exit.to_string()
        } else {
            format!("{prefix}N{}", i + 1)
        };
        write_untagged_entry(out, &c.to_string(), &next, counts);
        if i > 0 {
            for rep in reps {
                write_untagged_entry(out, rep, &format!("{prefix}B{i}"), counts);
            }
            write_lexicon_header(out, &format!("{prefix}B{i}"));
            let next = if last {
                exit.to_string()
            } else {
                format!("{prefix}B{}", i + 1)
            };
            write_untagged_entry(out, &c.to_string(), &next, counts);
        }
    }
}

/// Joins `known`'s tag strings in ascending surface `order`, deduped by allomorph — re-derived from `crate::preexpand::morph_order_tags`, which is private to that file.
fn struct_morph_order_tags(w: &Word, known: &[(MorphemeId, String)]) -> Option<String> {
    let mut ms = w.morphs.clone();
    ms.sort_by_key(|m| m.order);
    let mut seen: Vec<AllomorphId> = Vec::new();
    let mut out = String::new();
    for m in ms {
        if seen.contains(&m.allomorph) {
            continue;
        }
        seen.push(m.allomorph);
        match known.iter().find(|(mid, _)| *mid == m.morpheme) {
            Some((_, tag)) => out.push_str(tag),
            None => return None,
        }
    }
    if out.is_empty() {
        None
    } else {
        Some(out)
    }
}

/// `struct_extend`'s shared, read-only recursion context — mirrors `crate::preexpand::ExtendCtx`, re-derived here because that struct is private to its own file.
struct StructCtx<'a> {
    g: &'a Grammar,
    root_table: &'a CharDefTable,
    root_entry: LexEntryId,
    rules: &'a [MRuleId],
    rule_variants: &'a [Vec<crate::preexpand::AllomorphVariants>],
    cache: &'a RuleCache,
    morpher: &'a Morpher<'a>,
    /// For `with_boundary_insertions` on `generate_words`-fallback surfaces; empty if the grammar defines no boundaries.
    boundary_reps: &'a [String],
    /// The morphotactic-pruning automaton `struct_extend` consults, its flat/pruned escape hatch, and the shared probe-cap budget.
    mt: &'a MorphotacticIndex,
    mode: ExploreMode,
    probe_budget: Option<ProbeBudget<'a>>,
    closure_trace: Option<&'a crate::characterization::ClosureTrace>,
    structural_trace: &'a StructuralTrace,
}

/// `struct_extend`'s output accumulator: composite records plus a `(tag_lexc, spelling)` dedup set — mirrors `crate::preexpand::Acc`.
struct StructAcc {
    recs: Vec<crate::preexpand::CompositeRec>,
    seen: rustc_hash::FxHashSet<(String, String, bool)>,
    /// `g.mrules` indices with at least one composite entry here, so `emit` can drop their now-stale `uncovered` items.
    covered_rules: BTreeSet<u32>,
    /// Legal synthesized successors beyond the configured closure-depth limit.
    pending_successors: usize,
    pending_rule_ordinals: BTreeSet<u32>,
}

/// Whether structural synthesis must own this rule regardless of its current surface.
fn candidate_requires_structural_route(g: &Grammar, mid: MRuleId) -> bool {
    probe_would_refuse(g)
        || is_structural_rule(g, mid)
        || !matches!(rule_role(g, mid), Role::Prefix | Role::Suffix)
}

/// Whether this successor needs a composite rather than the ordinary prefix/suffix route.
fn structural_successor_is_dirty(
    g: &Grammar,
    mid: MRuleId,
    anchored: bool,
    ordinary_base: Option<(&[String], &[String])>,
    rule_variants: &[crate::preexpand::AllomorphVariants],
    surface: &str,
) -> bool {
    if candidate_requires_structural_route(g, mid) {
        return true;
    }
    if !anchored {
        return false;
    }
    let role = rule_role(g, mid);
    let Some((root_variants, root_stripped)) = ordinary_base else {
        return true;
    };
    !crate::preexpand::reachable_via_ordinary_emission(
        root_variants,
        root_stripped,
        rule_variants,
        role == Role::Prefix,
        surface,
    )
}

/// Uncertain site reachability retains a tail; application counts alone prove it exhausted.
fn can_reach_dirty_candidate(ctx: &StructCtx<'_>, state: &ChainState) -> bool {
    ctx.rules.iter().any(|&mid| {
        state.applications[mid.0 as usize] < ctx.g.mrules[mid.0 as usize].max_apps()
            && candidate_requires_structural_route(ctx.g, mid)
    })
}

fn structural_next_state(
    ctx: &StructCtx<'_>,
    state: &ChainState,
    mid: MRuleId,
    word: &Word,
) -> Option<ChainState> {
    match ctx.mode {
        ExploreMode::Flat => ctx.mt.next_state_unpruned(state, mid),
        ExploreMode::Pruned => ctx
            .mt
            .next_state(state, mid, &word.syn_fs, &ctx.g.fs_interner),
    }
}

/// Affix synthesis changes these fields; every other field is inherited from the same input.
fn structural_affix_words_equal(a: &Word, b: &Word) -> bool {
    a.dedup_key() == b.dedup_key()
        && a.syn_fs == b.syn_fs
        && a.mpr == b.mpr
        && a.morphs == b.morphs
        && a.obligatory == b.obligatory
        && a.flags == b.flags
}

/// Equal annotated words and continuation states permit a lexicographically decreasing swap.
fn structural_reverse_order_matches(
    ctx: &StructCtx<'_>,
    before: &Word,
    before_state: &ChainState,
    previous: MRuleId,
    next: MRuleId,
    result: &Word,
    result_state: &ChainState,
) -> bool {
    #[cfg(test)]
    if !ctx.structural_trace.canonical_order {
        return false;
    }
    if previous <= next
        || ctx.g.strata.is_empty()
        || before.stratum.0 != 0
        || ctx.g.strata[0].mrule_order != pg_grammar::model::MorphRuleOrder::Unordered
        || ctx.g.strata.iter().skip(1).any(|stratum| {
            !stratum.entries.is_empty() || !stratum.mrules.is_empty() || !stratum.prules.is_empty()
        })
        || !ctx.g.templates.is_empty()
        || !candidate_requires_structural_route(ctx.g, previous)
        || !candidate_requires_structural_route(ctx.g, next)
        || !matches!(
            ctx.g.mrules[previous.0 as usize],
            MorphRuleDef::AffixProcess(_)
        )
        || !matches!(ctx.g.mrules[next.0 as usize], MorphRuleDef::AffixProcess(_))
    {
        return false;
    }
    if ctx.g.morphemes[owning_morpheme(ctx.g, previous).0 as usize].stratum != before.stratum
        || ctx.g.morphemes[owning_morpheme(ctx.g, next).0 as usize].stratum != before.stratum
    {
        return false;
    }
    ctx.structural_trace.bump(|st| st.proof_attempts += 1);
    let Some(first_state) = structural_next_state(ctx, before_state, next, before) else {
        ctx.structural_trace
            .bump(|st| st.proof_fail_no_reverse += 1);
        return false;
    };
    if !ctx.structural_trace.charge(None) {
        return false;
    }
    let (mut state_mismatch, mut word_unequal) = (false, false);
    for first in pg_rules::morph::synthesize(ctx.g, before, &ctx.g.mrules[next.0 as usize]) {
        let Some(second_state) = structural_next_state(ctx, &first_state, previous, &first) else {
            continue;
        };
        if second_state != *result_state {
            state_mismatch = true;
            continue;
        }
        if !ctx.structural_trace.charge(None) {
            return false;
        }
        for second in pg_rules::morph::synthesize(ctx.g, &first, &ctx.g.mrules[previous.0 as usize])
        {
            if structural_affix_words_equal(&second, result) {
                ctx.structural_trace
                    .state
                    .lock()
                    .expect("structural trace poisoned")
                    .commutations += 1;
                return true;
            }
            word_unequal = true;
        }
    }
    ctx.structural_trace.bump(|st| {
        if word_unequal {
            st.proof_fail_word += 1;
        } else if state_mismatch {
            st.proof_fail_state += 1;
        } else {
            st.proof_fail_no_reverse += 1;
        }
    });
    false
}

/// Explores authored applications within the closure limit, emitting only structural chains.
#[allow(clippy::too_many_arguments)]
fn struct_extend(
    ctx: &StructCtx,
    base_word: &Word,
    chain: &[(MorphemeId, String)],
    rule_chain: &[MRuleId],
    depth: usize,
    width: usize,
    state: &ChainState,
    preceding: Option<(&Word, &ChainState, MRuleId)>,
    anchored: bool,
    acc: &mut StructAcc,
) {
    if ctx.structural_trace.stopped() {
        return;
    }
    ctx.structural_trace
        .state
        .lock()
        .expect("structural trace poisoned")
        .nodes += 1;
    let base_fs = base_word.syn_fs.clone();
    // Failure to prove an anchored surface ordinarily reachable keeps it on the structural path.
    let ordinary_base = if anchored {
        probe_surface_on_current_stack(ctx.g, ctx.root_table, &base_word.shape, ctx.cache).and_then(
            |surface| {
                let variants = surface_variants(ctx.root_table, &surface)?.0;
                let stripped = stripped_variants(ctx.root_table, &surface)
                    .map(|(variants, _)| variants)
                    .unwrap_or_default();
                Some((variants, stripped))
            },
        )
    } else {
        None
    };
    for (ridx, &mid) in ctx.rules.iter().enumerate() {
        if ctx.structural_trace.stopped() {
            return;
        }
        let rule = &ctx.g.mrules[mid.0 as usize];
        let (req, rule_morpheme) = match rule {
            MorphRuleDef::AffixProcess(def) => (def.required_syn_fs, def.morpheme),
            MorphRuleDef::Realizational(def) => (def.required_syn_fs, def.morpheme),
            MorphRuleDef::Compounding(_) => continue,
        };
        // Morphotactic pruning before the FS pre-filter below, mirroring `crate::preexpand::extend`'s insertion point.
        let Some(next_state) = structural_next_state(ctx, state, mid, base_word) else {
            continue;
        };
        let req_fs = ctx.g.fs_interner.get(req);
        if !req_fs.is_empty() && !is_unifiable(req_fs, &base_fs) {
            continue;
        }
        if let Some(trace) = ctx.closure_trace {
            if !trace.begin_pair(depth, mid.0) {
                return;
            }
        }
        if let Some(budget) = &ctx.probe_budget {
            budget.tick();
        }

        if !ctx.structural_trace.charge(None) {
            return;
        }

        let synthesized = pg_rules::morph::synthesize(ctx.g, base_word, rule);
        if let Some(trace) = ctx.closure_trace {
            if !trace.record_successors(depth, mid.0, synthesized.len()) {
                return;
            }
        }
        let depth_limit = ctx
            .closure_trace
            .map_or(DEFAULT_STRUCTURAL_CLOSURE_DEPTH_BUDGET, |trace| {
                trace.depth_cap()
            });
        if depth >= depth_limit {
            if !synthesized.is_empty() {
                acc.pending_rule_ordinals.insert(mid.0);
            }
            acc.pending_successors += synthesized.len();
            continue;
        }

        let mut next_rule_chain = rule_chain.to_vec();
        next_rule_chain.push(mid);

        for w in synthesized {
            if let Some((before, before_state, previous)) = preceding {
                if structural_reverse_order_matches(
                    ctx,
                    before,
                    before_state,
                    previous,
                    mid,
                    &w,
                    &next_state,
                ) {
                    continue;
                }
                if ctx.structural_trace.stopped() {
                    return;
                }
            }
            let mut next_chain = chain.to_vec();
            next_chain.push((rule_morpheme, tags::morph_tag_lexc(rule_morpheme, width)));
            let next_anchored = anchored || candidate_requires_structural_route(ctx.g, mid);
            if !next_anchored {
                struct_extend(
                    ctx,
                    &w,
                    &next_chain,
                    &next_rule_chain,
                    depth + 1,
                    width,
                    &next_state,
                    Some((base_word, state, mid)),
                    false,
                    acc,
                );
                continue;
            }

            let shape_has_boundary = w
                .shape
                .interior()
                .any(|(_, kind, _, _)| kind == pg_shape::NodeKind::Boundary);
            let (surfaces, boundary_insertions): (Vec<String>, bool) =
                match probe_surface_on_current_stack(ctx.g, ctx.root_table, &w.shape, ctx.cache) {
                    // A rendered-away boundary needs speculative positions for confirmation.
                    Some(s) => (vec![s], shape_has_boundary && !ctx.boundary_reps.is_empty()),
                    None => {
                        // Probe refused: fall back to real generation for the whole chain so far, which can return more than one surface when the LHS match is genuinely ambiguous.
                        let others: Vec<GenMorpheme> = next_rule_chain
                            .iter()
                            .map(|&m| GenMorpheme::Rule(m))
                            .collect();
                        (
                            ctx.morpher
                                .generate_words(ctx.root_entry, &others, FeatureStruct::EMPTY)
                                .into_iter()
                                .collect(),
                            !ctx.boundary_reps.is_empty(),
                        )
                    }
                };

            let tag_lexc = struct_morph_order_tags(&w, &next_chain);
            for s in &surfaces {
                if s.is_empty() {
                    continue;
                }
                // Only an ordinary Prefix/Suffix after an anchor may use the exact clean proof.
                let dirty = structural_successor_is_dirty(
                    ctx.g,
                    mid,
                    anchored,
                    ordinary_base
                        .as_ref()
                        .map(|(variants, stripped)| (variants.as_slice(), stripped.as_slice())),
                    &ctx.rule_variants[ridx],
                    s,
                );
                if !dirty {
                    continue;
                }
                let Some(tag_lexc) = tag_lexc.as_ref() else {
                    continue;
                };
                acc.covered_rules.insert(mid.0);
                let key = (tag_lexc.clone(), s.clone(), boundary_insertions);
                if !acc.seen.contains(&key) {
                    // Charge spare Vec/hash capacity as well as both copies of the strings.
                    let bytes = 4usize.saturating_mul(
                        2usize
                            .saturating_mul(tag_lexc.len().saturating_add(s.len()))
                            .saturating_add(std::mem::size_of::<crate::preexpand::CompositeRec>())
                            .saturating_add(std::mem::size_of_val(&key))
                            .saturating_add(std::mem::size_of::<String>())
                            .saturating_add(next_chain.len().saturating_mul(std::mem::size_of::<(
                                bool,
                                MorphemeId,
                            )>(
                            ))),
                    );
                    if !ctx.structural_trace.charge(Some(bytes)) {
                        return;
                    }
                    acc.seen.insert(key);
                    acc.recs.push(crate::preexpand::CompositeRec {
                        chain_morphemes: next_chain
                            .iter()
                            .enumerate()
                            .map(|(i, (m, _))| (i == 0, *m))
                            .collect(),
                        tag_lexc: tag_lexc.clone(),
                        variants: vec![s.clone()],
                        boundary_insertions,
                    });
                } else {
                    ctx.structural_trace.bump(|st| st.seen_duplicate_hits += 1);
                }
            }

            if !next_anchored || can_reach_dirty_candidate(ctx, &next_state) {
                struct_extend(
                    ctx,
                    &w,
                    &next_chain,
                    &next_rule_chain,
                    depth + 1,
                    width,
                    &next_state,
                    Some((base_word, state, mid)),
                    next_anchored,
                    acc,
                );
            }
        }
    }
}

/// Builds every structural composite for `g`; a no-op when `rules` is empty. Also returns every rule id that produced an entry, so `emit` can drop its now-stale `uncovered` items.
#[allow(clippy::too_many_arguments)]
fn build_structural_composites_on_current_stack(
    g: &Grammar,
    width: usize,
    rules: &[MRuleId],
    cache: &RuleCache,
    morpher: &Morpher,
    mt: &MorphotacticIndex,
    mode: ExploreMode,
    probe_budget: Option<ProbeBudget<'_>>,
    phon: Option<&PhonologyProbe>,
    closure_trace: Option<&crate::characterization::ClosureTrace>,
    structural_trace: &StructuralTrace,
) -> (
    Vec<crate::preexpand::CompositeRec>,
    BTreeSet<u32>,
    usize,
    BTreeSet<u32>,
    usize,
) {
    if rules.is_empty() {
        return (Vec::new(), BTreeSet::new(), 0, BTreeSet::new(), 0);
    }
    let mut acc = StructAcc {
        recs: Vec::new(),
        seen: rustc_hash::FxHashSet::default(),
        covered_rules: BTreeSet::new(),
        pending_successors: 0,
        pending_rule_ordinals: BTreeSet::new(),
    };
    // Every stratum shares one surface table in the reference grammars, so computing this once is safe.
    let bnd_reps = boundary_reps(surface_table(g));
    let mut candidate_pairs_pruned = 0usize;
    for sd in &g.strata {
        for &entry_id in &sd.entries {
            if structural_trace.stopped() {
                break;
            }
            let entry = &g.entries[entry_id.0 as usize];
            let root_stratum = g.morphemes[entry.morpheme.0 as usize].stratum;
            let root_table = &g.char_tables[g.strata[root_stratum.0 as usize].table.0 as usize];
            let entry_fs = g.fs_interner.get(entry.syn_fs);
            let (root_rules, pruned_per_allomorph) =
                structural_candidate_rules_for_root(g, rules, entry_fs);
            for allo in &entry.allomorphs {
                if structural_trace.stopped() {
                    break;
                }
                if allo.is_pattern {
                    continue;
                }
                let Ok(shape) =
                    pg_rules::shape_feat::segment_with_features(g, root_table, &allo.shape.text)
                else {
                    continue;
                };
                let mut word = Word::new(shape, root_stratum);
                word.syn_fs = entry_fs.clone();
                word.mpr = entry.mpr;
                word.root_allomorph = Some(allo.id);
                word.morphs = vec![MorphRecord::new(allo.id, entry.morpheme, 0)];
                candidate_pairs_pruned =
                    candidate_pairs_pruned.saturating_add(pruned_per_allomorph);

                let root_tag = tags::root_tag_lexc(entry.morpheme, width);
                let chain0 = vec![(entry.morpheme, root_tag)];
                let rule_variants: Vec<Vec<crate::preexpand::AllomorphVariants>> = root_rules
                    .iter()
                    .map(|&mid| {
                        crate::preexpand::build_allomorph_variants(
                            root_table,
                            phon,
                            &g.mrules[mid.0 as usize],
                        )
                    })
                    .collect();
                let ctx = StructCtx {
                    g,
                    root_table,
                    root_entry: entry_id,
                    rules: &root_rules,
                    rule_variants: &rule_variants,
                    cache,
                    morpher,
                    boundary_reps: &bnd_reps,
                    mt,
                    mode,
                    probe_budget,
                    closure_trace,
                    structural_trace,
                };
                // Seeded the same way `crate::preexpand::process_root_work` seeds pruning.
                let seed_state = ChainState::seed(g, root_stratum.0, entry.is_partial());
                struct_extend(
                    &ctx,
                    &word,
                    &chain0,
                    &[],
                    0,
                    width,
                    &seed_state,
                    None,
                    false,
                    &mut acc,
                );
            }
        }
    }
    structural_trace
        .state
        .lock()
        .expect("structural trace poisoned")
        .dedup_bytes = acc
        .seen
        .capacity()
        .saturating_mul(std::mem::size_of::<(String, String, bool)>())
        .saturating_add(
            acc.seen
                .iter()
                .map(|(tag, surface, _)| tag.capacity() + surface.capacity())
                .sum::<usize>(),
        );
    (
        acc.recs,
        acc.covered_rules,
        acc.pending_successors,
        acc.pending_rule_ordinals,
        candidate_pairs_pruned,
    )
}

#[allow(clippy::too_many_arguments)]
#[allow(dead_code)]
#[allow(clippy::type_complexity)]
fn build_structural_composites(
    g: &Grammar,
    width: usize,
    rules: &[MRuleId],
    cache: &RuleCache,
    morpher: &Morpher,
    mt: &MorphotacticIndex,
    mode: ExploreMode,
    probe_budget: Option<ProbeBudget<'_>>,
    phon: Option<&PhonologyProbe>,
) -> Result<
    (
        Vec<crate::preexpand::CompositeRec>,
        BTreeSet<u32>,
        usize,
        BTreeSet<u32>,
        usize,
    ),
    EnumBudgetExceeded,
> {
    let structural_trace = StructuralTrace::new(StructuralClosureLimits::default());
    let result = build_structural_composites_with_trace(
        g,
        width,
        rules,
        cache,
        morpher,
        mt,
        mode,
        probe_budget,
        phon,
        None,
        &structural_trace,
    );
    let state = structural_trace
        .state
        .lock()
        .expect("structural trace poisoned");
    match state.refusal.clone() {
        Some(refusal) => Err(refusal),
        None => Ok(result),
    }
}

#[allow(clippy::too_many_arguments)]
pub(crate) fn build_structural_composites_with_trace(
    g: &Grammar,
    width: usize,
    rules: &[MRuleId],
    cache: &RuleCache,
    morpher: &Morpher,
    mt: &MorphotacticIndex,
    mode: ExploreMode,
    probe_budget: Option<ProbeBudget<'_>>,
    phon: Option<&PhonologyProbe>,
    closure_trace: Option<&crate::characterization::ClosureTrace>,
    structural_trace: &StructuralTrace,
) -> (
    Vec<crate::preexpand::CompositeRec>,
    BTreeSet<u32>,
    usize,
    BTreeSet<u32>,
    usize,
) {
    #[cfg(target_arch = "wasm32")]
    {
        return build_structural_composites_on_current_stack(
            g,
            width,
            rules,
            cache,
            morpher,
            mt,
            mode,
            probe_budget,
            phon,
            closure_trace,
            structural_trace,
        );
    }
    #[cfg(not(target_arch = "wasm32"))]
    std::thread::scope(|scope| {
        std::thread::Builder::new()
            .stack_size(PROBE_STACK_BYTES)
            .spawn_scoped(scope, move || {
                build_structural_composites_on_current_stack(
                    g,
                    width,
                    rules,
                    cache,
                    morpher,
                    mt,
                    mode,
                    probe_budget,
                    phon,
                    closure_trace,
                    structural_trace,
                )
            })
            .expect("spawning the structural-composite worker")
            .join()
            .expect("structural-composite worker panicked")
    })
}

