//! The emitter: `Grammar -> lexc source`.
//!
//! ## Structure: a faithful mirror of `hc-hybrid/src/trie.rs`'s morphotactics
//! This emitter reproduces the SAME morphotactic language `hc-hybrid`'s trie encodes (upward
//! deviations only — see "deliberate supersets" below), expressed as lexc continuation classes:
//!
//! - **Bare-root paths** (`trie.rs` `run()` "Bare-root paths"): every root allomorph directly
//!   accepting. Deviation (upward): trie gates bare roots on `bare_root_surfaces` non-empty
//!   (the obligatory-inflection check, which needs a live `Morpher`); this emitter admits every
//!   root bare EXCEPT the one sub-case `bare_admissible_roots` proves safe to omit at compile
//!   time: an entry with exactly one allomorph that is `is_bound` can never be valid bare,
//!   confirm's `distinct_count == 1 && is_bound` gate rejects it unconditionally — every other
//!   root is still a superset; the verify pass prunes.
//! - **Template-less derivation section** (`trie.rs:1035-1063`): prefix derivation layer →
//!   every root → optional single compound root → suffix derivation layer → accept. Only built
//!   when the grammar has standalone derivation rules or compounding rules, like trie.
//! - **Per-template slot chains** (`trie.rs::classify_template`/`append_slots`,
//!   `trie.rs:871-959`): each template's slots are classified prefix/suffix by `slot_op`, the
//!   prefix list REVERSED to surface order, and each slot appears EXACTLY ONCE in its chain
//!   (optional slots add an epsilon skip) — this is what bounds zero-surface slot allomorphs to
//!   at most one tag per slot (the depth-N "bag" design this replaced admitted them at every
//!   level and overgenerated by six orders of magnitude on real Sena words — 2.5M candidates for
//!   `mbali` vs the engine's 8).
//! - **Derivation layers** (`trie.rs::build_derivation_layer`, `trie.rs:796-836`): the
//!   standalone (stratum-attached, non-template) affix rules, in a bounded chain of optional
//!   levels. Depth = the NUMBER OF RULES routed to that side (min 2) — deeper than trie's
//!   `deriv_depth = 2` (an upward deviation, found by the recall gate: Sena's corpus word
//!   `kubulukira` stacks THREE derivational suffixes, REV + separado + APPLIC, which depth 2
//!   silently loses). Depth = rule count is the engine-faithful bound for the default
//!   `multipleApplication = 1` case (each rule can apply once, so no chain exceeds the rule
//!   count); a rule with `max_apps > 1` could still exceed it — none exists in the reference
//!   grammars, and the corpus recall gate is the empirical backstop. Rules whose first allomorph
//!   classifies `None` (a pure zero morph) are SKIPPED by trie's `rule_op` routing
//!   (`trie.rs:1001-1006` — `MorphOp::None => {}`); this emitter instead includes them in BOTH
//!   layers (an upward deviation; zero such rules exist in Sena — note for future grammars: each
//!   such rule adds an optional epsilon-tag choice per level, so a grammar with many could
//!   inflate candidate counts).
//! - **Outer (post-template) derivation layers** — an addition trie does NOT have, found by the
//!   recall gate: the engine applies later-stratum rules OUTSIDE a completed template (Sena's
//!   stratum-1 `=mbo` clitic lands AFTER the template's final-vowel suffix slot: engine order
//!   `[.., root, IND, ADD]`), while trie places ALL strata's standalone rules in the inner
//!   derivation layer (before suffix slots — order `[.., root, ADD, IND]`, a positional miss).
//!   This emitter wires every template path through `OuterPfx`/`OuterSfx` chains (same rule sets
//!   as the inner layers — a superset of the exact per-stratum split) so both orders exist.
//! - **Bounded compound loop** (`trie.rs::build_compound_loop`, `trie.rs:857-867`): when any
//!   `CompoundingRule` exists, exactly ONE extra root may follow the head root, then control
//!   passes to the suffix derivation layer — same one-extra-root bound as trie.
//!
//! ## Deliberate supersets (upward approximations only — a subset is a bug)
//! 1. **Group sharing decouples a template's prefix side from its suffix side.** trie replicates
//!    root wiring per template (cheap epsilon edges into shared root chains — a graph trick lexc
//!    has no equivalent for: a `LEXICON` name is a single forward continuation, so per-template
//!    replication would copy every root line once per template). This emitter groups templates by
//!    their exact `required_syn_fs` `FsId` (9 groups for Sena's 24 templates; identical authored
//!    POS lists collapse to one id in the grammar's own interner) and shares one root section per
//!    group; after the root+derivation section, control joins a UNION of the group's templates'
//!    suffix-slot chains. A word can therefore combine template A's prefix slots with template
//!    B's suffix slots (same category group) — more paths than trie, never fewer.
//! 2. **`derivable_to_category` is approximated one-step and fail-open.** trie's bounded BFS
//!    (`trie.rs:1567-1622`) admits a root to a template if some derivation chain can reach the
//!    template's category. Here: if ANY category-changing standalone rule's `out_syn_fs` unifies
//!    with a group's key, the group admits EVERY root ("permissive") — a strict superset of the
//!    BFS's answer for that group.
//! 3. Bare roots skip the obligatory-inflection gate; root stratum-index-vs-template-stratum
//!    admission (`trie.rs:1105`) is skipped (all roots offered to all groups they categorize
//!    into).
//!
//! ## Tag tape convention
//! Every lexc entry's UPPER side is the morpheme's tag SYMBOL ONLY (never literal underlying
//! text) — `<R:nnnn>`/`<M:nnnn>` (`tags::root_tag_lexc`/`morph_tag_lexc`). The LOWER side is the
//! real surface spelling. This keeps `tags::decode_path` a trivial tag-occurrence scan (no
//! literal upper-tape text can ever contain `<`/`>`). The tag for each morpheme sits at the
//! morpheme's SURFACE position — prefix tags precede the root tag, suffix tags follow it —
//! because confirm's `analyses_match` is positional in ascending surface order — the "positional
//! match trap": engine order = `allomorphs_in_morph_order`, ascending surface
//! position, `pg-parse/src/morpher.rs:725-746`. Multiple allomorphs of one morpheme are multiple
//! lexc entries sharing ONE tag symbol; free-fluctuating allomorphs are naturally separate
//! entries.
//!
//! ## Surface spelling: boundary characters dropped, representation variants enumerated
//! Sena's affix/root shapes carry literal `Boundary`-kind characters (`+`, the `^0`-family, `.`)
//! that are structural morpheme-juncture markers, NOT real orthography — verified two ways: (a)
//! `pg-parse`'s own generation-output renderer (`surface::to_plain_string`, called with
//! `include_boundaries = false`) strips them from every synthesized word; (b) `hc-hybrid`'s bare
//! walker treats every `Boundary`-kind trie arc as FREE (`walk.rs::is_free_arc` — traversed
//! without consuming input, exactly like an epsilon arc). `surface_variants` reproduces this:
//! it re-segments a root/affix's authored text against the surface char-def table (the same
//! greedy longest-match algorithm `pg_grammar::segment::segment` uses) and drops `Boundary`-kind
//! matches.
//!
//! The engine matches SEGMENTS BY CHAR-DEF IDENTITY, not by spelling (`pg_parse::root_trie`'s
//! `edge_matches`; ditto trie.rs's `ArcLabel::Segment { char_def }`): a char-def with several
//! `<Representation>`s (Sena `char4` = {"m", "n"}) matches ANY of its spellings in the input
//! word. A single literal lexc string cannot ("tun", the authored shape of Sena's *mentir*, must
//! also match corpus "tum..." — found as 13 of the first recall gate's 19 misses).
//! `surface_variants` therefore returns the CARTESIAN PRODUCT of each matched segment
//! char-def's representations — every spelling the engine would accept. Bounded by
//! `REP_VARIANT_CAP`; on overflow the remainder is dropped AND reported as an uncovered item
//! (an explicit, visible under-approximation for a pathological grammar — never triggered by
//! Sena, whose only multi-representation segment char-def is `char4`).
//!
//! ## Normalization
//! `kept_surface_text` NFD-normalizes before matching (mirroring `pg_grammar::segment::segment`
//! and, downstream, `pg_parse`'s own `segment_with_features` — the real engine's query words are
//! NFD-matched too). `crate::analyzer` NFD-normalizes its own query word the same way before
//! calling `apply_up`, so lexc surface text and query text live in the same normalization space
//! regardless of whether the corpus file itself is NFC or NFD on disk.
//!
//! ## Junction-aware affix/root emission (Indonesian: `meN+tulis -> menulis`)
//! The baseline emission path (Sena, 0 phonological rules) emits every affix/root surface as its
//! literal, boundary-stripped authored text. That is exactly wrong for a grammar with real junction phonology: the
//! `meN` rule's authored insert text is `"meⁿ+"` (`ⁿ` a placeholder nasal segment that phonological
//! rules assimilate in place and, before a voiceless obstruent + vowel, delete the OBSTRUENT too),
//! and no literal spelling of that text is ever the surface word. `crate::junctions::PhonologyProbe`
//! (built once per grammar, `None` when the grammar has no phonological rules at all — a true no-op
//! for Sena, preserving that gate byte-for-byte) drives the real synthesis cascade
//! (`pg_rules::surface_probe::probe_synthesize`) to answer two questions per affix underlying text:
//! - `PhonologyProbe::variants`: every surface spelling the affix can realize as, alone or next to
//!   one alphabet neighbor on either side (`"meⁿ+"` -> `{"meng", "mem", "men", "meny", "me", ...}`).
//!   `emit_rule_allomorphs` UNIONS these into the ordinary literal-text entries at every affix
//!   emission site (any zone, any derivation level, any slot) — pure upward approximation, so it
//!   can never cost recall, only add it.
//! - `PhonologyProbe::deletion_junctions`: every affix spelling that, in SOME right-neighbor
//!   context, additionally deletes that neighbor's own leading segment (`"meⁿ+"` -> `{"men", "mem",
//!   "meng", ...}` — the SAME rendered strings `variants` can produce, since the deleted neighbor is
//!   excluded from the render; the two sets legitimately overlap and both get emitted, to different
//!   continuations, see below).
//!
//! **Encoding choice: per-prefix-variant root partitions, not lane-gated skip edges.** `hc-hybrid`'s
//! trie (`trie.rs::wire_deletion_skips`) gates each deletion-skip edge on a real FeatureStruct
//! unification test against the specific root's own onset, because its root chains are SHARED
//! graph structure across every affix and an ungated skip edge would corrupt an unrelated affix's
//! path. lexc has no equivalent sharing problem here (root text is written out per section, not
//! linked as one graph), so this emitter takes the simpler, still-upward-safe route: whenever a
//! prefix derivation chain's FINAL level is genuinely root-adjacent (its `next == exit` IS a roots
//! lexicon — `TLRoots`/`G{gi}Roots`, never true for `OuterPfx`'s `TmplDispatch` exit or any
//! `T{ti}P` template slot chain, which are never root-adjacent by construction), that roots lexicon
//! gets a `{name}Stripped` sibling (`write_roots_lexicon`) holding every root's OWN
//! `stripped_variants` (root text with its first SEGMENT — not first character; multi-char
//! representations like `"ny"`/`"ng"` are one segment — removed). Every `deletion_junctions` hit for
//! a rule at that final level is routed to `{exit}Stripped` instead of `exit`; every ordinary
//! `variants` hit still goes to `exit` (module doc superset: nothing here ever narrows what the
//! baseline emission path already accepted). Deliberately UNGATED by onset class — every root gets a stripped entry
//! regardless of whether its own initial segment would really delete after that particular
//! assimilated spelling (e.g. `"mem"` + `baca`'s stripped `"aca"`, which the real grammar never
//! licenses) — an explicit upward approximation: the extra candidate is harmless
//! (confirm prunes it), and it avoids needing lane-level unification data this emitter has no
//! other use for. See `crate::junctions`'s module doc for why this is smaller in scope than
//! `hc-hybrid`'s original (no `bare_root_surfaces`, no per-junction neighbor-class bookkeeping).
//!
//! **Reduplication is explicitly out of scope here** (the peel is a later verification pass's job): every rule
//! whose primary allomorph classifies `Role::Reduplication` (Indonesian's `-Cont`, `-Pl`,
//! `REDUP-meN`) is already routed to `uncovered` by the SAME zone-mismatch logic the baseline
//! emission path uses for every other exotic role (see "Not emittable as literal lexc" below) —
//! nothing new needed to exclude it; the recall gate (`tests/f2_indonesian_gate.rs`) separately excludes the
//! 7 corpus words that only have a reduplicated analysis, printing each with its reason.
//!
//! ## Composite entries (interdigitation + Ge'ez boundary fusion)
//! `crate::preexpand` (see that module's doc for the full design) applies the engine's own
//! morphological rules to each root allomorph — and, recursively, to each resulting stem — and
//! emits every surface the ordinary entries above cannot reach as ONE multi-tag entry in a single
//! shared `Composites` lexicon. Every roots lexicon (`Root`, `TLRoots`, each `G{gi}Roots`) gets a
//! bare redirect into `Composites`; each composite entry continues to `CompositeExit`, a
//! bare-redirect UNION of every post-root continuation (`#`, `TLPost`, every `G{gi}Post`) — so a
//! composite stem sits exactly where an ordinary root does (any prefix chain before it, any suffix
//! chain after it), at the cost of a cross-group superset (upward
//! only, confirm prunes). An `Infix` rule that produced at least one composite here, OR (for an
//! allomorph that drops LHS material, census C4) via `build_structural_composites`, is removed from
//! `uncovered` (it IS representable now); one that matched zero roots stays, honestly. Zero-cost
//! and zero-entry for a grammar with no phonological rules and no `Infix` rules (Sena,
//! byte-identical) and for one whose junctions the deletion-junction model already covers
//! (Indonesian, zero composites emitted).
//!
//! ## Not emittable as literal lexc (routed to `EmitReport::uncovered`, never silently dropped)
//! - `RootAllomorphDef::is_pattern` allomorphs (iterative/optional shape nodes — no concrete
//!   spelling).
//! - `OutputAction::Modify`/`InsertContext` ("process morphs" — ablaut/simulfix/class-insertion,
//!   not compilable as strings). Zero uses in Sena; this path is defensive.
//! - Any allomorph whose `classify_affix` role doesn't fit the zone it was reached from (Infix,
//!   Reduplication, Circumfix, Process) — mirrors `trie.rs::append_slots`'s per-allomorph
//!   mismatch check (`trie.rs:941-946`) and `classify_template`'s slot-level uncovered routing
//!   (`trie.rs:884-889`) exactly.
//! - Text that fails to re-segment against the surface table (defensive; the loader already
//!   accepted it once).

