pub(crate) fn write_lexicon_header(out: &mut String, name: &str) {
    out.push_str("\nLEXICON ");
    out.push_str(name);
    out.push('\n');
}

/// A bare continuation-only line (standard lexc idiom for a pure structural redirect — no symbols
/// consumed on either tape).
pub(crate) fn write_bare(out: &mut String, continuation: &str, counts: &mut EmitCounts) {
    out.push_str(continuation);
    out.push_str(" ;\n");
    counts.lexc_lines += 1;
}

/// Every emitted entry funnels through this one function, which is what lets `PrecisionEmit::tagged_lower` gate the ENVIRONMENT family without touching each call site's own logic; byte-identical to the pre-precision-knob emitter under `PrecisionConfig::Strip` (pinned by `precision_emit_tagged_lower_is_passthrough_under_strip`).
#[allow(clippy::too_many_arguments)]
fn write_tag_entry(
    out: &mut String,
    tag_lexc: &str,
    surface: &str,
    continuation: &str,
    counts: &mut EmitCounts,
    pk: &mut PrecisionEmit,
    owner: Option<AllomorphId>,
) {
    let escaped = escape_lexc_text(surface);
    let lower = pk.tagged_lower(surface, &escaped, owner);
    out.push_str(tag_lexc);
    out.push(':');
    out.push_str(&lower);
    out.push(' ');
    out.push_str(continuation);
    out.push_str(" ;\n");
    counts.lexc_lines += 1;
}

/// A surface-only entry for a circumfix's non-tag-bearing half.
fn write_untagged_entry(out: &mut String, text: &str, continuation: &str, counts: &mut EmitCounts) {
    if text.is_empty() {
        out.push_str(continuation);
        out.push_str(" ;\n");
        counts.lexc_lines += 1;
        return;
    }
    out.push_str("0:");
    out.push_str(&escape_lexc_text(text));
    out.push(' ');
    out.push_str(continuation);
    out.push_str(" ;\n");
    counts.lexc_lines += 1;
}

/// FST emission cannot preserve alpha bindings across environment traversal.
pub const ALPHA_ENVIRONMENT_REFUSAL: &str = "alpha-variable environments are not represented by FST backends; use the full morphological parser";

/// Shared representability decision used by each FST compiler and its capability envelope.
pub fn alpha_environment_refusal(g: &Grammar) -> bool {
    let has_alpha = |pattern: &Option<pg_grammar::model::Pattern>| {
        pattern
            .as_ref()
            .is_some_and(|p| crate::lower::nodes_contain_alpha_context(&p.nodes))
    };
    let environment_has_alpha =
        |env: &pg_grammar::model::EnvironmentDef| has_alpha(&env.left) || has_alpha(&env.right);
    g.prules.iter().any(|rule| match rule {
        PhonRuleDef::Rewrite(rule) => rule
            .subrules
            .iter()
            .any(|s| has_alpha(&s.left_env) || has_alpha(&s.right_env)),
        PhonRuleDef::Metathesis(_) => false,
    }) || g
        .entries
        .iter()
        .flat_map(|entry| &entry.allomorphs)
        .any(|a| a.environments.iter().any(&environment_has_alpha))
        || g.mrules
            .iter()
            .filter_map(|rule| rule.affix_allomorphs())
            .flatten()
            .any(|a| a.environments.iter().any(&environment_has_alpha))
}

fn alpha_environment_emit_refusal(g: &Grammar) -> EmitResult {
    EmitResult {
        lexc_source: String::new(),
        report: EmitReport {
            uncovered: Vec::new(),
            counts: EmitCounts {
                entries: g.entries.len(),
                rules: g.mrules.len(),
                ..Default::default()
            },
            tier: FomaTier::CannotRepresent {
                reason: ALPHA_ENVIRONMENT_REFUSAL.to_owned(),
            },
            enum_budget_exceeded: None,
            closure_refusal: None,
            closure_evidence: None,
        },
    }
}

fn write_root_entries_with_width(
    out: &mut String,
    roots: &[&RootRec],
    continuation: &str,
    counts: &mut EmitCounts,
    pk: &mut PrecisionEmit,
    width: usize,
) {
    for r in roots {
        let tag_lexc = tags::root_tag_lexc(r.morpheme, width);
        if let Some(body) = &r.pattern_regex_body {
            write_pattern_root_entry(out, &tag_lexc, body, continuation, counts);
            continue;
        }
        for v in &r.variants {
            write_tag_entry(out, &tag_lexc, v, continuation, counts, pk, Some(r.id));
        }
    }
}

