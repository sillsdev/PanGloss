/// Floor for a derivation layer chain's depth (the actual depth is the rule count routed to that
/// side, but never less than trie's `deriv_depth = 2` — staying >= trie's language is the
/// baseline recall guarantee; see the module doc's derivation-layer section for why rule count,
/// not 2, is the engine-faithful bound).
pub const DERIV_DEPTH_MIN: usize = 2;

/// Largest derivation chain (levels) the emitter will unroll; deeper refuses with a typed reason.
const DEFAULT_DERIV_CHAIN_DEPTH_BUDGET: usize = 200;

/// `HC_DERIV_CHAIN_DEPTH_BUDGET` overrides `DEFAULT_DERIV_CHAIN_DEPTH_BUDGET`.
fn deriv_chain_depth_budget() -> Result<usize, String> {
    parse_deriv_chain_budget(std::env::var("HC_DERIV_CHAIN_DEPTH_BUDGET").ok().as_deref())
}

/// The budget for an env value (`None` = unset); a malformed value is an error, never a silent default.
pub fn parse_deriv_chain_budget(raw: Option<&str>) -> Result<usize, String> {
    let Some(v) = raw else {
        return Ok(DEFAULT_DERIV_CHAIN_DEPTH_BUDGET);
    };
    v.trim()
        .parse()
        .map_err(|_| format!("HC_DERIV_CHAIN_DEPTH_BUDGET={v:?} is not a non-negative integer"))
}

/// Shared configuration resolver for the legacy compound emitter entry point.
fn compound_chain_depth_budget() -> usize {
    let mut bounds = crate::construction::ConstructionBounds::default();
    bounds.resolve_depths_from_env();
    bounds.compound_depth.expect("resolved compound depth")
}

// --- Report types -----------------------------------------------------------------------------

/// `OutputAction::Modify`/`InsertContext` carry no concrete text; checked independently of `classify_affix` since an RHS can contain one and still classify as plain Prefix/Suffix.
fn has_unemittable_action(rhs: &[OutputAction]) -> bool {
    rhs.iter().any(|a| {
        matches!(
            a,
            OutputAction::Modify(_, _) | OutputAction::InsertContext(_)
        )
    })
}

/// Carries EVERY `InsertSegments` action's `text`/`shape` pair in document order, not just the first — a rule's RHS can legitimately contain more than one, and dropping the rest loses inserted material.
enum InsertText<'a> {
    /// A pure zero/null morph: no `InsertSegments` action at all, whether or not the RHS also `Copy`s an input part.
    None,
    /// One `InsertSegments` action's literal text and already-segmented `Shape` per occurrence, in RHS document order — safe to concatenate since only `Role::None`/`Prefix`/`Suffix` ever reach this variant, so no occurrence interleaves with a `Copy`.
    Text { texts: Vec<&'a str> },
}

/// Every `InsertSegments` action's underlying text/shape in `rhs`, in document order — not just the first; see `InsertText::Text` for why concatenation order is always sound here.
fn insert_action_texts(rhs: &[OutputAction]) -> InsertText<'_> {
    let mut texts = Vec::new();
    for a in rhs {
        if let OutputAction::InsertSegments { shape, .. } = a {
            texts.push(shape.text.as_str());
        }
    }
    if texts.is_empty() {
        InsertText::None
    } else {
        InsertText::Text { texts }
    }
}

/// `pub(crate)`: `crate::peel::ReduplicationPeeler` reuses this too. Its `redup_rules` and
/// `suffix_surfaces` (see its own `new`) are built only from `AffixProcess`/`Realizational`
/// allomorphs, so a Compounding rule id never reaches this function from that caller either.
pub fn allomorphs_of(g: &Grammar, mid: MRuleId) -> &[AffixAllomorphDef] {
    match &g.mrules[mid.0 as usize] {
        MorphRuleDef::AffixProcess(def) => &def.allomorphs,
        MorphRuleDef::Realizational(def) => &def.allomorphs,
        MorphRuleDef::Compounding(_) => &[],
    }
}

/// `trie.rs::required_category`: the requirement FS a rule imposes (empty `FsId(0)` where C# would say null).
fn required_category(g: &Grammar, mid: MRuleId) -> FsId {
    match &g.mrules[mid.0 as usize] {
        MorphRuleDef::AffixProcess(def) => def.required_syn_fs,
        MorphRuleDef::Realizational(def) => def.required_syn_fs,
        MorphRuleDef::Compounding(_) => FsId(0),
    }
}

/// `trie.rs::rule_op`: a rule's primary role, from its FIRST allomorph.
pub fn rule_role(g: &Grammar, mid: MRuleId) -> Role {
    allomorphs_of(g, mid)
        .first()
        .map(|a| classify_affix(&a.rhs))
        .unwrap_or(Role::None)
}

// --- Surface text (boundary-stripped, as-authored) ----------------------------------------------

/// Projects a non-final-stratum root into the final character table through phonological rules.
/// A segment is its feature bundle and a table only spells it for one stratum, so the root reaches the surface spelled by whichever final-table segment carries the same bundle (hc.dll `CharacterDefinitionTable.GetMatchingStrReps`).
pub(crate) fn cross_table_root_surface(
    g: &Grammar,
    stratum_table: &CharDefTable,
    text: &str,
    cache: &RuleCache,
) -> Option<String> {
    if std::ptr::eq(stratum_table, surface_table(g)) {
        return None;
    }
    let feat_shape = pg_rules::shape_feat::segment_with_features(g, stratum_table, text).ok()?;
    probe_surface(g, surface_table(g), &feat_shape, cache).filter(|s| !s.is_empty())
}

/// The final table's own spelling of an inner-stratum root's bundles, before any rule runs, when it differs from the root's text: the respelling proper, as distinct from a root both tables spell alike (whatever a later rule then does to it).
pub(crate) fn cross_table_respelling(
    g: &Grammar,
    stratum_table: &CharDefTable,
    text: &str,
) -> Option<String> {
    if std::ptr::eq(stratum_table, surface_table(g)) {
        return None;
    }
    let feat_shape = pg_rules::shape_feat::segment_with_features(g, stratum_table, text).ok()?;
    pg_rules::surface_probe::render_shape(surface_table(g), &feat_shape)
        .filter(|s| !s.is_empty() && s != text)
}

/// Re-encode a shape into final-table tokens, expanding foreign-table NFD representation variants.
pub(crate) fn underlying_shape_variants(
    alphabet: &SegAlphabet<'_>,
    origin_table: &CharDefTable,
    shape: &Shape,
) -> Vec<String> {
    if std::ptr::eq(origin_table, alphabet.table()) {
        return vec![alphabet.encode_shape(shape)];
    }

    let mut variants = vec![String::new()];
    for (_, _, raw_cd, _) in shape.interior() {
        let source = origin_table.get(CharDefId(raw_cd));
        let mut tokens: Vec<char> = source
            .representations_nfd()
            .iter()
            .filter_map(|spelling| alphabet.table().lookup_nfd(spelling))
            .map(|cd| alphabet.token(cd))
            .collect();
        tokens.sort_unstable();
        tokens.dedup();
        if tokens.is_empty() {
            return Vec::new();
        }

        let mut next = Vec::with_capacity(variants.len() * tokens.len());
        for prefix in &variants {
            for token in &tokens {
                let mut encoded = prefix.clone();
                encoded.push(*token);
                next.push(encoded);
            }
        }
        variants = next;
    }
    variants
}

/// Surface spellings for one literal-only action slice, preserving each action's source table.
fn surface_insert_action_variants(g: &Grammar, actions: &[OutputAction]) -> Option<Vec<String>> {
    if actions.is_empty() {
        return None;
    }
    let mut variants = vec![String::new()];
    for action in actions {
        let OutputAction::InsertSegments { table, shape } = action else {
            return None;
        };
        let (pieces, limit) = surface_variants(g.char_tables.get(table.0 as usize)?, &shape.text)?;
        // Bails on an INCOMPLETE set only; a complete set is usable however large, since this caller needs every spelling or none.
        if limit.drops_spellings() || pieces.is_empty() {
            return None;
        }
        let mut next = Vec::with_capacity(variants.len().saturating_mul(pieces.len()));
        let mut grown = 0usize;
        for prefix in &variants {
            for piece in &pieces {
                let joined = format!("{prefix}{piece}");
                grown = grown.saturating_add(joined.len());
                if grown > REP_VARIANT_BYTE_BUDGET {
                    return None;
                }
                next.push(joined);
            }
        }
        variants = next;
    }
    variants.sort_unstable();
    variants.dedup();
    Some(variants)
}

/// Surface-spelled halves of a one-copy literal circumfix.
fn circumfix_surface_texts(
    g: &Grammar,
    allomorph: &AffixAllomorphDef,
) -> Option<Vec<(String, String)>> {
    if allomorph.lhs.len() != 1 {
        return None;
    }
    let rhs = allomorph.rhs.as_slice();
    let mut copies = rhs.iter().enumerate().filter_map(|(index, action)| {
        matches!(action, OutputAction::Copy(PartRef::Input(0))).then_some(index)
    });
    let copy = copies.next()?;
    if copies.next().is_some() || copy == 0 || copy == rhs.len() - 1 {
        return None;
    }
    let prefixes = surface_insert_action_variants(g, &rhs[..copy])?;
    let suffixes = surface_insert_action_variants(g, &rhs[copy + 1..])?;
    let mut pairs = Vec::with_capacity(prefixes.len().saturating_mul(suffixes.len()));
    for prefix in prefixes {
        for suffix in &suffixes {
            pairs.push((prefix.clone(), suffix.clone()));
        }
    }
    Some(pairs)
}

/// Every accepted spelling of `text` with its OWN FIRST SEGMENT removed (module doc, "Junction-
/// aware affix/root emission"): re-run `surface_variants`'s greedy segmentation, skip past any
/// leading `Boundary`-kind matches (structural, already dropped from ordinary output — a root
/// should never actually start with one, but this stays defensive), consume exactly one
/// `Segment`-kind match (possibly multi-CHARACTER, e.g. `"ny"`/`"ng"`/`"kh"`/`"sy"` are each ONE
/// segment), then return `surface_variants` of everything after it. `None` when `text` is
/// entirely boundaries (or empty) — nothing to strip — or fails to segment at all.
pub(crate) fn stripped_variants(
    table: &CharDefTable,
    text: &str,
) -> Option<(Vec<String>, VariantLimit)> {
    let normalized = pg_grammar::nfd::nfd(text);
    let chars: Vec<char> = normalized.chars().collect();
    let mut i = 0usize;
    while i < chars.len() {
        let mut matched: Option<(usize, CharDefKind)> = None;
        for j in (1..=(chars.len() - i)).rev() {
            let candidate: String = chars[i..i + j].iter().collect();
            if let Some(cd_id) = table.lookup_nfd(&candidate) {
                matched = Some((j, table.get(cd_id).kind()));
                break;
            }
        }
        let (j, kind) = matched?;
        i += j;
        if kind == CharDefKind::Segment {
            let remainder: String = chars[i..].iter().collect();
            return surface_variants(table, &remainder);
        }
        // Boundary-kind: not a real segment to strip -- keep scanning for the first one.
    }
    None // nothing but boundaries, or empty text: no segment to strip.
}

/// Every char-def-set member's representations for a `[ClassName]` natural-class `Shape` node — the emission-side rendering of the same member set `pg_parse::root_trie`'s trie edges consult for matching.
fn class_node_representations(table: &CharDefTable, cd_set: EffectiveCdSet<'_>) -> Vec<String> {
    let mut out = Vec::new();
    for (id, cd) in table.iter() {
        if cd.kind() != CharDefKind::Segment {
            continue;
        }
        let member = match cd_set {
            EffectiveCdSet::Singleton(s) => s == id.0,
            EffectiveCdSet::Unrestricted => true,
            EffectiveCdSet::Members(b) => b.contains(id.0),
        };
        if member {
            out.extend(cd.representations_nfd().iter().cloned());
        }
    }
    out
}

/// One interior shape node's own alternatives before either flag is applied -- shared by `node_alternatives` and the pattern-route regex builder so neither re-derives what a node's segment/class means.
fn node_base_alternatives(
    table: &CharDefTable,
    shape: &Shape,
    i: usize,
    char_def: u32,
) -> Vec<String> {
    let mut reps: Vec<String> = if char_def != pg_shape::NO_CHAR_DEF {
        table
            .get(CharDefId(char_def))
            .representations_nfd()
            .to_vec()
    } else {
        class_node_representations(table, shape.node_cd_set(i))
    };
    if reps.is_empty() {
        // Defensive: neither case occurs in practice, but treat as silent epsilon rather than dropping the whole allomorph.
        reps.push(String::new());
    }
    reps
}

/// One interior shape node's alternatives, shared by [`pattern_variants`] and `root_variant_census` (`test-support` only) so the census cannot drift from the emitter it measures.
fn node_alternatives(
    table: &CharDefTable,
    shape: &Shape,
    i: usize,
    char_def: u32,
    flags: pg_shape::NodeFlags,
) -> Vec<String> {
    let mut reps = node_base_alternatives(table, shape, i, char_def);
    if flags.is_iterative() {
        let base = reps.clone();
        let mut repeated = base.clone();
        for _ in 0..PATTERN_ITER_CAP {
            let mut next = Vec::with_capacity(repeated.len() * base.len());
            for prev in &repeated {
                for r in &base {
                    next.push(format!("{prev}{r}"));
                }
            }
            reps.extend(next.iter().cloned());
            repeated = next;
        }
    }
    if flags.is_optional() {
        reps.push(String::new());
    }
    reps.sort_unstable();
    reps.dedup();
    reps
}

/// Every concrete surface spelling a lexical PATTERN root allomorph (`RootAllomorphDef::is_pattern`
/// — module doc "Not emittable as literal lexc" v1) CAN realize as, computed directly from the
/// allomorph's own already-parsed `Shape` (built once at grammar load by
/// `pg_grammar::segment::segment_with_patterns`) rather than re-parsing the authored text's bracket
/// syntax a second time — the `Shape` already carries exactly what the pattern means: a
/// `[ClassName]` reference is a `NO_CHAR_DEF` node whose char-def-set is the class's real member set
/// (`class_node_representations`); `([ClassName])`/`[ClassName]*` set the node's
/// `OPTIONAL`/`ITERATIVE` flags (`pg_shape::NodeFlags`).
///
/// Walks the interior nodes left to right, taking the CARTESIAN PRODUCT of each node's own
/// alternatives (mirroring `surface_variants`'s representation-variant product, same
/// [`REP_VARIANT_BYTE_BUDGET`]): a concrete `Segment` node contributes its own char-def's
/// representations (`Boundary`-kind nodes are dropped, exactly like `surface_variants`/module doc
/// "Surface spelling"); an abstract class-reference node contributes the union of every member's
/// representations. An `OPTIONAL` node (from `(...)` or a Kleene star) ADDITIONALLY contributes the
/// empty string (the "absent" branch) — upward-safe by construction, since the pattern really does
/// allow that branch (`pg_parse::root_trie`'s own doc notes the ENGINE's trie does NOT honor this
/// flag on a matched node — a documented, intentional divergence from that matching-side quirk;
/// this emitter's job is only to make every candidate the PATTERN's own semantics allow
/// *proposable*, never fewer). An `ITERATIVE` node (Kleene star) further repeats its own
/// alternatives 1..=`PATTERN_ITER_CAP` extra times on top of that — an explicit, bounded
/// under-approximation of the star's true unbounded repetition (never triggered by the reference
/// grammars or the conformance suite's own pattern fixture, whose only patterns are
/// `[Vowel]`/`([Vowel])`, module doc).
///
/// Returns `(variants, limit)` exactly like `surface_variants`.
pub(crate) fn pattern_variants(table: &CharDefTable, shape: &Shape) -> (Vec<String>, VariantLimit) {
    let mut variants: Vec<String> = vec![String::new()];
    let mut exhausted = None;
    let mut unbounded = false;
    for (i, kind, char_def, flags) in shape.interior() {
        if exhausted.is_some() {
            break;
        }
        if kind == NodeKind::Boundary {
            continue; // dropped, same convention as `surface_variants`.
        }
        // A star's language is infinite, so no budget enumerates it: representability, not size.
        unbounded |= flags.is_iterative();
        let reps = node_alternatives(table, shape, i, char_def, flags);

        let mut next = Vec::with_capacity(variants.len().saturating_mul(reps.len().max(1)));
        let mut grown = 0usize;
        'grow: for v in &variants {
            for r in &reps {
                let joined = format!("{v}{r}");
                grown = grown.saturating_add(joined.len());
                if grown > REP_VARIANT_BYTE_BUDGET {
                    exhausted = Some(grown);
                    break 'grow;
                }
                next.push(joined);
            }
        }
        variants = next;
    }
    variants.sort_unstable();
    variants.dedup();
    let limit = if unbounded {
        VariantLimit::Unbounded
    } else if let Some(bytes) = exhausted {
        VariantLimit::BytesExhausted { bytes }
    } else {
        VariantLimit::Complete {
            warn: variants.len() > REP_VARIANT_WARN_THRESHOLD,
        }
    };
    (variants, limit)
}

/// Escapes literal text for a foma XRE `< regex >` lexc entry body, mirroring `nfst_xre`'s own reserved-character set (a wider set than `escape_lexc_text`'s plain-entry escaping).
fn escape_xre_text(s: &str) -> String {
    fn needs_escape(c: char) -> bool {
        matches!(
            c,
            '-' | ' '
                | '\t'
                | '\r'
                | '\n'
                | '|'
                | '<'
                | '>'
                | '%'
                | '!'
                | ','
                | '.'
                | '^'
                | ':'
                | '"'
                | ';'
                | '@'
                | '0'
                | '~'
                | '\\'
                | '&'
                | '?'
                | '$'
                | '+'
                | '*'
                | '/'
                | '_'
                | '('
                | ')'
                | '{'
                | '}'
                | ']'
                | '['
                | '#'
                | '`'
                | '\''
                | '='
        )
    }
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        if needs_escape(c) {
            out.push('%');
        }
        out.push(c);
    }
    out
}

/// One shape node's own XRE fragment (identity plane): a bracketed union of `node_base_alternatives`, `*`-starred when iterative or `(...)`-optional when merely optional, genuinely unbounded rather than `PATTERN_ITER_CAP`-truncated.
fn node_regex_fragment(
    table: &CharDefTable,
    shape: &Shape,
    i: usize,
    char_def: u32,
    flags: pg_shape::NodeFlags,
) -> String {
    let reps = node_base_alternatives(table, shape, i, char_def);
    let escaped: Vec<String> = reps
        .iter()
        .map(|r| {
            if r.is_empty() {
                "0".to_string()
            } else {
                escape_xre_text(r)
            }
        })
        .collect();
    let union = if escaped.len() == 1 {
        escaped.into_iter().next().unwrap()
    } else {
        format!("[{}]", escaped.join("|"))
    };
    if flags.is_iterative() {
        format!("{union}*")
    } else if flags.is_optional() {
        format!("({union})")
    } else {
        union
    }
}

/// The pattern route's bracketed concatenation of every non-`Boundary` interior node's own `node_regex_fragment`, in shape order.
fn pattern_shape_regex_body(table: &CharDefTable, shape: &Shape) -> String {
    let mut nodes = Vec::new();
    for (i, kind, char_def, flags) in shape.interior() {
        if kind == NodeKind::Boundary {
            continue;
        }
        nodes.push(node_regex_fragment(table, shape, i, char_def, flags));
    }
    if nodes.is_empty() {
        "[0]".to_string()
    } else {
        format!("[{}]", nodes.join(" "))
    }
}

/// Writes one pattern root's regex-routed entry (`TAG:0 0:body`, lexc's `< regex >` syntax) -- one physical line for the shape's whole language, replacing one `write_tag_entry` line per spelling; `body` must already be bracketed (foma XRE's `:` binds tighter than concatenation).
fn write_pattern_root_entry(
    out: &mut String,
    tag_lexc: &str,
    body: &str,
    continuation: &str,
    counts: &mut EmitCounts,
) {
    out.push_str("< ");
    out.push_str(tag_lexc);
    out.push_str(":0 0:");
    out.push_str(body);
    out.push_str(" > ");
    out.push_str(continuation);
    out.push_str(" ;\n");
    counts.lexc_lines += 1;
}

/// What one root allomorph's shape would cost to enumerate, measured WITHOUT enumerating it.
#[cfg(feature = "test-support")]
pub struct RootVariantFact {
    /// `entry<id>(morpheme=<name>)#allo<n>`, the same label `collect_roots` reports uncovered items under.
    pub label: String,
    /// The authored surface text of the shape, for reading a census row back to a grammar.
    pub text: String,
    pub is_pattern: bool,
    /// Interior nodes excluding `Boundary`, i.e. how many factors the product below has.
    pub nodes: usize,
    /// The product of every node's alternative count, saturating at `u128::MAX`. `None` when a
    /// Kleene-star node makes the TRUE count unbounded -- which no cap can make representable by
    /// enumeration, however large.
    pub variants: Option<u128>,
}

#[cfg(feature = "test-support")]
impl RootVariantFact {
    /// Unbounded, or past [`REP_VARIANT_WARN_THRESHOLD`] -- i.e. worth a census row. Only the
    /// unbounded half means spellings are actually missing; breadth alone costs memory, not recall.
    pub fn notable(&self) -> bool {
        self.variants
            .is_none_or(|n| n > REP_VARIANT_WARN_THRESHOLD as u128)
    }

    /// Whether this shape can never be fully enumerated, at any budget.
    pub fn unbounded(&self) -> bool {
        self.variants.is_none()
    }
}

/// Every root allomorph's true enumeration cost, to answer whether [`REP_VARIANT_WARN_THRESHOLD`] is a
/// realistic ceiling or the wrong shape of control entirely.
///
/// Computes the magnitude symbolically -- multiplying per-node alternative counts rather than
/// materializing strings -- so measuring a grammar that would exhaust memory under enumeration
/// costs no more than one that fits. It walks strata and entries in `collect_roots`'s order and
/// shares `node_alternatives` with `pattern_variants`, so a row here describes the shape the
/// emitter really faces.
#[cfg(feature = "test-support")]
pub fn root_variant_census(g: &Grammar) -> Vec<RootVariantFact> {
    let mut out = Vec::new();
    for sd in &g.strata {
        let table = &g.char_tables[sd.table.0 as usize];
        for &entry_id in &sd.entries {
            let entry = &g.entries[entry_id.0 as usize];
            let morpheme_name = g
                .morphemes
                .get(entry.morpheme.0 as usize)
                .map(|m| m.xml_key.as_str())
                .unwrap_or("?");
            for (allo_idx, allo) in entry.allomorphs.iter().enumerate() {
                let shape = &allo.shape.shape;
                let mut product: u128 = 1;
                let mut unbounded = false;
                let mut nodes = 0usize;
                for (i, kind, char_def, flags) in shape.interior() {
                    if kind == NodeKind::Boundary {
                        continue;
                    }
                    nodes += 1;
                    // The emitter approximates a star with `PATTERN_ITER_CAP` repetitions; the shape's own semantics do not stop there.
                    unbounded |= flags.is_iterative();
                    let count = node_alternatives(table, shape, i, char_def, flags).len() as u128;
                    product = product.saturating_mul(count.max(1));
                }
                out.push(RootVariantFact {
                    label: format!(
                        "entry{}(morpheme={morpheme_name})#allo{allo_idx}",
                        entry_id.0
                    ),
                    text: allo.shape.text.clone(),
                    is_pattern: allo.is_pattern,
                    nodes,
                    variants: (!unbounded).then_some(product),
                });
            }
        }
    }
    out
}

/// Escapes lexc's special characters (`% < : > 0 ; !` and space) in literal text — `0` matters for any text, not just tag numerals (gate F0, `tests/f0_viability.rs`).
fn escape_lexc_text(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        if matches!(c, '%' | '<' | '>' | ':' | '0' | ';' | '!' | ' ') {
            out.push('%');
        }
        out.push(c);
    }
    out
}

/// Whether `c` is a Unicode combining mark, per the same ranges vendored `apply.rs::is_combining` (a literal port of foma's C `utf8iscombining`) checks.
fn char_is_combining(c: char) -> bool {
    let mut buf = [0u8; 4];
    is_combining(c.encode_utf8(&mut buf).as_bytes()) != 0
}

/// Declares every base-char-plus-trailing-combining-mark run in the surface `CharDefTable` as a lexc `Multichar_Symbols` entry, fixing a real 100%-recall bug (not a reference-grammar gap).
/// Root cause, fix, and scope: docs/research/pg-foma-emit-design-notes.md.
fn combining_run_symbols(table: &CharDefTable) -> BTreeSet<String> {
    let mut out = BTreeSet::new();
    for (_, cd) in table.iter() {
        if cd.kind() != CharDefKind::Segment {
            continue;
        }
        for rep in cd.representations_nfd() {
            let chars: Vec<char> = rep.chars().collect();
            let mut i = 0usize;
            while i < chars.len() {
                let mut j = i + 1;
                while j < chars.len() && char_is_combining(chars[j]) {
                    j += 1;
                }
                if j - i >= 2 {
                    // Escapes just this slice — per-char escaping is context-free, so this matches what `write_tag_entry` produces over the full string.
                    let run: String = chars[i..j].iter().collect();
                    out.insert(escape_lexc_text(&run));
                }
                i = j;
            }
        }
    }
    out
}

/// Every Segment char-def representation as an NFD char vector; shared by `boundary_combining_run_symbols`, which needs the set twice (once filtered to mark-initial).
fn segment_representations(table: &CharDefTable) -> Vec<Vec<char>> {
    let mut out = Vec::new();
    for (_, cd) in table.iter() {
        if cd.kind() != CharDefKind::Segment {
            continue;
        }
        for rep in cd.representations_nfd() {
            out.push(rep.chars().collect());
        }
    }
    out
}

/// The maximal trailing base-char-plus-combining-marks run — exactly the suffix `vendor/foma`'s apply-time merge would keep absorbing into, so no separate all-marks case is needed.
fn trailing_combining_run(rep: &[char]) -> &[char] {
    let mut i = rep.len();
    while i > 0 && char_is_combining(rep[i - 1]) {
        i -= 1;
    }
    if i == 0 {
        rep
    } else {
        &rep[i - 1..]
    }
}

/// Cross-char-def-boundary companion to `combining_run_symbols`: covers a combining run that spans two adjacent char-defs' representations, which apply's flat character-by-character retokenization also merges.
/// Dormant today (no reference grammar needs it) but real — see docs/research/pg-foma-emit-design-notes.md.
fn boundary_combining_run_symbols(table: &CharDefTable) -> BTreeSet<String> {
    let all_reps = segment_representations(table);
    let mark_initial: Vec<&[char]> = all_reps
        .iter()
        .filter(|rep| rep.first().is_some_and(|&c| char_is_combining(c)))
        .map(|rep| rep.as_slice())
        .collect();
    let mut out = BTreeSet::new();
    if mark_initial.is_empty() {
        return out;
    }
    for p in &all_reps {
        let trailing = trailing_combining_run(p);
        for &m in &mark_initial {
            let run: String = trailing.iter().chain(m.iter()).collect();
            out.insert(escape_lexc_text(&run));
            for &m2 in &mark_initial {
                let chain: String = trailing.iter().chain(m.iter()).chain(m2.iter()).collect();
                out.insert(escape_lexc_text(&chain));
            }
        }
    }
    out
}

