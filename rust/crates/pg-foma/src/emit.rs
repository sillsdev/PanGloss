/// Cheap pre-flight scale estimate for `crate::preexpand::build_composites` (`should_run`,
/// candidate `Infix`/`Prefix`/`Suffix` rule count, root count) WITHOUT running that module's
/// expensive `O(roots × rules^depth)` recursive probe (its own doc: "workable at Amharic's 76
/// entries × 87 rules × depth 3 ... but decidedly NOT at FLEx scale") — for triaging whether a very
/// large grammar is worth attempting `emit`/`emit_with_precision` on at all.
pub fn composite_scale_hint(g: &Grammar) -> (bool, usize, usize) {
    let phon = PhonologyProbe::new(g);
    let should_run = crate::preexpand::should_run(g, phon.as_ref());
    let candidate_rule_count = crate::preexpand::candidate_rule_count(g);
    let root_count: usize = g.strata.iter().map(|s| s.entries.len()).sum();
    (should_run, candidate_rule_count, root_count)
}

/// Diagnostic-only, alongside `composite_scale_hint` (used by `crates/pg-foma/examples/
/// aweti_probe.rs` to size the payoff of template-slot pruning for
/// `crate::preexpand::build_composites`/`build_structural_composites` on a large grammar
/// without ever running either's expensive recursive probe): every rule this crate's two
/// rule-application composite mechanisms consider as a candidate, plus the same per-grammar
/// structural-widening facts `build_structural_composites` itself gates on.
///
/// `preexpand_candidates`: every `crate::preexpand::build_composites` candidate rule id paired
/// with its role label ("Infix"/"Prefix"/"Suffix") — mirrors that module's own private
/// `candidate_rules` (same `rule_role` classification, same `Compounding` exclusion, and, since
/// census C4, the same Infix-with-drop ownership handoff onto `build_structural_composites`),
/// re-derived here rather than exposing that sibling module's helper (this crate's diagnostic
/// surface must not touch `preexpand.rs`).
///
/// `structural_probe_would_refuse`/`structural_candidate_count`/`structural_candidates`:
/// `probe_would_refuse`'s verdict and `structural_candidate_rules`'s candidate set
/// for `build_structural_composites` — that set widens dramatically (every ordinary
/// Prefix/Suffix/Infix rule joins it, on top of the always-on structural/circumfix rules) exactly
/// when `structural_probe_would_refuse` is true; when a structural anchor exists it also carries
/// every bounded non-Compounding predecessor rule. `structural_candidates` carries the exact rule ids
/// (`structural_candidate_count` is simply its length) so a caller can assert set MEMBERSHIP, not
/// only cardinality — the census C4 handoff test needs this to prove a rule reaches this set
/// specifically, rather than merely inferring it from a count that could shift for an unrelated
/// reason.
#[derive(serde::Serialize)]
pub struct CompositeCandidateDiagnostics {
    pub preexpand_candidates: Vec<(u32, &'static str)>,
    pub structural_probe_would_refuse: bool,
    pub structural_candidate_count: usize,
    pub structural_candidates: Vec<u32>,
}

/// See `CompositeCandidateDiagnostics`.
pub fn composite_candidate_rules(g: &Grammar) -> CompositeCandidateDiagnostics {
    let preexpand_candidates = (0..g.mrules.len() as u32)
        .filter_map(|i| {
            if matches!(g.mrules[i as usize], MorphRuleDef::Compounding(_)) {
                return None;
            }
            let mid = MRuleId(i);
            match rule_role(g, mid) {
                // Structural synthesis owns the whole rule, including ordinary first allomorphs.
                Role::Prefix | Role::Suffix | Role::Infix if is_structural_rule(g, mid) => None,
                Role::Infix => Some((i, "Infix")),
                Role::Prefix => Some((i, "Prefix")),
                Role::Suffix => Some((i, "Suffix")),
                _ => None,
            }
        })
        .collect();
    let structural_candidates: Vec<u32> =
        structural_candidate_rules(g).iter().map(|m| m.0).collect();
    CompositeCandidateDiagnostics {
        preexpand_candidates,
        structural_probe_would_refuse: probe_would_refuse(g),
        structural_candidate_count: structural_candidates.len(),
        structural_candidates,
    }
}

/// `emit_with_precision(g, PrecisionConfig::Strip)` — v1's original, unconditional behavior.
/// Callers that don't need the FST precision knob (`crate::precision`) keep using this; its output
/// is byte-identical to before that module existed (verified, `tests/pk1_precision_recall_
/// invariance.rs` and every other existing `pg-foma` gate).
pub fn emit(g: &Grammar) -> EmitResult {
    emit_with_precision(g, PrecisionConfig::Strip)
}

/// `emit`, but with the FST precision knob (`crate::precision`) wired in: under
/// `PrecisionConfig::Strip` (the default, and what `emit` always passes) this is
/// byte-identical to the pre-knob emitter; under `PrecisionConfig::AllFlags`, every
/// `AllFlags`-coverable ENVIRONMENT gate-constraint instance (`crate::precision`'s module doc) is
/// emitted as a real `@R@`+`@P@` flag scheme (require-only — exclude is declined this step, see
/// `crate::precision`'s module doc finding 4), shrinking the raw candidate set at lookup time
/// without ever losing a confirmed analysis (`sena_precision_recall_invariance`/
/// `indonesian_precision_recall_invariance` pin this on real grammars).
///
/// Thin wrapper over the profiled surface emitter. The exploratory flat/pruned and probe-cap
/// switches remain internal measurement controls; structural containment limits also apply
/// inside the external execution envelope.
pub fn emit_with_precision(g: &Grammar, precision: PrecisionConfig) -> EmitResult {
    emit_with_budget(g, precision)
}

/// Thin, zero-behavior-change wrapper over `emit_with_budget_profiled` with `profile: None`
/// ("no observer-induced minimization" rule, proven byte-for-byte by
/// `tests::fst_profile_emitted_artifact_is_byte_identical_with_profiling_on_or_off`
/// in this file's own test module below): every existing caller of this function is completely
/// unaffected by the profiling machinery's existence.
pub(crate) fn emit_with_budget(g: &Grammar, precision: PrecisionConfig) -> EmitResult {
    emit_with_budget_profiled(g, precision, None)
}

/// Uses explicit structural containment limits instead of the environment defaults.
