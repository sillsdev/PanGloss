/// The two deliberate seams in the tuned surface emitter: derive topology from the reified plan, and admit every collected root.
#[derive(Clone, Copy, Debug)]
struct SurfaceEmitStrategy {
    derivation: SurfaceDerivationPolicy,
    root_scope: SurfaceRootScopePolicy,
    structural_limits: Option<StructuralClosureLimits>,
    /// An explicit snapshot keeps production controls independent of evidence collection.
    preexpand_controls: Option<(ExploreMode, Option<usize>)>,
}

impl Default for SurfaceEmitStrategy {
    fn default() -> Self {
        Self {
            derivation: SurfaceDerivationPolicy::ReifiedPlan,
            root_scope: SurfaceRootScopePolicy::AllRoots,
            structural_limits: None,
            preexpand_controls: None,
        }
    }
}

/// Decides which already-defined plan topology controls surface emission.
#[derive(Clone, Copy, Debug)]
enum SurfaceDerivationPolicy {
    ReifiedPlan,
}

/// Decides which collected roots the surface emitter may admit.
#[derive(Clone, Copy, Debug)]
enum SurfaceRootScopePolicy {
    AllRoots,
}

/// `emit_with_budget`'s real core, with an optional compile-profile sink
/// (`crate::profile`'s own module doc "Stage boundaries") threaded through as its fourth
/// parameter. `profile: None` is byte-for-byte
/// identical to this function's pre-profiling behavior (nothing here branches on `profile` for any
/// purpose OTHER than pushing a timing/count record) -- `crate::analyzer::FomaProposer::
/// new_proposer` is the one production caller that passes `Some`.
///
/// Every stage boundary below is a plain `Instant::now()`/`.elapsed()` pair around already-existing
/// sequential code, never a closure: several stages sit across this function's own early `return`s
/// (the empty-roots bail-out and other early returns), and a closure
/// cannot early-return its OUTER function, so timing via closures would not fit every stage
/// `CompileStage` names (`crate::profile`'s own doc, `CompileProfileBuilder::push_stage`).
pub(crate) fn emit_with_budget_profiled(
    g: &Grammar,
    precision: PrecisionConfig,
    profile: Option<&mut CompileProfileBuilder>,
) -> EmitResult {
    emit_with_budget_profiled_with_strategy(g, precision, profile, SurfaceEmitStrategy::default())
}

