pub(crate) fn write_lexicon_header(out: &mut String, name: &str) {
    out.push_str("\nLEXICON ");
    out.push_str(name);
    out.push('\n');
}

/// A bare continuation-only line (standard lexc idiom for a pure structural redirect — no symbols
/// consumed on either tape).
pub(crate) fn write_bare(out: &mut String, continuation: &str, counts: &mut EmitCounts) {
    out.push_str(continuation);
    out.push_str(" ;\n");
    counts.lexc_lines += 1;
}

/// One tagged entry: upper = the tag symbol ONLY (module doc's tag-tape convention), lower = the
/// (already boundary-stripped) surface text, escaped, with the FST precision knob's inline flag
/// text spliced in (`crate::precision`'s module doc, "Emission mechanism"). Empty surface = lexc's
/// `0` epsilon (still gets the owner's own `@R@` prefix if applicable — see
/// [`PrecisionEmit::tagged_lower`]).
///
/// `pk`/`owner`: every entry in the whole emitter funnels through this ONE function, which is what
/// lets [`PrecisionEmit::tagged_lower`] gate the ENVIRONMENT family's `AllFlags` preset without
/// touching every call site's own logic — `owner` identifies the allomorph THIS entry realizes
/// (`Some(allo.id)` from [`emit_rule_allomorphs`] and `Some(root.id)` from the root-entry writers;
/// `None` only for composite entries, which are never an owner-side gate this step), and
/// `surface` (this entry's own literal spelling, pre-escape) is checked against every covered
/// constraint's set-side literal match regardless of owner. Under [`PrecisionConfig::Strip`] (`pk`
/// built from that config) `tagged_lower` always returns exactly what this function wrote before
/// the precision knob existed, so this is byte-identical to that version.
#[allow(clippy::too_many_arguments)]
fn write_tag_entry(
    out: &mut String,
    tag_lexc: &str,
    surface: &str,
    continuation: &str,
    counts: &mut EmitCounts,
    pk: &mut PrecisionEmit,
    owner: Option<AllomorphId>,
) {
    let escaped = escape_lexc_text(surface);
    let lower = pk.tagged_lower(surface, &escaped, owner);
    out.push_str(tag_lexc);
    out.push(':');
    out.push_str(&lower);
    out.push(' ');
    out.push_str(continuation);
    out.push_str(" ;\n");
    counts.lexc_lines += 1;
}

fn write_root_entries_with_width(
    out: &mut String,
    roots: &[&RootRec],
    continuation: &str,
    counts: &mut EmitCounts,
    pk: &mut PrecisionEmit,
    width: usize,
) {
    for r in roots {
        let tag_lexc = tags::root_tag_lexc(r.morpheme, width);
        for v in &r.variants {
            write_tag_entry(out, &tag_lexc, v, continuation, counts, pk, Some(r.id));
        }
    }
}

// --- Root collection ------------------------------------------------------------------------------

struct RootRec {
    /// The root allomorph's own registry id — `crate::precision`'s ENVIRONMENT-family owner-side
    /// gate (`PrecisionEmit::tagged_lower`'s `owner` argument) is keyed on this.
    id: AllomorphId,
    morpheme: MorphemeId,
    category: FsId,
    /// Every accepted spelling ([`surface_variants`]), each emitted as its own lexc entry line
    /// sharing this morpheme's one tag symbol.
    variants: Vec<String>,
    /// Every accepted spelling with this root's own first segment removed ([`stripped_variants`]),
    /// used ONLY by a roots lexicon's `Stripped` sibling (module doc, "Junction-aware affix/root
    /// emission"). Empty when `phon` is `None` (no phonological rules at all — nothing needs it) or
    /// when the root has no segment to strip.
    stripped: Vec<String>,
    /// Compile-time-provable "never valid bare" fact (`pg_rules::validity::allomorphs_valid_impl`'s
    /// `def.is_bound && distinct_count == 1` gate, `FailureReason::BoundRoot` — precision.rs's own
    /// `ConstraintFamily::BoundRoot`, "cannot be the word's only allomorph"): `true` iff this
    /// allomorph's OWNING ENTRY has exactly one allomorph total AND that allomorph is `is_bound`.
    /// For a bare-root candidate (this allomorph alone, no other morph — exactly what the
    /// `"#"`-continuation `Root` lexicon proposes) confirm's `distinct_count` is trivially 1, so
    /// `is_bound` alone already dooms the word; the entry-has-exactly-one-allomorph restriction is
    /// deliberate extra caution (never lose recall) — it sidesteps entirely the disjunctive-
    /// allomorph re-check's cross-allomorph reasoning (`free_fluctuates`/`disjunctive_candidates`), which
    /// does not apply when there is nothing to disjoin against. When `true`, [`collect_roots`]'s
    /// callers must OMIT this `RootRec` from the bare (`"#"`-continuation) `write_root_entries`
    /// call only — every other continuation (`TLPost`, per-group `Roots`, compound chains) still
    /// offers this root normally, since a word with ANY other morph attached is unaffected by this
    /// gate.
    never_valid_bare: bool,
}

#[allow(clippy::too_many_arguments)]
fn collect_roots(
    g: &Grammar,
    uncovered: &mut Vec<UncoveredItem>,
    counts: &mut EmitCounts,
    phon: Option<&PhonologyProbe>,
    cache: &RuleCache,
    morpher: Option<&Morpher>,
    allowed_entries: Option<&HashSet<LexEntryId>>,
    mode: TextMode<'_>,
) -> Vec<RootRec> {
    let mut roots = Vec::new();
    // Stratum order then entry order, mirroring trie.rs's own roots collection (`run()`,
    // trie.rs:966-981) — deterministic Vec walks only.
    for sd in &g.strata {
        // A root allomorph's `Shape` char-def ids are indices into ITS OWN stratum's
        // `CharacterDefinitionTable` (`sd.table`), never necessarily whichever table a caller
        // supplies for the whole function: a multi-table grammar (`Grammar::char_tables.len() > 1`,
        // strata pointing at different, differently-sized tables) can have entries whose char-def
        // ids are only valid in their OWN table, not a grammar-wide constant one. Indexing an
        // earlier stratum's entry against a later stratum's (possibly shorter) table panics rather
        // than refusing, since `CharDefTable::get`'s direct `Vec` index has no bounds check of its
        // own. Resolving the table fresh per stratum, from `sd.table` (the same field
        // `pg_parse::Morpher` already resolves per-rule via an explicit `TableId`), is the same fix
        // class `crate::replace::owning_table` applies to rewrite rules.
        let stratum_table = &g.char_tables[sd.table.0 as usize];
        for &entry_id in &sd.entries {
            // `allowed_entries` (`emit_underlying_templated`, mirrors `uflexc::
            // emit_underlying_filtered`'s own convention exactly — same "not a coverage gap, a
            // DIFFERENT group's lexicon has it" doc): every existing caller passes `None`
            // (unfiltered), so this is a pure no-op there.
            if let Some(allowed) = allowed_entries {
                if !allowed.contains(&entry_id) {
                    continue;
                }
            }
            let entry = &g.entries[entry_id.0 as usize];
            let morpheme_name = g
                .morphemes
                .get(entry.morpheme.0 as usize)
                .map(|m| m.xml_key.as_str())
                .unwrap_or("?");
            for (allo_idx, allo) in entry.allomorphs.iter().enumerate() {
                let label = format!(
                    "entry{}(morpheme={morpheme_name})#allo{allo_idx}",
                    entry_id.0
                );
                // `TextMode::UnderlyingTokens` (`emit_underlying_templated`): ONE token string
                // via `SegAlphabet::encode_shape` — char-def identity already collapses the
                // representation cartesian product [`pattern_variants`] exists for, so that
                // machinery (and the bare-root-phonology enrichment below, which needs a real
                // `Morpher`/surface probe — meaningless in token space) is skipped outright. A
                // lexical PATTERN allomorph (`allo.is_pattern`, a `[ClassName]` bracket shape) is
                // NOT representable here: its `Shape` carries `NO_CHAR_DEF`/class-reference interior
                // nodes `encode_shape` cannot token (module doc, "Not emittable as literal lexc" —
                // same convention, reported not silently dropped); zero occurrences in Aweti
                // (verified: `p6_aweti_diagnostics.rs`'s pattern-root-allomorph count is 0), kept
                // defensive for any future grammar this path is pointed at.
                if let TextMode::UnderlyingTokens(alphabet) = mode {
                    if allo.is_pattern {
                        uncovered.push(UncoveredItem {
                            kind: "pattern-allomorph".to_string(),
                            id: label,
                            reason:
                                "lexical pattern root shapes are not representable as a single \
                                     underlying token string (P6 templated emitter, v1)"
                                    .to_string(),
                        });
                        counts.allomorphs_skipped += 1;
                        continue;
                    }
                    let underlying = alphabet.encode_shape(&allo.shape.shape);
                    roots.push(RootRec {
                        id: allo.id,
                        morpheme: entry.morpheme,
                        category: entry.syn_fs,
                        variants: vec![underlying],
                        stripped: Vec::new(),
                        never_valid_bare: entry.allomorphs.len() == 1 && allo.is_bound,
                    });
                    counts.allomorphs_emitted += 1;
                    continue;
                }
                // [`pattern_variants`] walks the allomorph's own already-parsed `Shape` (built at
                // grammar load by `pg_grammar::segment::segment_with_patterns` for EVERY root
                // allomorph, pattern or not — that module's own doc). For an ordinary literal-text
                // root (no `[ClassName]` bracket syntax at all — every Sena/Indonesian/Amharic
                // root) this is identical, node-for-node, to re-segmenting `allo.shape.text` via
                // [`surface_variants`] (same greedy match already performed once at load time, same
                // representation cartesian product, same dropped `Boundary` nodes) — so switching
                // to it is behavior-preserving for the reference grammars, and additionally
                // NEVER "fails to re-segment" (the shape is already a valid parse; the old
                // `unsegmentable-root` uncovered path this replaces was only ever a defensive
                // fallback per this module's own doc, "Not emittable as literal lexc").
                //
                // A MANDATORY (non-optional, non-iterative) `[ClassName]` node does NOT set
                // `is_pattern` (C#-faithful rule: "a bare mandatory `[Class]` node does NOT
                // qualify... that's a normal trie-indexed root, e.g. `b[Vowel]t`" —
                // `pg_grammar::load::load_root_allomorph`), so a literal-text re-segmentation of
                // `allo.shape.text` fails outright for such a root (the literal string
                // `"b[Vowel]t"` cannot re-segment) even though `is_pattern` alone would not route it
                // to `uncovered`. Routing every root uniformly through the Shape-based path above
                // handles both the pattern and the mandatory-class case with one mechanism.
                let (variants, overflowed) = pattern_variants(stratum_table, &allo.shape.shape);
                if overflowed {
                    uncovered.push(UncoveredItem {
                        kind: "rep-variant-overflow".to_string(),
                        id: label.clone(),
                        reason: format!(
                            "root shape {:?} exceeds {REP_VARIANT_CAP} representation variants; excess spellings dropped",
                            allo.shape.text
                        ),
                    });
                }
                if variants.is_empty() {
                    uncovered.push(UncoveredItem {
                        kind: if allo.is_pattern {
                            "pattern-allomorph".to_string()
                        } else {
                            "unsegmentable-root".to_string()
                        },
                        id: label,
                        reason: format!(
                            "root shape {:?} produced no concrete spelling at all",
                            allo.shape.text
                        ),
                    });
                    counts.allomorphs_skipped += 1;
                    continue;
                }
                // Stripped spellings (module doc, "Junction-aware affix/root emission"): only ever
                // consumed when `phon` is `Some` (a `Stripped` roots lexicon only exists then, see
                // `write_roots_lexicon`); pattern allomorphs don't get one (`stripped_variants`
                // remains text-based — no reference/edge-case grammar needs a stripped pattern
                // root, and an empty `stripped` list can only under-supply the already-upward
                // junction path, never regress it). Overflow on the stripped side is not separately
                // reported for the same reason stage 1 never reported it.
                let stripped = if allo.is_pattern {
                    Vec::new()
                } else {
                    phon.and_then(|_| stripped_variants(stratum_table, &allo.shape.text))
                        .map(|(v, _)| v)
                        .unwrap_or_default()
                };
                let mut variants = variants;
                // Bare-root phonology (gate F3 3b, `languages/suffixing-extension-slot-ordering`'s "mba" and
                // `languages/suffixing-vowel-harmony`'s "duy"/"sueb"): a grammar with real
                // phonological rules can obligatorily change a root's OWN surface even with no
                // morphological rule applied at all (post-nasal voicing, vowel coalescence,
                // gradation/epenthesis at a root-internal consonant cluster) — [`surface_variants`]
                // and [`pattern_variants`] both only ever re-segment the AUTHORED literal text,
                // never running it through the phonological cascade at all. This unions in the
                // REAL post-cascade surface as an extra, upward-safe spelling.
                //
                // [`Morpher::generate_words`] is tried FIRST here (not [`probe_surface`] — the
                // ordering [`struct_extend`] uses, where it's the right one): `probe_surface`
                // ultimately calls `pg_rules::rewrite::probe_apply_rule_cached`, which applies
                // EVERY phonological rule in the stratum UNCONDITIONALLY (`FeatureStruct::EMPTY` as
                // the "current word" — that function's own doc: "no 'which stratum owns this word'
                // entry gate", ported faithfully from C# `SurfacePhonology`, whose whole design
                // brief is exactly that POS-blindness for probing a bare AFFIX shape in isolation).
                // For a BARE ROOT specifically, that is actively WRONG whenever the grammar scopes
                // different phonological rules to different POS in the SAME stratum
                // (`languages/polysynthetic-stratal-derivation-chain`: `prDelReins` is `requiredPartsOfSpeech="posDelR"`
                // only, but `probe_surface` applies it to `posMDC`'s "buiibuii" too, since an empty
                // `FeatureStruct` vacuously satisfies every POS gate — found empirically: it returns
                // "bubu", the OTHER probe root's answer, instead of "buuubuuu"). `generate_words`
                // has no such blind spot (it is the real per-word pipeline, gated on the actual
                // entry's own POS via its real `syn_fs`), so it is the authoritative source whenever
                // a `Morpher` is available (always true here — `morpher` is built whenever `phon` is
                // `Some`, the same condition gating this whole block); `probe_surface` remains the
                // fallback for the defensive case a caller ever runs this with `morpher = None`.
                if phon.is_some() && !allo.is_pattern {
                    if let Ok(feat_shape) = pg_rules::shape_feat::segment_with_features(
                        g,
                        stratum_table,
                        &allo.shape.text,
                    ) {
                        let extra = morpher
                            .and_then(|m| {
                                m.generate_words(entry_id, &[], FeatureStruct::EMPTY)
                                    .into_iter()
                                    .next()
                            })
                            .or_else(|| probe_surface(g, stratum_table, &feat_shape, cache));
                        if let Some(s) = extra {
                            if !s.is_empty() && !variants.contains(&s) {
                                variants.push(s);
                            }
                        }
                    }
                }
                roots.push(RootRec {
                    id: allo.id,
                    morpheme: entry.morpheme,
                    category: entry.syn_fs,
                    variants,
                    stripped,
                    never_valid_bare: entry.allomorphs.len() == 1 && allo.is_bound,
                });
                counts.allomorphs_emitted += 1;
            }
        }
    }
    roots
}

/// The bare-root compile-time discharge: filters `all_roots` down to the subset safe to offer
/// on the `"#"`-continuation (word = this root alone, nothing else) `Root`/`Root` (underlying-token
/// mode) `LEXICON`.
/// [`RootRec::never_valid_bare`] roots are OMITTED here ONLY — every other call site
/// (`TLPost`/`TLPostNoCmp`/per-group `Roots`/compound-chain roots) keeps using the full,
/// unfiltered `all_roots`, since a word with any other morph attached is untouched by the
/// bound-root gate this predicate targets. Zero new states, zero new flags: this removes lexc
/// entry lines (arcs into the accept state) rather than adding machinery, matching the module
/// doc's "deliberate supersets" direction (this is the one place this emitter is allowed to
/// narrow, because the narrowing is PROVEN, not heuristic).
///
/// Defensive floor: if EVERY root would be pruned (a grammar consisting entirely of bound,
/// single-allomorph root entries — a degenerate case no reference/edge-case fixture exercises,
/// since such a root can never appear in ANY valid word, bare or otherwise), the filter backs off
/// and returns `all_roots` unfiltered rather than risk handing the caller an empty list where an
/// empty `LEXICON Root` block would otherwise have no OTHER continuation to fall back on. This can
/// only ever make the emitted network larger (a superset), never narrower than what this function
/// was asked to guarantee is safe to omit — the over-approximation invariant (module doc) never
/// trades away recall for a states/arcs win.
fn bare_admissible_roots<'a>(
    all_roots: &[&'a RootRec],
    counts: &mut EmitCounts,
) -> Vec<&'a RootRec> {
    if !all_roots.is_empty() && all_roots.iter().all(|r| r.never_valid_bare) {
        return all_roots.to_vec();
    }
    let mut out = Vec::with_capacity(all_roots.len());
    for &r in all_roots {
        if r.never_valid_bare {
            counts.bare_root_arcs_pruned += r.variants.len();
            continue;
        }
        out.push(r);
    }
    out
}

// --- Compounding license gate ---------------------------------------------------------------------

/// The two license-gated lexical-entry subsets the `Gate` partitions a reified `Plan`'s
/// `Union(Gate(head-trie) x Gate(non_head-trie))`
/// node would author for `compounding.non-recursive`. Computed directly against `Grammar` here
/// (rather than authored as real `crate::plan::PlanNodeKind::Gate` nodes) because
/// this crate's lexc emitters consult `Grammar` directly rather than a reified
/// `Plan` — this is the concrete stand-in the emitter itself consults instead of a real `Gate`
/// node.
pub(crate) struct CompoundLicense {
    /// Entries licensed to serve as a compound's HEAD stem by at least one `CompoundingRuleDef` in
    /// the grammar.
    pub(crate) head_eligible: HashSet<LexEntryId>,
    /// Entries licensed to serve as a compound's NON-HEAD ("extra root") stem by at least one
    /// `CompoundingRuleDef` in the grammar.
    pub(crate) non_head_eligible: HashSet<LexEntryId>,
}

/// Computes [`CompoundLicense`] for `g`, or `None` if `g` declares no `CompoundingRuleDef` at all
/// (the overwhelmingly common case — this function, and every call site consuming its result, is a
/// pure no-op for a grammar that never uses compounding).
///
/// **The (un)group-awareness contract (load-bearing — never reverse these):**
/// - The three RULE-level restriction fields (`head_prod_restrictions_mpr`,
///   `non_head_prod_restrictions_mpr`; `output_prod_restrictions_mpr` is confirm-only, see below)
///   are tested with [`MprSet::compound_match`] — group-UNAWARE, mirroring C#'s
///   `CompoundMprFeaturesMatch`, the ONLY semantics `pg_rules::morph::synth_compound`/
///   `resolve_non_head_roots` ever apply to these two fields (`morph.rs:2834,2938,3329,3357`).
/// - Each SUBRULE's `required_mpr`/`excluded_mpr` is tested with [`Grammar::mpr_group_ok`] —
///   group-AWARE (`morph.rs:2842,2955`). Using `compound_match` here instead would apply a LOOSER
///   test than confirm does (harmless for propose's over-approximation, but not what confirm
///   verifies against); using the group-aware helper on the RULE-level fields instead (the
///   opposite mistake) would apply a STRICTER test than C# and confirm actually use there, a
///   genuine under-propose/recall-loss bug. This function follows
///   the contract exactly, in the direction that matches `pg_rules::morph` line for line.
///
/// **Head-subrule union, not per-subrule partitions (a documented simplification, not a precision
/// loss):** `synth_compound`'s own gate order tests EVERY subrule's `required_mpr`/`excluded_mpr`
/// against the SAME `word.mpr` (the head's own mpr) before trying that subrule's pattern match — so
/// an entry is head-eligible under rule `r` if it clears `r`'s rule-level gate AND clears AT LEAST
/// ONE subrule's gate. Keeping N separate per-subrule head partitions and unioning their CROSS
/// PRODUCTS with the (subrule-independent) non-head set afterward would be provably equivalent as an
/// upper bound (`∪_sr (H_sr x N) == (∪_sr H_sr) x N` for a fixed `N`) — this function computes the
/// flattened right-hand side directly, a safe simplification (still a superset), not a narrower one.
///
/// **The subrule gate is NEVER applied to the non-head side**: confirm's own
/// `resolve_non_head_roots` tests only `rule.non_head_prod_restrictions_mpr.compound_match`, never
/// any subrule's `required_mpr`/`excluded_mpr`, against a non-head candidate — applying it here would
/// silently narrow past what confirm accepts (an under-propose bug), so this function does not.
///
/// **Grammar-scoped, not per-rule** (mirrors the pre-existing `has_compounding_rules: bool` grain
/// this module's "bounded compound loop" already uses — module doc, "Bounded compound loop"): an
/// entry is admitted if ANY `CompoundingRuleDef` in the grammar licenses it. Union across rules is
/// still a safe superset of any one rule's own exact requirement, and matches the granularity the
/// existing lexc sections (`TLCmp`/`G{gi}Cmp`, shared across every compounding rule) already use.
///
/// **Left to confirm, deliberately** (only language-preserving/widening operations belong in
/// propose): `head_required_syn_fs`/`non_head_required_syn_fs` (syntactic-FS
/// unification), `output_prod_restrictions_mpr`, `out_syn_fs`, `obligatory_features`, and the exact
/// `head_lhs`/`non_head_lhs` pattern match itself. None of those narrow this function's result.
pub(crate) fn compound_license(g: &Grammar) -> Option<CompoundLicense> {
    let mut head_eligible: HashSet<LexEntryId> = HashSet::new();
    let mut non_head_eligible: HashSet<LexEntryId> = HashSet::new();
    let mut any_rule = false;
    for mrule in &g.mrules {
        let MorphRuleDef::Compounding(rule) = mrule else {
            continue;
        };
        any_rule = true;
        for (i, entry) in g.entries.iter().enumerate() {
            let id = LexEntryId(i as u32);
            if rule.head_prod_restrictions_mpr.compound_match(entry.mpr)
                && (rule.subrules.is_empty()
                    || rule
                        .subrules
                        .iter()
                        .any(|sr| g.mpr_group_ok(sr.required_mpr, sr.excluded_mpr, entry.mpr)))
            {
                head_eligible.insert(id);
            }
            if rule
                .non_head_prod_restrictions_mpr
                .compound_match(entry.mpr)
            {
                non_head_eligible.insert(id);
            }
        }
    }
    if !any_rule {
        return None;
    }
    Some(CompoundLicense {
        head_eligible,
        non_head_eligible,
    })
}

/// Resolves a [`RootRec`]'s owning [`LexEntryId`] via `g.allomorph_owners` (the registry
/// [`collect_roots`] itself draws every `RootRec::id` from). `None` for a registry id this grammar's
/// `allomorph_owners` doesn't classify as `AllomorphOwner::Root` (an affix allomorph would never
/// appear in a root list at all, so this is defensive, not expected to fire in practice).
fn root_lex_entry(g: &Grammar, id: AllomorphId) -> Option<LexEntryId> {
    match g.allomorph_owners.get(id.0 as usize)? {
        AllomorphOwner::Root(le, _) => Some(*le),
        AllomorphOwner::Affix(_, _) => None,
    }
}

/// Filters `roots` down to the entries `eligible` licenses (via [`root_lex_entry`]). Used to narrow
/// the compound HEAD/NON-HEAD lexc continuation sections from the maximal `all_roots` bag down to
/// [`compound_license`]'s two subsets.
fn filter_roots_by_license<'a>(
    g: &Grammar,
    roots: &[&'a RootRec],
    eligible: &HashSet<LexEntryId>,
) -> Vec<&'a RootRec> {
    roots
        .iter()
        .copied()
        .filter(|r| root_lex_entry(g, r.id).is_some_and(|le| eligible.contains(&le)))
        .collect()
}

// --- Bounded compound loop (module doc, "Bounded compound loop"): the shared depth-budgeted chain
// -------------------------------------------------------------------------------------------------

/// The depth-budgeted extension of the "bounded compound loop" (module doc) -- a chain of `levels`
/// license-gated non-head-root LEVELS under `base` (e.g. `"TLCmp"`/`"G3Cmp"`), each with its own
/// optional prefix-derivation hop (a prefix on the compound's non-head span, e.g.
/// `lexbedom`/`silamanuk` -- see module doc's "Bounded compound loop" section), realizing every compound
/// depth from 2 stems (head + 1 extra root) up to `1 + levels` stems (head + `levels` extra roots)
/// as accepted paths through ONE compiled network, not `levels` separately-sized copies --
/// `compound_license`'s own license-gated non-head set is reused, UNCHANGED, at every level (this
/// adds depth, never new precision, matching every other over-approximating simplification the
/// module doc's "Deliberate supersets" section already accepts).
///
/// **Byte-identical to the pre-existing single-level construction when `levels == 1`**: level 1 reuses the EXACT
/// pre-existing names (`{base}`, `{base}Pfx`, `{base}Roots`[`Stripped`]) and, since `levels == 1`
/// makes it also the LAST level, its root entries continue DIRECTLY to `exit` -- no dispatcher
/// lexicon is ever written for the single-level case. Level `k >= 2` (only emitted when
/// `levels >= 2`, a genuinely recursive/self-feeding `CompoundingRuleDef`) uses
/// `{base}{k}`/`{base}{k}Pfx`/`{base}{k}Roots`; a level's root entries continue to `exit` directly
/// when it is the LAST level, or to a small `{base}{k}Next` dispatcher (bare-redirecting to BOTH
/// `exit` and level `k+1`'s own entry) otherwise -- so every intermediate depth from 2 up to
/// `1 + levels` stems is a real accepted path, not just the maximum.
///
/// Growth is LINEAR in `levels` (one more `{Pfx,Roots,Next}` triple per level, each sized by the
/// license-gated non-head root count), never exponential in emitted TEXT size --
/// [`DEFAULT_COMPOUND_CHAIN_DEPTH_BUDGET`]'s own doc is the containment for the one input that can
/// still make `levels` itself unreasonably large.
///
/// **Shared by BOTH emitters** (`emit_with_budget_profiled`'s `TextMode::SurfaceProbed` path AND
/// `emit_underlying_templated`'s templated path): one construction, generalized over
/// `mode`/`phon`/`write_root_entries`/`write_stripped_root_entries` exactly the way
/// `build_deriv_chain` (this file's other shared chain-builder) is already generalized over `mode`.
/// A per-emitter unroller could silently drift from this one and, on the templated path, propose
/// fewer compound depths than a rule's own `compounding_max_depth` bound allows even though
/// `CompoundingRecursionSafePredicate` is `ConfirmOnly` unconditionally for `Compounding`
/// (`capability.rs`'s own doc) -- one shared function rules that out by construction.
///
/// `write_prefix_hop`/`write_root_entries`/`write_stripped_root_entries` are supplied by the caller
/// (each emitter's own local closure, capturing that emitter's own `width`/tag-writing convention --
/// mirrors how `build_deriv_chain`'s callers already pass their own `mode`) rather than re-derived
/// here, so this function never needs any emitter's own closure SHAPE.
/// `write_stripped_root_entries` is only ever actually invoked when `emit_stripped` (the caller's own
/// `phon.is_some()`; never true on the templated path or the `crate::uflexc` path, module doc: "No
/// junction probing... under this mode"), so a caller with no real `Stripped` sibling can pass any
/// closure with the right signature; it is provably never called there.
///
/// **Generic over the root record type `R` and the emitter-state type `C`.** The third caller,
/// [`crate::uflexc`], is a deliberately minimal
/// `SegAlphabet`-token-space emitter that shares NONE of this module's emission state: it has no
/// [`RootRec`] (its roots are `(tag, underlying-token)` pairs read straight off `Grammar::entries`),
/// no [`PrecisionEmit`] (no FST precision knob at all), no [`PhonologyProbe`], and -- most
/// importantly -- its own SELF-LOOPING prefix chain rather than this module's rule-count-bounded
/// [`build_deriv_chain`] derivation layers (`crate::uflexc`'s own module doc states that difference
/// as its defining property). Parameterizing this function over those three seams (root record,
/// emitter state, prefix hop) is what lets uflexc reuse the part that would actually DRIFT -- the
/// level naming, the `{base}{k}` / `{base}{k}Pfx` / `{base}{k}Roots` triple, the `{base}{k}Next`
/// dispatcher, and the "last level exits to `exit`" rule -- without importing half of this module's
/// emission machinery into it. Everything removed from the signature here (`g`, `table`, `phon`,
/// `deriv_prefix`, `width`, `mode`, `uncovered`) is now captured by the caller's own prefix-hop
/// closure, so this function got SMALLER, not larger, for gaining a third caller.
///
/// `write_prefix_hop(out, pfx_base, roots_name, counts, ctx)` must define the lexicon
/// **`{pfx_base}0`** -- the name this function has already bare-redirected the level's entry lexicon
/// to before calling it -- and every path through it must exit to `roots_name`.
/// [`build_deriv_chain`] satisfies this by construction (it always defines `{prefix}0` and returns
/// that name).
///
/// Shared shape of `build_compound_chain`'s `write_root_entries`/`write_stripped_root_entries`
/// callback parameters (own doc above): each emitter's own local closure for writing one root
/// group's lexc entries, capturing that emitter's `width`/tag-writing convention.
pub(crate) type RootEntryWriter<'a, R, C> =
    &'a dyn Fn(&mut String, &[&R], &str, &mut EmitCounts, &mut C);

/// Shared shape of [`build_compound_chain`]'s per-level prefix-derivation hop (own doc above):
/// `FnMut` rather than `Fn` because this module's own callers capture `&mut uncovered` in it.
pub(crate) type CompoundPrefixHop<'a, C> =
    &'a mut dyn FnMut(&mut String, &str, &str, &mut EmitCounts, &mut C);

#[allow(clippy::too_many_arguments)]
pub(crate) fn build_compound_chain<R, C>(
    out: &mut String,
    base: &str,
    levels: usize,
    non_head_roots: &[&R],
    all_roots: &[&R],
    exit: &str,
    counts: &mut EmitCounts,
    ctx: &mut C,
    emit_stripped: bool,
    write_prefix_hop: CompoundPrefixHop<'_, C>,
    write_root_entries: RootEntryWriter<'_, R, C>,
    write_stripped_root_entries: RootEntryWriter<'_, R, C>,
) {
    let levels = levels.max(1);
    for k in 1..=levels {
        let entry_name = if k == 1 {
            base.to_string()
        } else {
            format!("{base}{k}")
        };
        let pfx_base = if k == 1 {
            format!("{base}Pfx")
        } else {
            format!("{base}{k}Pfx")
        };
        let roots_name = if k == 1 {
            format!("{base}Roots")
        } else {
            format!("{base}{k}Roots")
        };
        let continuation = if k == levels {
            exit.to_string()
        } else {
            format!("{base}{k}Next")
        };

        write_lexicon_header(out, &entry_name);
        write_bare(out, &format!("{pfx_base}0"), counts);
        write_prefix_hop(out, &pfx_base, &roots_name, counts, ctx);
        write_lexicon_header(out, &roots_name);
        write_root_entries(out, non_head_roots, &continuation, counts, ctx);
        if emit_stripped {
            write_lexicon_header(out, &format!("{roots_name}Stripped"));
            write_stripped_root_entries(out, all_roots, &continuation, counts, ctx);
        }

        if k < levels {
            write_lexicon_header(out, &continuation);
            write_bare(out, exit, counts);
            write_bare(out, &format!("{base}{}", k + 1), counts);
        }
    }
}

/// Consumes `crate::capability::characterize`'s precomputed `CompoundingDetail::max_depth` (one
/// source of truth -- this crate never re-derives it) into `compound_extra_levels`, the number of
/// NON-HEAD levels [`build_compound_chain`] should unroll (`max_depth - 1`, floored at 1 so an
/// ordinary non-recursive grammar -- `max_depth == 2` -- gets EXACTLY the pre-existing "one extra
/// root" shape, never fewer) -- and checks that number against [`DEFAULT_COMPOUND_CHAIN_DEPTH_BUDGET`]
/// BEFORE any of the chain's own lexc text is written (same "check the search result before the
/// expensive part" discipline as the compound-pair-budget check every caller runs just before this).
///
/// Shared by both emitters so this budget discipline can never drift between them --
/// mirrors [`build_compound_chain`]'s own "one construction" rationale.
///
/// `Err(EmitResult)` is the caller's own early-return refusal outcome (`FomaTier::Unsupported`, a
/// typed `EnumBudgetExceeded`, never a partial/unsound network), built from the `uncovered`/`counts`
/// snapshot passed in -- the caller should `return` it exactly as received.
///
/// `result_large_err` is allowed deliberately, not overlooked: the `Err` payload IS the emitter's
/// full `EmitResult` (192 bytes), because the refusal is a COMPLETE, honest emit outcome carrying its
/// own `uncovered`/`counts` diagnostics, not an error code the caller enriches later -- the whole
/// point is that the caller returns it verbatim. Boxing it would add an allocation and a pointer
/// chase on the refusal path purely to satisfy a size heuristic, and would make the "return it
/// exactly as received" contract above less obvious at both call sites. This is the same
/// documented-allow discipline `pg_rules::cache`'s own `large_enum_variant` note uses.
#[allow(clippy::result_large_err)]
fn compound_chain_depth_and_budget_check(
    g: &Grammar,
    uncovered: &[UncoveredItem],
    counts: &EmitCounts,
) -> Result<usize, EmitResult> {
    let compound_depth_bound = compound_depth_bound(g);
    let (depth, limit) = match compound_extra_levels_checked(g) {
        Ok(levels) => return Ok(levels),
        Err(ComposeError::ChainDepthExceeded { depth, limit, .. }) => (depth, limit),
        Err(other) => unreachable!(
            "compound_extra_levels_checked only ever fails with ChainDepthExceeded: {other}"
        ),
    };
    {
        let reason = format!(
            "compound chain depth ({depth} extra non-head compound-root level(s), from a computed \
             max_depth of {compound_depth_bound} total stems across this grammar's CompoundingRule(s)) \
             exceeds this path's compound chain-depth budget (limit {limit}). This grammar's \
             self-feeding compounding recursion is deeper than this construction will unroll -- raise \
             HC_COMPOUND_CHAIN_DEPTH_BUDGET only if you understand why this grammar's compounding \
             recursion is this deep, or fall back to another engine for this grammar. Never silently \
             truncated: an honest refusal, not a partial/unsound network."
        );
        return Err(EmitResult {
            lexc_source: String::new(),
            report: EmitReport {
                uncovered: uncovered.to_vec(),
                counts: counts.clone(),
                tier: FomaTier::Unsupported { reason },
                enum_budget_exceeded: Some(EnumBudgetExceeded {
                    measure: "compound chain depth (extra non-head root levels)",
                    value: depth,
                    limit,
                }),
            },
        });
    }
}

/// The grammar-wide total-stem bound `crate::capability::characterize` already computed for every
/// `CompoundingRuleDef` (one source of truth -- this crate never re-derives it), defaulting to 2
/// (head + one non-head) for a grammar whose rules declare nothing deeper.
fn compound_depth_bound(g: &Grammar) -> usize {
    crate::capability::characterize(g)
        .compounding_details()
        .map(|d| d.max_depth)
        .max()
        .unwrap_or(2)
}

/// [`compound_chain_depth_and_budget_check`]'s computation and budget check, with the TYPED
/// [`ComposeError`] as its error rather than that function's `EmitResult` refusal payload -- what a
/// caller whose own error type is `ComposeError` (`crate::uflexc`, whose whole public surface is
/// `Result<UEmitReport, ComposeError>`) calls instead, so uflexc's compound loop shares this
/// module's depth bound and budget discipline verbatim rather than re-deriving either.
///
/// `compound_chain_depth_and_budget_check` is now a thin front end onto this that additionally
/// renders the `FomaTier::Unsupported`/`EnumBudgetExceeded` refusal the two `EmitResult`-returning
/// emitters need -- the same "one construction, two presentations" split
/// [`build_compound_chain`]'s own doc uses.
pub(crate) fn compound_extra_levels_checked(g: &Grammar) -> Result<usize, ComposeError> {
    let compound_extra_levels = compound_depth_bound(g).saturating_sub(1).max(1);
    ComposeBudget::from_env()
        .with_chain_depth_cap(compound_chain_depth_budget())
        .check_chain_depth(
            compound_extra_levels,
            "compound loop (extra non-head root levels)",
        )?;
    Ok(compound_extra_levels)
}

// --- Affix entry emission (shared by slot chains and derivation layers) ---------------------------

/// Emit every emittable allomorph of `mid` as one tagged lexc entry with continuation `next`,
/// requiring each allomorph's role to be `zone_role` (or `None` — a zero morph is legal in either
/// zone, exactly like `trie.rs::append_slots`'s `aop != op && aop != MorphOp::None` check,
/// trie.rs:941-946).
///
/// `phon` (module doc, "Junction-aware affix/root emission"): when `Some`, every `InsertText::Text`
/// allomorph ALSO gets [`PhonologyProbe::variants`]'s spellings unioned into `next` (safe at any
/// zone/level: these are context-generic, upward-only additions to what stage 1 already emits).
/// `junction_target`, when `Some`, additionally routes every [`PhonologyProbe::deletion_junctions`]
/// hit to THAT lexicon instead of `next` — callers only pass it at a genuinely root-adjacent final
/// derivation level (see `build_deriv_chain`); everywhere else it's `None` and this behaves exactly
/// like stage 1.
///
/// `pk` (`crate::precision`'s module doc): every entry this function writes for allomorph `allo`
/// passes `Some(allo.id)` as [`write_tag_entry`]'s owner — the ENVIRONMENT family's `AllFlags`
/// preset's owner-side require/disallow gate can then find it regardless of which zone/level/slot
/// this call is emitting into.
#[allow(clippy::too_many_arguments)]
fn emit_rule_allomorphs(
    out: &mut String,
    g: &Grammar,
    table: &CharDefTable,
    mid: MRuleId,
    zone_role: Role,
    width: usize,
    next: &str,
    uncovered: &mut Vec<UncoveredItem>,
    counts: &mut EmitCounts,
    phon: Option<&PhonologyProbe>,
    junction_target: Option<&str>,
    pk: &mut PrecisionEmit,
    mode: TextMode<'_>,
) {
    let morpheme = owning_morpheme(g, mid);
    let tag_lexc = tags::morph_tag_lexc(morpheme, width);
    for (allo_idx, allo) in allomorphs_of(g, mid).iter().enumerate() {
        let label = format!("mrule{}#allo{allo_idx}", mid.0);
        if has_unemittable_action(&allo.rhs) {
            uncovered.push(UncoveredItem {
                kind: "process-morph".to_string(),
                id: label,
                reason: "Modify/InsertContext action has no literal text to emit (v1)".to_string(),
            });
            counts.allomorphs_skipped += 1;
            continue;
        }
        let role = classify_affix(&allo.rhs);
        if role != zone_role && role != Role::None {
            uncovered.push(UncoveredItem {
                kind: role.label().to_string(),
                id: label,
                reason: format!(
                    "allomorph classifies as {role:?} but its rule is referenced in a {zone_role:?} position"
                ),
            });
            counts.allomorphs_skipped += 1;
            continue;
        }
        let owner = Some(allo.id);
        match insert_action_texts(&allo.rhs) {
            InsertText::None => {
                write_tag_entry(out, &tag_lexc, "", next, counts, pk, owner);
                counts.allomorphs_emitted += 1;
            }
            // `TextMode::UnderlyingTokens`: concatenate EVERY `InsertSegments` action's own
            // token string via `SegAlphabet::encode_shape`, in document order (`InsertText::Text`'s
            // own doc: never just the first) — no surface_variants cartesian product, no
            // `phon`/junction-probe consultation at all (module doc on `TextMode`; each action's
            // own underlying spelling is exactly what its `Shape` already is, char-def identity
            // collapsing the representation question the SurfaceProbed arm below exists to solve).
            // `encode_shape` keeps Boundary nodes (e.g. the affix's own trailing `+`) — the rule
            // cascade's own environments need them.
            InsertText::Text { shapes, .. } if matches!(mode, TextMode::UnderlyingTokens(_)) => {
                let TextMode::UnderlyingTokens(alphabet) = mode else {
                    unreachable!()
                };
                let underlying: String = shapes
                    .iter()
                    .map(|shape| alphabet.encode_shape(shape))
                    .collect();
                write_tag_entry(out, &tag_lexc, &underlying, next, counts, pk, owner);
                if let Some(marker) = crate::structural_allomorph::structural_marker(g, allo) {
                    write_tag_entry(out, &tag_lexc, &marker.to_string(), next, counts, pk, owner);
                }
                counts.allomorphs_emitted += 1;
            }
            InsertText::Text { texts, .. } => {
                let mut emitted_any = false;
                match surface_variants_concat(table, &texts) {
                    Some((variants, overflowed)) => {
                        if overflowed {
                            uncovered.push(UncoveredItem {
                                kind: "rep-variant-overflow".to_string(),
                                id: label.clone(),
                                reason: format!(
                                    "affix insert text {texts:?} exceeds {REP_VARIANT_CAP} representation variants; excess spellings dropped"
                                ),
                            });
                        }
                        for surface in &variants {
                            write_tag_entry(out, &tag_lexc, surface, next, counts, pk, owner);
                        }
                        emitted_any = true;
                    }
                    None => {
                        uncovered.push(UncoveredItem {
                            kind: "unsegmentable-affix".to_string(),
                            id: label.clone(),
                            reason: format!(
                                "affix insert text {texts:?} does not re-segment against the surface char-def table"
                            ),
                        });
                    }
                }
                // Junction-aware enrichment (module doc): union in every probe-derived surface
                // spelling, and (only where the caller says this level is root-adjacent) route
                // deletion-junction spellings to the stripped-roots continuation instead. The probe
                // takes one literal string; every piece is joined in document order first (an
                // upward-only, harmless-anywhere approximation for the 2+-piece case, same
                // convention as the rest of this enrichment -- module doc, "Junction-aware
                // affix/root emission" -- byte-identical to the pre-fix single-piece call when
                // `texts.len() == 1`).
                if let Some(probe) = phon {
                    let joined: String = texts.concat();
                    for surface in probe.variants(&joined) {
                        write_tag_entry(out, &tag_lexc, &surface, next, counts, pk, owner);
                        emitted_any = true;
                    }
                    if let Some(target) = junction_target {
                        for surface in probe.deletion_junctions(&joined) {
                            write_tag_entry(out, &tag_lexc, &surface, target, counts, pk, owner);
                            emitted_any = true;
                        }
                    }
                }
                if emitted_any {
                    counts.allomorphs_emitted += 1;
                } else {
                    counts.allomorphs_skipped += 1;
                }
            }
        }
    }
}

// --- Derivation layer chain (trie.rs::build_derivation_layer) -------------------------------------

/// Emit a chain of optional derivation layers named `{prefix}0` .. `{prefix}{depth-1}`, ending at
/// `exit`. Mirrors `trie.rs::build_derivation_layer` (each level: an epsilon skip to the next
/// level plus one token+arc path per rule allomorph). Always defines `{prefix}0`, even when
/// `rules` is empty (a plain passthrough), so callers can reference it unconditionally.
///
/// Two distinct level-assignment strategies, gated on `mode`:
/// - [`TextMode::SurfaceProbed`] (legacy, unchanged): EVERY level offers EVERY rule in `rules`;
///   depth = `rules.len()` floored at [`DERIV_DEPTH_MIN`] (module doc: the engine-faithful bound
///   for `multipleApplication = 1` — each rule can apply at most once, so no derivation chain is
///   longer than the rule count).
/// - [`TextMode::UnderlyingTokens`] ("dedicated-level-per-rule"): level `i` offers ONLY
///   `rules_expanded[i]` (a rule with `max_apps() == k > 1` gets `k` CONSECUTIVE dedicated levels,
///   capped at [`MAX_DEDICATED_LEVELS_PER_RULE`] — every Aweti rule has `max_apps() == 1`, so this
///   cap is never exercised there; it exists only to bound a hypothetical uncapped/Realizational
///   rule, which this codebase's dedicated mode does not attempt to represent faithfully beyond
///   the cap). This eliminates the "same rule chosen at any of N levels, N times independently"
///   nondeterminism the legacy strategy has — measured on Aweti: a single epsilon-yielding rule
///   could have its tag chosen up to 22x (prefix) / 48x (suffix)
///   along one path under the legacy strategy; dedicated levels bound that to (at most) the
///   number of independent chain INSTANCES a path crosses (2, for a template-taking word: this
///   chain instance once, the OTHER same-zone instance — e.g. `OuterPfx` vs `G{gi}PfxD` — once).
///   COST: this fixes the RELATIVE SURFACE ORDER of any two standalone rules chosen within the
///   SAME chain instance to `rules`' own document order (previously free at any two of the
///   `rules.len()` levels) — a real recall risk if some oracle analysis needs two standalone rules
///   in the OTHER order; the corpus recall gate is the judge (measured on Aweti specifically: no
///   regression observed).
///
/// `phon`/`exit_is_roots` (module doc, "Junction-aware affix/root emission"): `phon` is unioned
/// into every affix spelling at EVERY level (harmless anywhere). Deletion-junction routing to a
/// `{exit}Stripped` roots lexicon additionally requires `zone_role == Role::Prefix`,
/// `exit_is_roots` (the caller vouches that `exit` names an actual roots lexicon — never true for
/// `OuterPfx`'s `TmplDispatch` exit or a template slot chain's exit, which are never root-adjacent
/// by construction; passing `true` there would emit a dangling lexc reference), and only fires at
/// the chain's FINAL level (`next == exit`, i.e. genuinely root-adjacent — an intermediate level's
/// `next` is another derivation opportunity, not a root).
#[allow(clippy::too_many_arguments)]
fn build_deriv_chain(
    out: &mut String,
    g: &Grammar,
    table: &CharDefTable,
    prefix: &str,
    zone_role: Role,
    rules: &[MRuleId],
    width: usize,
    exit: &str,
    uncovered: &mut Vec<UncoveredItem>,
    counts: &mut EmitCounts,
    phon: Option<&PhonologyProbe>,
    exit_is_roots: bool,
    pk: &mut PrecisionEmit,
    mode: TextMode<'_>,
) -> String {
    let entry_name = format!("{prefix}0");
    if rules.is_empty() {
        write_lexicon_header(out, &entry_name);
        write_bare(out, exit, counts);
        return entry_name;
    }
    let junction_target = if zone_role == Role::Prefix && exit_is_roots && phon.is_some() {
        Some(format!("{exit}Stripped"))
    } else {
        None
    };

    // `dedicated` is `Some(expanded)` under the dedicated strategy (one rule per level) or `None`
    // under the legacy strategy (every level's per-rule loop below runs the full `rules` slice
    // instead) — a single shared level-emission loop follows so the two strategies can never
    // diverge in how they write lexicon headers/epsilon-skip arcs/junction routing.
    let dedicated: Option<Vec<MRuleId>> = match mode {
        TextMode::UnderlyingTokens(_) => {
            let mut expanded = Vec::with_capacity(rules.len());
            for &mid in rules {
                let reps = (g.mrules[mid.0 as usize].max_apps() as usize)
                    .clamp(1, MAX_DEDICATED_LEVELS_PER_RULE);
                expanded.extend(std::iter::repeat_n(mid, reps));
            }
            Some(expanded)
        }
        TextMode::SurfaceProbed => None,
    };
    let depth = match &dedicated {
        Some(expanded) => expanded.len().max(DERIV_DEPTH_MIN),
        None => rules.len().max(DERIV_DEPTH_MIN),
    };

    for level in 0..depth {
        let name = format!("{prefix}{level}");
        write_lexicon_header(out, &name);
        let is_final = level + 1 == depth;
        let next = if is_final {
            exit.to_string()
        } else {
            format!("{prefix}{}", level + 1)
        };
        // The whole level is optional (trie: `add_epsilon(current, after)` before the per-rule
        // arcs, trie.rs:807-808) — kept identically for BOTH strategies.
        write_bare(out, &next, counts);
        let junction_here = if is_final {
            junction_target.as_deref()
        } else {
            None
        };
        match &dedicated {
            Some(expanded) => {
                // Dedicated-level-per-rule: this level offers AT MOST one rule (a level past the
                // end of `expanded`, from the `DERIV_DEPTH_MIN` floor on a short `rules`, offers
                // none — a harmless extra optional hop).
                if let Some(&mid) = expanded.get(level) {
                    emit_rule_allomorphs(
                        out,
                        g,
                        table,
                        mid,
                        zone_role,
                        width,
                        &next,
                        uncovered,
                        counts,
                        phon,
                        junction_here,
                        pk,
                        mode,
                    );
                }
            }
            None => {
                // Legacy strategy: every level offers every rule (unchanged).
                for &mid in rules {
                    emit_rule_allomorphs(
                        out,
                        g,
                        table,
                        mid,
                        zone_role,
                        width,
                        &next,
                        uncovered,
                        counts,
                        phon,
                        junction_here,
                        pk,
                        mode,
                    );
                }
            }
        }
    }
    entry_name
}

// --- Slot chains (trie.rs::classify_template + append_slots) --------------------------------------

/// `trie.rs::slot_op` (C# `SlotOp`, `FstTemplateAnalyzer.cs:1238-1254`): a slot's zone is that of
/// its first Prefix/Suffix-classified rule; a slot with only zero-morph rules counts as Suffix.
fn slot_role(g: &Grammar, slot: &SlotDef) -> Role {
    let mut has_zero = false;
    for &mid in &slot.rules {
        let role = rule_role(g, mid);
        if role == Role::Prefix || role == Role::Suffix {
            return role;
        }
        if role == Role::None {
            has_zero = true;
        }
    }
    if has_zero {
        Role::Suffix
    } else {
        Role::None
    }
}

/// `trie.rs::classify_template`: split a template's slots into prefix (REVERSED to surface order)
/// and suffix lists, routing any exotic-op slot rule to `uncovered`.
fn classify_template<'g>(
    g: &'g Grammar,
    template: &'g pg_grammar::model::AffixTemplateDef,
    uncovered: &mut Vec<UncoveredItem>,
) -> (Vec<&'g SlotDef>, Vec<&'g SlotDef>) {
    let mut prefix = Vec::new();
    let mut suffix = Vec::new();
    for slot in &template.slots {
        match slot_role(g, slot) {
            Role::Prefix => prefix.push(slot),
            Role::Suffix => suffix.push(slot),
            _ => {
                for &mid in &slot.rules {
                    let role = rule_role(g, mid);
                    if role != Role::Prefix && role != Role::Suffix && role != Role::None {
                        uncovered.push(UncoveredItem {
                            kind: role.label().to_string(),
                            id: format!("mrule{}", mid.0),
                            reason: format!(
                                "template slot rule's primary allomorph classifies as {role:?}; slot dropped (v1, mirrors trie.rs classify_template)"
                            ),
                        });
                    }
                }
            }
        }
    }
    prefix.reverse();
    (prefix, suffix)
}

/// `trie.rs::append_slots`: emit one lexicon per slot, in order, each offering every (unifiable,
/// zone-fitting) rule allomorph once; optional slots add an epsilon skip. Chain is named
/// `{prefix}0` .. and ends at `exit`; always defines `{prefix}0` (passthrough when `slots` is
/// empty).
///
/// `phon` (module doc, "Junction-aware affix/root emission"): unioned into every slot allomorph's
/// spelling, same as [`build_deriv_chain`]. No junction routing here — a template slot chain's
/// `exit` is never a roots lexicon directly (it always lands on further derivation, `G{gi}PfxD0` or
/// `OuterSfx0`/`G{gi}Join`), so there is no root-adjacent final level to gate on.
#[allow(clippy::too_many_arguments)]
fn build_slot_chain(
    out: &mut String,
    g: &Grammar,
    table: &CharDefTable,
    prefix: &str,
    slots: &[&SlotDef],
    zone_role: Role,
    template_category: FsId,
    width: usize,
    exit: &str,
    uncovered: &mut Vec<UncoveredItem>,
    counts: &mut EmitCounts,
    phon: Option<&PhonologyProbe>,
    pk: &mut PrecisionEmit,
    mode: TextMode<'_>,
) -> String {
    let entry_name = format!("{prefix}0");
    if slots.is_empty() {
        write_lexicon_header(out, &entry_name);
        write_bare(out, exit, counts);
        return entry_name;
    }
    for (si, slot) in slots.iter().enumerate() {
        let name = format!("{prefix}{si}");
        write_lexicon_header(out, &name);
        let next = if si + 1 == slots.len() {
            exit.to_string()
        } else {
            format!("{prefix}{}", si + 1)
        };
        if slot.optional {
            write_bare(out, &next, counts);
        }
        for &mid in &slot.rules {
            // trie.rs::append_slots's rule-level category gate (trie.rs:933-939): skip a slot
            // rule whose own requirement can't unify with the template's category.
            let req = required_category(g, mid);
            let req_fs = g.fs_interner.get(req);
            if !req_fs.is_empty() {
                let tmpl_fs = g.fs_interner.get(template_category);
                if !is_unifiable(tmpl_fs, req_fs) {
                    continue;
                }
            }
            emit_rule_allomorphs(
                out, g, table, mid, zone_role, width, &next, uncovered, counts, phon, None, pk,
                mode,
            );
        }
    }
    entry_name
}

// --- Structural composites: rules `crate::preexpand` cannot represent at all ---------------------
//
// The conformance suite's `edge-cases/
// truncate-morphotactic` and `languages/suffixing-vowel-harmony` fixtures exercise two related gaps
// `crate::preexpand`'s rule-application composite mechanism does not close:
//
// 1. **Truncation/subtraction rules.** [`classify_affix`] only inspects RHS `Copy`/`Insert`
//    POSITIONS, blind to whether the rule's LHS pattern has more than one top-level part and, if
//    so, whether every part survives into the RHS as a `Copy`. A rule whose entire RHS is a single
//    `Copy` of one LHS part while the LHS has more than one part classifies `Role::None`
//    (`classify_affix` sees exactly one `Copy` action and no leading/trailing insert) — and
//    `build_deriv_chain`'s "Role::None is legal in either zone" convention then treats it as a pure
//    ZERO MORPH, silently reproducing the UNTRUNCATED root text. That is not merely
//    unrepresentable (module doc "Not emittable as literal lexc" undersold this); the EXISTING
//    handling actively emits the wrong surface whenever the rule genuinely deletes a segment
//    (`edge-cases/truncate-morphotactic`'s `mruleTruncTrail`/`mruleTruncLead`: "sag"->"sa"/"ag"). A
//    `Role::Prefix`/`Suffix` rule can have the same problem when part of its LHS is an OPTIONAL
//    segment that is sometimes consumed (not copied) — `mruleTruncOptIns`: an optional leading "s"
//    that vanishes from the output exactly when present ("sas"->"gas", not the naive "g"+"sas" =
//    "gsas"). [`is_structural_rule`] identifies exactly this LHS shape.
// 2. **A grammar whose own phonological cascade defeats `crate::preexpand`'s probe.**
//    `pg_rules::surface_probe::probe_synthesize` — the build-time probe `crate::preexpand` drives
//    to get a rule-application's real, phonology-resolved surface — unconditionally REFUSES
//    (`pg_rules::rewrite::probe_synthesize_stratum`'s `Kind::Epenthesis`/`PhonRuleDef::Metathesis`
//    arms) the moment its cascade reaches an epenthesis-kind rewrite subrule (empty
//    `<PhoneticInput>`) or ANY `<MetathesisRule>` — REGARDLESS of whether that specific rule
//    actually fires for the shape being probed. Verified empirically against `languages/
//    suffixing-vowel-harmony` (has a real `prEpenthesis`): `crate::preexpand` probes 16 candidate
//    (root, rule) pairs and emits ZERO fusion/interdigitation composites — every one of the
//    grammar's ordinary suffix rules (`mrPast`/`mrPres`/`mrPlural`/`mrAlphaSuf`) and its infix rule
//    (`ruleInfixDemo`) needs the harmony/gradation/epenthesis cascade to reach its real surface
//    ("kutak"+"de" -> "kutagida"), and every probe for this stratum refuses outright. See
//    [`probe_would_refuse`] for the static (per-grammar, not per-word) detection this implies.
//
// Both are closed the SAME way [`crate::preexpand`] closes interdigitation/fusion: drive the REAL
// synthesis machinery ([`pg_rules::morph::synthesize`], not a re-implementation) against each root
// allomorph and recursively against the result (bounded, [`STRUCT_MAX_EXTRA_RULES`] — needed for
// `truncate-morphotactic`'s "gas", whose second analysis chains `mruleTruncLead` into
// `mruleTruncOptIns`), for [`structural_candidate_rules`]'s rule set. For the SURFACE: try
// [`probe_surface`] first (cheap, exact for this specific shape); when it's refused, fall back to
// [`Morpher::generate_words`] — the engine's OWN real per-word generation pipeline (used elsewhere
// in this crate by nothing else; a fresh, independent path from the probe, with no refusal case at
// all) — for the WHOLE chain applied so far. Composite entries are reused directly
// ([`crate::preexpand::CompositeRec`]) and merged into the SAME shared `Composites`/`CompositeExit`
// wiring `emit`'s "LEXICON Root" comment documents, so a structural composite stem is reachable
// exactly where an ordinary root or a preexpand composite is — no further chaining through
// non-structural rules is needed here (ordinary continuing morphology after a structural stem is
// already reachable through that shared wiring).
//
// Zero-cost, zero-entry for a grammar with no structural rule and no probe-refusing construct
// (Sena, Indonesian, Amharic: verified — zero `<MetathesisRule>`/empty-`<PhoneticInput>` elements
// in any of the three reference grammars' XML) — [`structural_candidate_rules`] returns empty and
// [`build_structural_composites`] returns immediately, preserving every existing gate byte-for-byte
// in the sense that matters (`crate::preexpand`'s own composites, and everything else this emitter
// already produced, are completely unchanged; this section only ever ADDS entries).
//
// Morphotactic pruning (`crate::morphotactics`) -- the Aweti scale fix: [`struct_extend`]'s flat
// depth-3 recursion below is pruned by the SAME
// automaton `crate::preexpand::extend` consults (`crate::morphotactics::MorphotacticIndex::
// next_state`), built once by [`emit_with_precision`] and shared across both builders — see
// `crate::preexpand`'s own module-doc addendum for the full design.

/// Bound on a structural composite chain's length beyond the root — same rationale as
/// `crate::preexpand::MAX_EXTRA_RULES` (module doc there): `edge-cases/truncate-morphotactic`'s
/// "gas" needs depth 2 (`mruleTruncLead` then `mruleTruncOptIns`); 3 leaves headroom the same way
/// preexpand's own constant does, with the same recall-gate backstop if a grammar ever needs more.
const STRUCT_MAX_EXTRA_RULES: usize = 3;

/// Does `allo`'s RHS drop at least one of its own LHS's top-level `<PhoneticSequence>` parts —
/// i.e. does some `PartRef::Input(i)` in `0..allo.lhs.len()` never appear as an `OutputAction::Copy`
/// anywhere in `allo.rhs`? A multi-part LHS where every part IS copied (in any order, interleaved
/// with inserts or not) drops nothing — that's ordinary interdigitation (`Role::Infix`,
/// `crate::preexpand`'s own job) or a ordinary affix whose LHS just happens to be split into
/// several trivial parts; only an UNCOPIED part is real subtracted material (module doc, item 1).
fn rhs_drops_lhs_material(a: &AffixAllomorphDef) -> bool {
    if a.lhs.len() <= 1 {
        return false;
    }
    let copied: BTreeSet<u16> = a
        .rhs
        .iter()
        .filter_map(|act| match act {
            OutputAction::Copy(PartRef::Input(i)) => Some(*i),
            _ => None,
        })
        .collect();
    (0..a.lhs.len() as u16).any(|i| !copied.contains(&i))
}

/// A rule's LHS drops (or, via an optional part, sometimes drops) real root material into the
/// surface, something no OTHER site in this emitter accounts for (module doc, item 1) —
/// [`rhs_drops_lhs_material`] on at least one allomorph. Scoped to the three roles
/// [`build_deriv_chain`]/[`emit_rule_allomorphs`] already accept in a `Prefix`/`Suffix` zone
/// (`Role::None`/`Role::Prefix`/`Role::Suffix`) — `Role::Infix` is `crate::preexpand`'s own job
/// (module doc, item 2, covers the case where it ALSO needs this mechanism); `CircumfixPrefix`/
/// `Reduplication`/`Process` remain `uncovered`'s job, unchanged.
///
/// `pub(crate)` (widened from private, no body change): `crate::capability::
/// CircumfixStructuralCompositePredicate` calls this directly to decide whether a given
/// `CircumfixOutputAction` observation's owning rule actually reaches the faithful, oracle-backed
/// [`build_structural_composites`] construction — the same "predicate reads the identical
/// structural fact the real compile path branches on, not a re-derivation of it" precedent
/// [`probe_would_refuse`]/[`structural_candidate_rules`] already set.
/// Whether ANY allomorph of `mid` classifies [`Role::CircumfixPrefix`] — unlike [`rule_role`],
/// which inspects allomorph 0 only. [`is_structural_rule`]'s own question is "would ANY allomorph of
/// this rule need [`build_structural_composites`]", so it must not miss a circumfix-shaped allomorph
/// declared at index ≥ 1 merely because allomorph 0 happens to classify as something else (this gap
/// is order-of-declaration-dependent — it appears and disappears purely as a grammar author
/// reorders a rule's allomorphs, which is what makes it worth fixing here rather than documenting
/// as a boundary).
///
/// Deliberately NOT a change to `rule_role`'s own contract: `rule_role`'s other call sites
/// (`slot_role`/`classify_template` — deciding a template slot's prefix/suffix zone — and the
/// standalone-derivation-rule classification duplicated in `emit_with_budget_profiled`, both
/// faithful ports of `trie.rs`'s own "a rule's primary role, from its FIRST allomorph" convention,
/// `rule_role`'s own doc comment) answer a DIFFERENT question — which concatenative zone a rule's
/// literal-lexc tag belongs in — where "primary allomorph decides" is the intended, HC-faithful
/// semantics, not an oversight. `crate::peel::is_reduplication_rule` does not call `rule_role` at
/// all; it already calls `classify_affix` directly with its own `.any()` scan for the same reason
/// this helper exists (that function's own doc contrasts the two aggregations explicitly). Adding a
/// second, narrowly-scoped helper here keeps every one of those other sites byte-for-byte unchanged.
fn any_allomorph_is_circumfix_prefix(g: &Grammar, mid: MRuleId) -> bool {
    allomorphs_of(g, mid)
        .iter()
        .any(|a| classify_affix(&a.rhs) == Role::CircumfixPrefix)
}

pub(crate) fn is_structural_rule(g: &Grammar, mid: MRuleId) -> bool {
    if let MorphRuleDef::AffixProcess(def) = &g.mrules[mid.0 as usize] {
        if !g.fs_interner.get(def.out_syn_fs).is_empty()
            && allomorphs_of(g, mid)
                .iter()
                .all(|a| classify_affix(&a.rhs) == Role::None)
        {
            return true;
        }
    }
    // Check EVERY allomorph for `CircumfixPrefix`, not just the one `rule_role` reports from
    // allomorph 0. Safe to check unconditionally before the `match` below — if allomorph 0 itself
    // is `CircumfixPrefix`, `rule_role` already agrees and the `match` arm just below would return
    // `true` anyway; this only ADDS the case a first-allomorph-only check would miss.
    if any_allomorph_is_circumfix_prefix(g, mid)
        || allomorphs_of(g, mid)
            .iter()
            .any(|a| has_unemittable_action(&a.rhs))
    {
        return true;
    }
    match rule_role(g, mid) {
        Role::None | Role::Prefix | Role::Suffix => {
            allomorphs_of(g, mid).iter().any(rhs_drops_lhs_material)
        }
        // A circumfix (`Insert`-before + `Copy` + `Insert`-after, ONE discontinuous morpheme
        // wrapping the root on BOTH sides) is unconditionally unrepresentable by this emitter's
        // ordinary concatenative model (separate, independently-combinable prefix/suffix
        // derivation layers — module doc "Not emittable as literal lexc" lists it explicitly) --
        // `metathesis-phase-isolation`'s "keadilan" (ke-adil-an) and `fusional-realizational-morphology`'s "gelobt"/"gelobth"
        // (ge-lob-t[-h]) need it, and neither grammar has a probe-refusing construct, so this is
        // ALWAYS-on, not gated by `probe_would_refuse` the way ordinary Prefix/Suffix/Infix is.
        // (Reached only when allomorph 0 itself is `CircumfixPrefix` — the check above already
        // returned `true` for any OTHER allomorph being `CircumfixPrefix`.)
        Role::CircumfixPrefix => true,
        // Process allomorphs cannot be emitted literally, but the structural-composite builder
        // replays `pg_rules::morph::synthesize` and therefore handles Modify/InsertContext without
        // approximating their segment effects. Keep the complete analyzer as confirmation.
        Role::Process => true,
        _ => false,
    }
}

/// Whether [`pg_rules::surface_probe::probe_synthesize`] would REFUSE for ANY word synthesized in
/// this grammar — module doc, item 2. A purely STATIC, per-grammar fact (not per-word): the
/// underlying cascade (`pg_rules::rewrite::probe_synthesize_stratum`) refuses unconditionally the
/// moment it reaches an epenthesis-kind rewrite subrule (`RewriteRuleDef::lhs` empty — the DTD's
/// "empty `<PhoneticInput>`" convention for an insertion-only rule) or ANY `PhonRuleDef::
/// Metathesis`, regardless of whether that specific rule actually fires for the shape being probed
/// — checking every rule in `g.prules` (not just ones reachable from a given stratum) is therefore
/// a safe, conservative over-approximation of "could this ever refuse", cheap enough to run
/// unconditionally.
///
/// `pub(crate)` (widened from private, no body change): `crate::enumerate::enumerate_default`
/// mirrors this seam's decision structurally, and that module's own tests compare the enumerated
/// `Plan` against calling this REAL function directly — the correctness argument depends on both
/// sides calling the identical predicate, not a re-derivation of it.
pub(crate) fn probe_would_refuse(g: &Grammar) -> bool {
    g.prules.iter().any(|pr| match pr {
        PhonRuleDef::Metathesis(_) => true,
        PhonRuleDef::Rewrite(r) => r.lhs.nodes.is_empty(),
    })
}

/// Candidate rules for [`build_structural_composites`]: always [`is_structural_rule`]'s set;
/// ADDITIONALLY every ordinary `Prefix`/`Suffix`/`Infix` rule when [`probe_would_refuse`] (module
/// doc, item 2) — in that case `crate::preexpand` cannot represent them correctly either (its own
/// probe refuses for every candidate in the affected stratum), so this mechanism is their only
/// remaining path to a phonology-resolved surface. Excludes `CompoundingRule` (never a candidate
/// anywhere in this emitter's rule-application mechanisms).
///
/// `pub(crate)` (widened from private, no body change): see [`probe_would_refuse`]'s doc for why --
/// this is the other half of that same seam (`crate::enumerate::enumerate_default` calls this
/// directly to decide the structural-composite route's presence). [`plan_topology_decisions`]
/// (below) is what makes [`emit_with_budget_profiled`]'s own gate match this seam BY CONSTRUCTION
/// rather than by two independently-written call sites happening to agree.
pub(crate) fn structural_candidate_rules(g: &Grammar) -> Vec<MRuleId> {
    let broad = probe_would_refuse(g);
    (0..g.mrules.len() as u32)
        .map(MRuleId)
        .filter(|&mid| {
            if matches!(g.mrules[mid.0 as usize], MorphRuleDef::Compounding(_)) {
                return false;
            }
            is_structural_rule(g, mid)
                || (broad && matches!(rule_role(g, mid), Role::Prefix | Role::Suffix | Role::Infix))
        })
        .collect()
}

/// `true` iff `plan` contains a [`PlanNodeKind::Leaf`] whose [`FragmentSpec`] equals `fragment` --
/// the structural primitive [`plan_topology_decisions`] uses to read a topology decision back OFF
/// an already-built [`Plan`] instead of recomputing it. Both marker fragments this crate uses today
/// ([`FragmentSpec::CompositeEmissionMarker`]/[`FragmentSpec::StructuralCompositeMarker`]) are unit
/// variants, so equality here is a plain content comparison, not a partial/fuzzy match.
fn plan_has_leaf(plan: &Plan, fragment: &FragmentSpec) -> bool {
    plan.iter()
        .any(|(_, kind)| matches!(kind, PlanNodeKind::Leaf { fragment: f, .. } if f == fragment))
}

/// Builds `g`'s reified [`Plan`] ([`crate::enumerate::enumerate_default`]) and returns
/// [`emit_with_budget_profiled`]'s two topology decisions **derived from it** --
/// `(plan wants the composite-emission subtree, plan wants the structural-composite subtree)` --
/// rather than that function calling `crate::preexpand::should_run`/
/// `structural_candidate_rules(...).is_empty()` a second, independently-derived time. This is the
/// production flip: the pre-refactor behavior is preserved as a specific enumerable
/// plan --
/// [`crate::enumerate::enumerate_default`] is the ONE place these two seams are
/// consulted to decide topology; this function only ever READS the plan it built. (The third seam,
/// `gate::partition_entries`, belongs to `gate.rs`'s separate compile entry point, which this
/// mainline lexc-emission path never calls at all -- see [`emit_with_budget_profiled`]'s own doc.)
///
/// `prules_in_order`/`alphabet` mirror [`crate::capability_entry::evaluate_capability`]'s own
/// construction of these same `enumerate_default` inputs (that module's own doc: this crate's
/// mainline lexc-emission path doesn't build a `Replace` cascade at all, so `prules_in_order` isn't
/// already a local anywhere in `emit.rs` -- built the same way every other real construction site in
/// this crate does: `g`'s strata, in order, flattened over each stratum's own `phonologicalRules` id
/// list, as literal borrows of `g.prules`).
///
/// Cheap and side-effect-free: [`crate::enumerate::enumerate_default`] builds plan DATA only
/// (`crate::plan`'s own module doc: "no live `Fsm` is built here at all") -- calling it here does
/// not build or compose any real FST, just the same handful of `Vec`/`HashMap` grammar-data scans
/// `should_run`/`structural_candidate_rules`/`find_gated_subrules`/`partition_entries` already
/// perform on their own.
pub(crate) fn plan_topology_decisions(g: &Grammar, phon: Option<&PhonologyProbe>) -> (bool, bool) {
    let prules_in_order: Vec<&PhonRuleDef> = g
        .strata
        .iter()
        .flat_map(|s| &s.prules)
        .map(|&id| &g.prules[id.0 as usize])
        .collect();
    let alphabet = SegAlphabet::new(surface_table(g));
    let plan = enumerate_default(g, &alphabet, &prules_in_order, phon);
    let wants_composite_emission = plan_has_leaf(&plan, &FragmentSpec::CompositeEmissionMarker);
    let wants_structural_composite = plan_has_leaf(&plan, &FragmentSpec::StructuralCompositeMarker);
    (wants_composite_emission, wants_structural_composite)
}

/// Stack size [`probe_surface`] runs on (module doc below): generous enough that a deep
/// feature-struct-unification/rewrite-rule recursion over a large char-def table (Amharic: 418
/// `<SegmentDefinition>`s) never overflows a caller's default thread stack (Windows test-harness
/// threads default to a few MiB — empirically NOT enough headroom for `pg_rules::surface_probe::
/// probe_synthesize` run against a bare-root shape on Amharic-scale grammars, found by this gate's
/// own `f3_amharic_gate` regression run once bare-root probing was added).
/// `pub(crate)`: [`crate::junctions::PhonologyProbe`]'s own rayon worker pool reuses this exact
/// value (its recursion through the same `probe_synthesize` machinery has the identical overflow
/// risk) rather than a second, driftable copy of the constant.
#[cfg(not(target_arch = "wasm32"))]
pub(crate) const PROBE_STACK_BYTES: usize = 64 * 1024 * 1024;

/// The real, phonology-resolved surface of `shape` via the cheap build-time probe —
/// [`pg_rules::surface_probe::probe_synthesize`] + [`pg_rules::surface_probe::render_nodes`] — when
/// it doesn't refuse; `None` when it does ([`probe_would_refuse`]'s per-shape counterpart), or when
/// the rendered surface is empty (nothing useful to add). The caller falls back to
/// [`Morpher::generate_words`] in that case.
///
/// Runs on a dedicated scoped thread with a large, explicit stack ([`PROBE_STACK_BYTES`]) rather
/// than directly on the caller's own stack: `pg_rules`'s rewrite-rule recursion depth scales with
/// the grammar's own char-def table / phonological rule set, not with anything this emitter
/// controls, and this crate cannot edit `pg_rules` to bound it there — a stack overflow aborts the
/// whole process (not catchable), so borrowing a known-generous stack for this one call is the only
/// contained fix available at this crate's own layer. `std::thread::scope` (not a detached
/// `thread::spawn`) lets the closure borrow `g`/`table`/`shape`/`cache` directly, no cloning needed;
/// the spawn/join overhead (microseconds) is negligible next to the probe's own cascade cost.
fn probe_surface(
    g: &Grammar,
    table: &CharDefTable,
    shape: &Shape,
    cache: &RuleCache,
) -> Option<String> {
    // wasm32-unknown-unknown has no thread support — `std::thread::Builder::spawn_scoped` panics
    // there ("operation not supported on this platform"), which would crash `PanGlossGrammar::new`
    // (pg-wasm) at construction, exactly like the vendored foma `apply_init` wasm fix. Run the
    // probe inline on wasm instead: the large-stack rationale below cannot apply (no thread to give
    // a stack to), and the wasm linear-memory stack is sized at link time — the reference grammars'
    // probe depth fits the default, and a genuinely deeper grammar would need a link-time
    // `-C link-arg=-zstack-size=…` bump, not a thread this target can't spawn.
    #[cfg(target_arch = "wasm32")]
    {
        let segs = pg_rules::surface_probe::probe_synthesize(g, shape, cache)?;
        return pg_rules::surface_probe::render_nodes(table, &segs).filter(|s| !s.is_empty());
    }
    #[cfg(not(target_arch = "wasm32"))]
    std::thread::scope(|scope| {
        std::thread::Builder::new()
            .stack_size(PROBE_STACK_BYTES)
            .spawn_scoped(scope, || {
                let segs = pg_rules::surface_probe::probe_synthesize(g, shape, cache)?;
                pg_rules::surface_probe::render_nodes(table, &segs).filter(|s| !s.is_empty())
            })
            .expect("spawning the probe thread")
            .join()
            .unwrap_or(None)
    })
}

/// Every `BoundaryDefinition` representation (NFD) in `table` — e.g. `metathesis-phase-isolation`'s "+".
/// Empty for a grammar with no boundary definitions (the common case), where boundary-insertion
/// ([`with_boundary_insertions`]) is a pure no-op.
fn boundary_reps(table: &CharDefTable) -> Vec<String> {
    let mut out = Vec::new();
    for (_, cd) in table.iter() {
        if cd.kind() == CharDefKind::Boundary {
            for r in cd.representations_nfd() {
                if !r.is_empty() && !out.contains(r) {
                    out.push(r.clone());
                }
            }
        }
    }
    out
}

/// `surface` plus every SINGLE-boundary-insertion variant (each rep in `bnd_reps` at each interior
/// character gap; `metathesis-phase-isolation`'s "mu+i"): a `MetathesisRule` can leave a
/// boundary character INSIDE the surface word (`mi` + suffix `+u` --metathesis--> `mu+i`), but the
/// only mechanism that renders a metathesized surface at all — [`Morpher::generate_words`] — strips
/// every boundary (`include_boundaries = false`, `pg_parse::surface::to_plain_string`'s only
/// generation call site), so its output "mui" can never match the boundary-bearing query "mu+i".
/// The shape (which WOULD carry the boundary at its true position) is not exposed by
/// `generate_words`' string-only API and `probe_surface` refuses on metathesis, so the exact
/// position is unrecoverable at this layer — enumerate every interior insertion instead: bounded
/// (one boundary, `bnd_reps.len() * (n-1)` extra strings for an n-char surface), upward-only
/// (`crate::confirm` prunes; a spurious "m+ui" is simply never the query and matches nothing). A
/// no-op when `bnd_reps` is empty (every grammar with no boundary definitions).
fn with_boundary_insertions(surface: &str, bnd_reps: &[String]) -> Vec<String> {
    let mut out = vec![surface.to_string()];
    if bnd_reps.is_empty() {
        return out;
    }
    let chars: Vec<char> = surface.chars().collect();
    for pos in 1..chars.len() {
        let head: String = chars[..pos].iter().collect();
        let tail: String = chars[pos..].iter().collect();
        for rep in bnd_reps {
            out.push(format!("{head}{rep}{tail}"));
        }
    }
    out
}

/// [`pg_rules::morph::synthesize`]'s `Word` carries `morphs` (each applied allomorph, with an
/// `order` field reflecting ascending SURFACE position — module doc's "Tag tape convention"; this
/// is what makes the resulting `tag_lexc` line up with `pg_parse::Morpher`'s own
/// `allomorphs_in_morph_order`, which `crate::confirm`'s positional `analyses_match` compares
/// against). Re-derived here from `crate::preexpand::morph_order_tags` (private to that file, which
/// this emitter's owning scope may not edit): sort by `order`, keep the first occurrence of each
/// distinct allomorph, join each survivor's pre-computed tag string from `known` (the root at index
/// 0, each applied rule appended in application order).
fn struct_morph_order_tags(w: &Word, known: &[(MorphemeId, String)]) -> Option<String> {
    let mut ms = w.morphs.clone();
    ms.sort_by_key(|m| m.order);
    let mut seen: Vec<AllomorphId> = Vec::new();
    let mut out = String::new();
    for m in ms {
        if seen.contains(&m.allomorph) {
            continue;
        }
        seen.push(m.allomorph);
        match known.iter().find(|(mid, _)| *mid == m.morpheme) {
            Some((_, tag)) => out.push_str(tag),
            None => return None,
        }
    }
    if out.is_empty() {
        None
    } else {
        Some(out)
    }
}

/// One in-progress structural-composite chain's shared, read-only context, threaded through
/// [`struct_extend`]'s recursion (mirrors `crate::preexpand::ExtendCtx`, re-derived here for the
/// same "can't edit preexpand.rs" reason [`struct_morph_order_tags`] is).
struct StructCtx<'a> {
    g: &'a Grammar,
    root_table: &'a CharDefTable,
    root_entry: LexEntryId,
    rules: &'a [MRuleId],
    cache: &'a RuleCache,
    morpher: &'a Morpher<'a>,
    /// Boundary representations for [`with_boundary_insertions`] (gate F3 3b, "mu+i") — applied only
    /// to `generate_words`-fallback surfaces, where a metathesis may have moved a boundary into the
    /// surface word. Empty for a grammar with no boundary definitions.
    boundary_reps: &'a [String],
    /// Morphotactic pruning (`crate::morphotactics`, mirrors `crate::preexpand::ExtendCtx`'s own
    /// fields for the same "can't edit preexpand.rs" reason): the automaton [`struct_extend`]
    /// consults before recursing, its flat/pruned escape hatch, and the shared
    /// `HC_PREEXPAND_PROBE_CAP` safety valve.
    mt: &'a MorphotacticIndex,
    mode: ExploreMode,
    probe_budget: Option<ProbeBudget<'a>>,
    /// Default-ON fail-fast enumeration budget (mirrors `crate::preexpand::ExtendCtx`'s own field,
    /// same "can't edit preexpand.rs" reason [`struct_morph_order_tags`] is re-derived here rather
    /// than shared) -- `crate::morphotactics::EnumerationBudget`'s own doc, Fix 1.
    enum_budget: &'a EnumerationBudget,
}

/// [`struct_extend`]'s output accumulator: the composite records plus a `(tag_lexc, spelling)`
/// dedup set (mirrors `crate::preexpand::Acc`).
struct StructAcc {
    recs: Vec<crate::preexpand::CompositeRec>,
    seen: rustc_hash::FxHashSet<(String, String)>,
    /// `g.mrules` indices that produced at least one composite entry here — mirrors
    /// `crate::preexpand::CompositeReport::covered_infix_rules`'s "IS representable now, drop its
    /// uncovered items" convention, generalized to every role this mechanism can cover (not just
    /// Infix): `Role::CircumfixPrefix` (module doc) is the one that actually needs it (`Role::None`/
    /// `Prefix`/`Suffix` are never pushed to `uncovered` in the first place — `build_deriv_chain`
    /// already accepts them in some zone).
    covered_rules: BTreeSet<u32>,
}

/// Try extending `base_word` (already carrying `chain`'s tags) with every remaining candidate rule;
/// recurse up to [`STRUCT_MAX_EXTRA_RULES`]. Mirrors `crate::preexpand::extend`'s shape (module doc)
/// but always emits (no `reachable_via_ordinary_emission` redundancy check — that optimization
/// exists to keep composite COUNTS down on a grammar `crate::preexpand` otherwise emits correctly
/// for; here, by construction, every candidate rule is one the ordinary two-entry path CANNOT
/// represent correctly at all, so there is no "already reachable" baseline to compare against).
#[allow(clippy::too_many_arguments)]
fn struct_extend(
    ctx: &StructCtx,
    base_word: &Word,
    chain: &[(MorphemeId, String)],
    rule_chain: &[MRuleId],
    depth: usize,
    width: usize,
    state: &ChainState,
    acc: &mut StructAcc,
) {
    if depth >= STRUCT_MAX_EXTRA_RULES {
        return;
    }
    // Fail-fast enumeration budget (Fix 1): same "check once at the top, bail early" shape as
    // `crate::preexpand::extend`'s own guard -- see `crate::morphotactics::EnumerationBudget`'s doc.
    if ctx.enum_budget.is_tripped() {
        return;
    }
    let base_fs = base_word.syn_fs.clone();
    for &mid in ctx.rules {
        let rule = &ctx.g.mrules[mid.0 as usize];
        let (req, rule_morpheme) = match rule {
            MorphRuleDef::AffixProcess(def) => (def.required_syn_fs, def.morpheme),
            MorphRuleDef::Realizational(def) => (def.required_syn_fs, def.morpheme),
            MorphRuleDef::Compounding(_) => continue,
        };
        // A rule already in this chain cannot apply again in the SAME composite (every reference/
        // edge-case grammar's rules default `multipleApplication = 1` — same guard preexpand.rs's
        // own `extend` uses).
        if chain.iter().any(|(m, _)| *m == rule_morpheme) {
            continue;
        }
        // Morphotactic pruning (`crate::morphotactics`, mirrors `crate::preexpand::extend`'s own
        // insertion point exactly -- module doc there): sits BEFORE the FS pre-filter below, a pure
        // subset restriction over the same automaton `crate::preexpand::extend` consults.
        let Some(next_state) = (match ctx.mode {
            ExploreMode::Flat => Some(state.clone()),
            ExploreMode::Pruned => ctx.mt.next_state(state, mid, &base_fs, &ctx.g.fs_interner),
        }) else {
            continue;
        };
        let req_fs = ctx.g.fs_interner.get(req);
        if !req_fs.is_empty() && !is_unifiable(req_fs, &base_fs) {
            continue;
        }
        if let Some(budget) = &ctx.probe_budget {
            budget.tick();
        }
        ctx.enum_budget.tick_probe();

        let mut next_rule_chain = rule_chain.to_vec();
        next_rule_chain.push(mid);

        for w in pg_rules::morph::synthesize(ctx.g, base_word, rule) {
            let mut next_chain = chain.to_vec();
            next_chain.push((rule_morpheme, tags::morph_tag_lexc(rule_morpheme, width)));
            let Some(tag_lexc) = struct_morph_order_tags(&w, &next_chain) else {
                struct_extend(
                    ctx,
                    &w,
                    &next_chain,
                    &next_rule_chain,
                    depth + 1,
                    width,
                    &next_state,
                    acc,
                );
                continue;
            };

            let surfaces: Vec<String> =
                match probe_surface(ctx.g, ctx.root_table, &w.shape, ctx.cache) {
                    Some(s) => vec![s],
                    None => {
                        // Probe refused (module doc, item 2) -- fall back to the real generation
                        // pipeline for the WHOLE chain applied so far. `generate_words` may return more
                        // than one surface when the chain's own LHS matching is genuinely ambiguous
                        // (`mruleTruncOptIns` on a root beginning with its own optional segment: "sas"
                        // admits BOTH "gas" and "gsas" as legitimate parses) -- every one is upward-safe
                        // to pair with THIS `w`'s own tag order (cross-product, upward-only).
                        // Boundary-insertion (module doc, [`with_boundary_insertions`]): a metathesis in
                        // this chain may have left a boundary char inside the surface (mu+i) that
                        // `generate_words` stripped — a no-op when the grammar has no boundary defs.
                        let others: Vec<GenMorpheme> = next_rule_chain
                            .iter()
                            .map(|&m| GenMorpheme::Rule(m))
                            .collect();
                        ctx.morpher
                            .generate_words(ctx.root_entry, &others, FeatureStruct::EMPTY)
                            .iter()
                            .flat_map(|s| with_boundary_insertions(s, ctx.boundary_reps))
                            .collect()
                    }
                };

            for s in &surfaces {
                if s.is_empty() {
                    continue;
                }
                acc.covered_rules.insert(mid.0);
                if acc.seen.insert((tag_lexc.clone(), s.clone())) {
                    acc.recs.push(crate::preexpand::CompositeRec {
                        morpheme: next_chain[0].0,
                        chain_morphemes: next_chain
                            .iter()
                            .enumerate()
                            .map(|(i, (m, _))| (i == 0, *m))
                            .collect(),
                        tag_lexc: tag_lexc.clone(),
                        variants: vec![s.clone()],
                    });
                    // Fail-fast enumeration budget: one structural composite entry recorded
                    // (`crate::morphotactics::EnumerationBudget`'s doc -- same measure
                    // `crate::preexpand::extend`'s fusion/interdigitation entries feed).
                    ctx.enum_budget.add_entries(1);
                }
            }

            struct_extend(
                ctx,
                &w,
                &next_chain,
                &next_rule_chain,
                depth + 1,
                width,
                &next_state,
                acc,
            );
        }
    }
}

/// Build every structural composite (module doc) for `g`. `width` mirrors
/// `crate::preexpand::build_composites`'s own parameter; `rules`/`cache`/`morpher` are built ONCE by
/// the caller ([`emit`]) and threaded through so this and the bare-root phonology enrichment in
/// [`collect_roots`] never construct a second, redundant [`RuleCache`]/[`Morpher`] for the same
/// grammar. Returns immediately (no-op) when `rules` is empty. The second return value is every
/// rule id ([`StructAcc::covered_rules`]) that produced at least one composite entry — `emit` uses
/// it to drop that rule's now-stale `uncovered` items (mirrors `crate::preexpand`'s own
/// `covered_infix_rules` convention). `mt`/`mode`/`probe_budget` are the SAME morphotactic-pruning
/// automaton, escape hatch, and probe-cap budget `crate::preexpand::build_composites_with_mode`
/// uses — `crate::emit::emit_with_precision` builds `mt`/`probe_budget` once and shares them across
/// both composite builders (module doc addendum on `crate::preexpand`).
#[allow(clippy::too_many_arguments)]
fn build_structural_composites(
    g: &Grammar,
    width: usize,
    rules: &[MRuleId],
    cache: &RuleCache,
    morpher: &Morpher,
    mt: &MorphotacticIndex,
    mode: ExploreMode,
    probe_budget: Option<ProbeBudget<'_>>,
    enum_budget: &EnumerationBudget,
) -> (Vec<crate::preexpand::CompositeRec>, BTreeSet<u32>) {
    if rules.is_empty() {
        return (Vec::new(), BTreeSet::new());
    }
    let mut acc = StructAcc {
        recs: Vec::new(),
        seen: rustc_hash::FxHashSet::default(),
        covered_rules: BTreeSet::new(),
    };
    // Boundary reps for the metathesis/boundary-in-surface case (gate F3 3b, "mu+i"); computed from
    // the surface stratum's table once (every stratum shares one table in the reference grammars).
    let bnd_reps = boundary_reps(surface_table(g));

    for sd in &g.strata {
        for &entry_id in &sd.entries {
            let entry = &g.entries[entry_id.0 as usize];
            let root_stratum = g.morphemes[entry.morpheme.0 as usize].stratum;
            let root_table = &g.char_tables[g.strata[root_stratum.0 as usize].table.0 as usize];
            let entry_fs = g.fs_interner.get(entry.syn_fs);

            for allo in &entry.allomorphs {
                if allo.is_pattern {
                    continue;
                }
                let Ok(shape) =
                    pg_rules::shape_feat::segment_with_features(g, root_table, &allo.shape.text)
                else {
                    continue;
                };
                let mut word = Word::new(shape, root_stratum);
                word.syn_fs = entry_fs.clone();
                word.mpr = entry.mpr;
                word.root_allomorph = Some(allo.id);
                word.morphs = vec![MorphRecord::new(allo.id, entry.morpheme, 0)];

                let root_tag = tags::root_tag_lexc(entry.morpheme, width);
                let chain0 = vec![(entry.morpheme, root_tag)];
                let ctx = StructCtx {
                    g,
                    root_table,
                    root_entry: entry_id,
                    rules,
                    cache,
                    morpher,
                    boundary_reps: &bnd_reps,
                    mt,
                    mode,
                    probe_budget,
                    enum_budget,
                };
                // Morphotactic pruning (module doc addendum): seed the same way
                // `crate::preexpand::process_root_work` does (root's own stratum, disabled template
                // entry iff `entry.partial` — engine fact 5).
                let seed_state = ChainState::seed(g, root_stratum.0, entry.partial);
                struct_extend(&ctx, &word, &chain0, &[], 0, width, &seed_state, &mut acc);
            }
        }
    }
    (acc.recs, acc.covered_rules)
}

