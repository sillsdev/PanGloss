#!/usr/bin/env python3
"""Generate crates/pg-foma-runtime/src/cascade/casefold_table.rs (fst-2 cascade backend, plan S.2 `Fold`).

Stdlib only. Emits every code point `ch` (surrogates excluded) with `ch.casefold() != ch`, i.e. Unicode full case
folding (CaseFolding.txt statuses C and F) as implemented by this Python. CaseFolding.txt itself is not copied.

  python3 -I rust/tools/cascade/gen_casefold_table.py > rust/crates/pg-foma-runtime/src/cascade/casefold_table.rs

The table must be regenerated with a Python whose `unicodedata.unidata_version` equals the Unicode version of the
`unicode-normalization` crate (unicode_normalization::UNICODE_VERSION), because NFD and the fold are used together.
"""
import sys
import unicodedata as ud

def main():
    rows = []
    for cp in range(0x110000):
        if 0xD800 <= cp < 0xE000:
            continue
        c = chr(cp)
        f = c.casefold()
        if f != c:
            rows.append((cp, f))
    out = sys.stdout
    out.write("//! @generated by rust/tools/cascade/gen_casefold_table.py; do not edit.\n")
    out.write(f"//! Python {sys.version.split()[0]}, unicodedata.unidata_version = {ud.unidata_version}.\n")
    out.write("//! Every code point with `ch.casefold() != ch`: full case folding, CaseFolding.txt statuses C and F.\n")
    out.write("//! The table must match the Unicode version of the unicode-normalization crate.\n\n")
    out.write(f'pub const UNIDATA_VERSION: &str = "{ud.unidata_version}";\n')
    out.write(f'pub const GENERATOR_PYTHON: &str = "{sys.version.split()[0]}";\n\n')
    out.write("/// Sorted by code point.\n")
    out.write("pub static CASEFOLD: &[(u32, &str)] = &[\n")
    for cp, f in rows:
        esc = "".join(f"\\u{{{ord(x):X}}}" for x in f)
        out.write(f'    (0x{cp:X}, "{esc}"),\n')
    out.write("];\n")

if __name__ == "__main__":
    main()
